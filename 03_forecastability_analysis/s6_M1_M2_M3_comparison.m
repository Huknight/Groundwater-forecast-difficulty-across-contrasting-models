function T = ...
    buildPixelLossGainSummary( ...
    Ylog, ...
    PredictionLog, ...
    PixelYearRowMap, ...
    outerTestYears, ...
    modelNames, ...
    variantNames, ...
    comparisonNames, ...
    referenceVariant, ...
    candidateVariant)


    nYear = ...
        numel(outerTestYears);


    nModel = ...
        numel(modelNames);


    nComparison = ...
        numel(comparisonNames);


    nRows = ...
        nYear * ...
        nModel * ...
        nComparison;


    TestYear = NaN(nRows,1);
    TargetModel = cell(nRows,1);
    Comparison = cell(nRows,1);

    ReferenceVariant = cell(nRows,1);
    CandidateVariant = cell(nRows,1);

    MeanSEGain = NaN(nRows,1);
    MedianSEGain = NaN(nRows,1);

    Q25_SEGain = NaN(nRows,1);
    Q75_SEGain = NaN(nRows,1);

    FractionCandidateLowerSE = NaN(nRows,1);
    FractionCandidateLowerAE = NaN(nRows,1);


    counter = ...
        0;


    for iy = 1:nYear


        rows = ...
            PixelYearRowMap(:,iy);


        for m = 1:nModel


            obs = ...
                Ylog(rows,m);


            for ic = 1:nComparison


                counter = ...
                    counter + ...
                    1;


                refV = ...
                    referenceVariant(ic);


                candV = ...
                    candidateVariant(ic);


                refError = ...
                    PredictionLog{refV}(rows,m) - ...
                    obs;


                candError = ...
                    PredictionLog{candV}(rows,m) - ...
                    obs;


                refSE = ...
                    refError .^ 2;


                candSE = ...
                    candError .^ 2;


                gain = ...
                    refSE - ...
                    candSE;


                TestYear(counter) = ...
                    outerTestYears(iy);


                TargetModel{counter} = ...
                    modelNames{m};


                Comparison{counter} = ...
                    comparisonNames{ic};


                ReferenceVariant{counter} = ...
                    variantNames{refV};


                CandidateVariant{counter} = ...
                    variantNames{candV};


                MeanSEGain(counter) = ...
                    mean(gain);


                MedianSEGain(counter) = ...
                    median(gain);


                Q25_SEGain(counter) = ...
                    prctile( ...
                    gain, ...
                    25);


                Q75_SEGain(counter) = ...
                    prctile( ...
                    gain, ...
                    75);


                FractionCandidateLowerSE(counter) = ...
                    mean( ...
                    candSE < ...
                    refSE);


                FractionCandidateLowerAE(counter) = ...
                    mean( ...
                    abs(candError) < ...
                    abs(refError));

            end

