%% s6_M1_M2_M3_comparison.m
%
% ============================================================
% FORMAL COMPARISON OF M1 / M2 / M3 FORECASTABILITY MODELS
% ============================================================
%
% M1:
%   dGWS-only
%   13 predictors
%
% M2:
%   hydroclimate-only
%   24 predictors
%
% M3:
%   dGWS + hydroclimate
%   37 predictors
%
%
% ============================================================
% PRIMARY SCIENTIFIC QUESTIONS
% ============================================================
%
% M3 vs M1:
%
%   Does hydroclimatic information provide incremental
%   forecastability information beyond intrinsic dGWS
%   temporal characteristics?
%
%
% M3 vs M2:
%
%   Do intrinsic dGWS characteristics provide incremental
%   information beyond hydroclimatic context?
%
%
% M2 vs M1:
%
%   Descriptive comparison of the two information domains.
%
%
% ============================================================
% OUTER TEST DATA ONLY
% ============================================================
%
% 2022:
%   trained on 2019-2021
%
% 2023:
%   trained on 2019-2022
%
% 2024:
%   trained on 2019-2023
%
%
% Each test year contains:
%
%   17,284 independent pixels
%
% Nine forecast-performance targets:
%
%   AR
%   ARIMA
%   SARIMA
%   SVM
%   RF
%   LSTM
%   SVMX
%   RFX
%   LSTMX
%
%
% ============================================================
% PRIMARY PERFORMANCE SCALE
% ============================================================
%
% log target:
%
%   log1p(NRMSE_Q10Q90)
%
% Metrics:
%
%   R2
%   RMSE
%   MAE
%   Spearman
%
%
% Secondary descriptive scale:
%
%   original NRMSE_Q10Q90
%
%
% ============================================================
% DIFFERENCE CONVENTION
% ============================================================
%
% For Candidate vs Reference:
%
%   DeltaRMSE =
%       RMSE_Candidate - RMSE_Reference
%
% Therefore:
%
%   DeltaRMSE < 0
%       Candidate is better
%
%
% Relative improvement:
%
%   100 * (RMSE_Reference - RMSE_Candidate)
%       / RMSE_Reference
%
% Therefore:
%
%   Improvement > 0
%       Candidate is better
%
%
% For skill metrics:
%
%   DeltaR2 =
%       R2_Candidate - R2_Reference
%
%   DeltaSpearman =
%       rho_Candidate - rho_Reference
%
% Positive:
%
%   Candidate is better
%
%
% ============================================================
% PAIRED PIXEL BOOTSTRAP
% ============================================================
%
% Primary inferential statistic:
%
%   Delta RMSE_log
%
% Secondary:
%
%   Delta MAE_log
%
%
% Year-specific:
%
%   resample the 17,284 test pixels with replacement.
%
%
% Pooled 2022-2024:
%
%   pixel-cluster bootstrap.
%
% If one pixel is sampled, ALL THREE test years belonging to
% that pixel enter the bootstrap replicate together.
%
%
% IMPORTANT:
%
% The same bootstrap pixel sample is simultaneously applied
% to all nine forecasting-model targets.
%
% Therefore:
%
%   the nine target models are NOT treated as nine independent
%   statistical replicates.
%
% They are treated as the fixed set of forecast configurations
% studied in this experiment.
%
%
% ============================================================
% BOOTSTRAP COMPARISONS
% ============================================================
%
% Primary:
%
%   M3 vs M1
%
% Secondary:
%
%   M3 vs M2
%
% M2 vs M1 remains descriptive by default.
%
%
% ============================================================
% OUTPUTS
% ============================================================
%
% 01_ModelYear_Performance.csv
%
%   81 rows:
%       3 years x 9 targets x 3 variants
%
%
% 02_ModelYear_Deltas_AllPairs.csv
%
%   81 rows:
%       3 years x 9 targets x 3 comparisons
%
%
% 03_Aggregate_ByYear.csv
%
% 04_Aggregate_ByTarget.csv
%
% 05_Overall_Aggregate.csv
%
%
% 06_Bootstrap_ModelYear.csv
%
%   paired bootstrap for each:
%
%       year x target x comparison
%
%
% 07_Bootstrap_PooledByTarget.csv
%
%   each target pooled across 2022-2024,
%   clustering by pixel.
%
%
% 08_Bootstrap_AggregateByYear.csv
%
%   mean RMSE difference across the nine fixed targets
%   for each year.
%
%
% 09_Bootstrap_Overall.csv
%
%   mean target-wise RMSE difference across
%   2022-2024 and all nine targets.
%
%
% 10_PixelLevel_LogLoss_Gain.csv
%
%   descriptive pixel-level gain summaries.
%
%
