function verifyResultAlignment( ...
    R, ...
    variantName, ...
    pixelID, ...
    forecastYear, ...
    lat, ...
    lon, ...
    Yraw, ...
    Ylog, ...
    modelNames, ...
    outerTestYears)


    requiredFields = { ...
        'completed', ...
        'prediction_log', ...
        'prediction_raw', ...
        'pixel_id', ...
        'forecast_year', ...
        'lat', ...
        'lon', ...
        'model_names'};


    for i = 1:numel(requiredFields)


        if ~isfield(R,requiredFields{i})

            error( ...
                '%s missing field: %s', ...
                variantName, ...
                requiredFields{i});

        end

    end


    if ~all(R.completed(:))

        error( ...
            '%s does not have all model-years completed.', ...
            variantName);

    end


    if ~isequal( ...
            double(R.pixel_id(:)), ...
            pixelID)

        error( ...
            '%s pixel_id mismatch.', ...
            variantName);

    end


    if ~isequal( ...
            double(R.forecast_year(:)), ...
            forecastYear)

        error( ...
            '%s forecast_year mismatch.', ...
            variantName);

    end


    tolerance = ...
        1e-10;


    if any( ...
            abs( ...
            double(R.lat(:)) - ...
            lat) > ...
            tolerance)

        error( ...
            '%s latitude mismatch.', ...
            variantName);

    end


    if any( ...
            abs( ...
            double(R.lon(:)) - ...
            lon) > ...
            tolerance)

        error( ...
            '%s longitude mismatch.', ...
            variantName);

    end


    resultModelNames = ...
        cellstr( ...
        string( ...
        R.model_names(:)));


    resultModelNames = ...
        resultModelNames';


    if ~isequal( ...
            resultModelNames, ...
            modelNames)

        error( ...
            '%s target-model order mismatch.', ...
            variantName);

    end


    if isfield(R,'observed_raw')


        maxRawDifference = ...
            max( ...
            abs( ...
            double(R.observed_raw(:)) - ...
            Yraw(:)));


        if maxRawDifference > 1e-12

            error( ...
                '%s observed_raw differs from Master.', ...
                variantName);

        end

    end


    if isfield(R,'observed_log')


        maxLogDifference = ...
            max( ...
            abs( ...
            double(R.observed_log(:)) - ...
            Ylog(:)));


        if maxLogDifference > 1e-12

            error( ...
                '%s observed_log differs from Master.', ...
                variantName);

        end

    end


    if isfield(R,'outer_test_years')


        if ~isequal( ...
                double(R.outer_test_years(:))', ...
                double(outerTestYears(:))')

            error( ...
                '%s outer test years differ.', ...
                variantName);

        end

    end


end


function M = ...
    regressionMetrics( ...
    observed, ...
    predicted)


    observed = ...
        double(observed(:));


    predicted = ...
        double(predicted(:));


    valid = ...
        isfinite(observed) & ...
        isfinite(predicted);


    observed = ...
        observed(valid);


    predicted = ...
        predicted(valid);


    if isempty(observed)

        M.R2 = NaN;
        M.RMSE = NaN;
        M.MAE = NaN;
        M.Spearman = NaN;

        return

    end


    errorVector = ...
        predicted - ...
        observed;


    M.RMSE = ...
        sqrt( ...
        mean( ...
        errorVector .^ 2));


    M.MAE = ...
        mean( ...
        abs(errorVector));


    denominator = ...
        sum( ...
        ( ...
        observed - ...
        mean(observed) ...
        ) .^ 2);


    if denominator > 0


        M.R2 = ...
            1 - ...
            sum( ...
            errorVector .^ 2) / ...
            denominator;


    else


        M.R2 = ...
            NaN;

    end


    if numel(observed) >= 3 && ...
            std(observed) > 0 && ...
            std(predicted) > 0


        M.Spearman = ...
            corr( ...
            observed, ...
            predicted, ...
            'Type', ...
            'Spearman', ...
            'Rows', ...
            'complete');


    else


        M.Spearman = ...
            NaN;

    end


end


