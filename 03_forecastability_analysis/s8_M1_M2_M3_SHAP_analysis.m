function [ ...
    FeatureTable, ...
    DomainTable, ...
    MechanismTable, ...
    HydroVariableTable] = ...
    summarizeSHAPCase( ...
    SHAPValues, ...
    cfg, ...
    testYear, ...
    targetModel)


    nFeature = ...
        size(SHAPValues,2);


    if nFeature ~= ...
            numel(cfg.FeatureNames)

        error( ...
            'Feature definition mismatch.');

    end


    %% ========================================================
    % FEATURE IMPORTANCE
    % ========================================================

    meanAbsFeature = ...
        mean( ...
        abs(SHAPValues), ...
        1)';


    totalImportance = ...
        sum( ...
        meanAbsFeature);


    totalShare = ...
        meanAbsFeature / ...
        totalImportance;


    meanSignedFeature = ...
        mean( ...
        SHAPValues, ...
        1)';


    medianSignedFeature = ...
        median( ...
        SHAPValues, ...
        1)';


    q25SignedFeature = ...
        prctile( ...
        SHAPValues, ...
        25, ...
        1)';


    q75SignedFeature = ...
        prctile( ...
        SHAPValues, ...
        75, ...
        1)';


    %% ========================================================
    % DOMAIN IMPORTANCE
    % ========================================================

    nDomain = ...
        numel(cfg.DomainNames);


    domainImportance = ...
        zeros(nDomain,1);


    domainSigned = ...
        zeros( ...
        size(SHAPValues,1), ...
        nDomain);


    for d = 1:nDomain


        idx = ...
            cfg.DomainID == ...
            d;


        domainImportance(d) = ...
            sum( ...
            meanAbsFeature(idx));


        domainSigned(:,d) = ...
            sum( ...
            SHAPValues(:,idx), ...
            2);

    end


    domainTotalShare = ...
        domainImportance / ...
        totalImportance;


    withinDomainFeatureShare = ...
        NaN(nFeature,1);


    for j = 1:nFeature


        d = ...
            cfg.DomainID(j);


        withinDomainFeatureShare(j) = ...
            meanAbsFeature(j) / ...
            domainImportance(d);

    end


    %% ========================================================
    % FEATURE METADATA
    % ========================================================

    featureDomain = ...
        cell(nFeature,1);


    featureMechanismGroup = ...
        cell(nFeature,1);


    featureMechanismClass = ...
        cell(nFeature,1);


    featureHydroVariable = ...
        cell(nFeature,1);


    for j = 1:nFeature


        d = ...
            cfg.DomainID(j);


        g = ...
            cfg.MechanismID(j);


        featureDomain{j} = ...
            cfg.DomainNames{d};


        featureMechanismGroup{j} = ...
            cfg.MechanismGroupNames{g};


        featureMechanismClass{j} = ...
            cfg.MechanismClassNames{g};


        hv = ...
            cfg.HydroVariableID(j);


        if hv > 0

            featureHydroVariable{j} = ...
                cfg.HydroVariableNames{hv};

        else

            featureHydroVariable{j} = ...
                'dGWS';

        end

    end


    FeatureTable = ...
        table( ...
        repmat({cfg.Name},nFeature,1), ...
        repmat(testYear,nFeature,1), ...
        repmat({targetModel},nFeature,1), ...
        cfg.FeatureNames(:), ...
        featureDomain, ...
        featureMechanismGroup, ...
        featureMechanismClass, ...
        featureHydroVariable, ...
        meanAbsFeature, ...
        totalShare, ...
        withinDomainFeatureShare, ...
        meanSignedFeature, ...
        medianSignedFeature, ...
        q25SignedFeature, ...
        q75SignedFeature, ...
        'VariableNames', { ...
        'Variant', ...
        'TestYear', ...
        'TargetModel', ...
        'FeatureName', ...
        'Domain', ...
        'MechanismGroup', ...
        'MechanismClass', ...
        'HydroVariable', ...
        'MeanAbsSHAP', ...
        'TotalShare', ...
        'WithinDomainShare', ...
        'MeanSignedSHAP', ...
        'MedianSignedSHAP', ...
        'Q25SignedSHAP', ...
        'Q75SignedSHAP'});


    %% ========================================================
    % DOMAIN TABLE
    % ========================================================

    domainMeanSigned = ...
        mean( ...
        domainSigned, ...
        1)';


    domainMedianSigned = ...
        median( ...
        domainSigned, ...
        1)';


    domainQ25Signed = ...
        prctile( ...
        domainSigned, ...
        25, ...
        1)';


    domainQ75Signed = ...
        prctile( ...
        domainSigned, ...
        75, ...
        1)';


    domainFeatureCount = ...
        zeros(nDomain,1);


    domainImportancePerFeature = ...
        zeros(nDomain,1);


    for d = 1:nDomain


        domainFeatureCount(d) = ...
            sum( ...
            cfg.DomainID == ...
            d);


        domainImportancePerFeature(d) = ...
            domainImportance(d) / ...
            domainFeatureCount(d);

    end


    DomainTable = ...
        table( ...
        repmat({cfg.Name},nDomain,1), ...
        repmat(testYear,nDomain,1), ...
        repmat({targetModel},nDomain,1), ...
        cfg.DomainNames(:), ...
        domainFeatureCount, ...
        domainImportance, ...
        domainTotalShare, ...
        domainImportancePerFeature, ...
        domainMeanSigned, ...
        domainMedianSigned, ...
        domainQ25Signed, ...
        domainQ75Signed, ...
        'VariableNames', { ...
        'Variant', ...
        'TestYear', ...
        'TargetModel', ...
        'Domain', ...
        'NFeatures', ...
        'MeanAbsoluteAttribution', ...
        'TotalShare', ...
        'MeanAbsoluteAttributionPerFeature', ...
        'MeanSignedSHAP', ...
        'MedianSignedSHAP', ...
        'Q25SignedSHAP', ...
        'Q75SignedSHAP'});


    %% ========================================================
    % MECHANISM TABLE
    % ========================================================

    nMechanism = ...
        numel(cfg.MechanismGroupNames);


    mechanismImportance = ...
        zeros(nMechanism,1);


    mechanismSigned = ...
        zeros( ...
        size(SHAPValues,1), ...
        nMechanism);


    mechanismFeatureCount = ...
        zeros(nMechanism,1);


    mechanismWithinDomainShare = ...
        zeros(nMechanism,1);


    mechanismDomain = ...
        cell(nMechanism,1);


    for g = 1:nMechanism


        idx = ...
            cfg.MechanismID == ...
            g;


        mechanismFeatureCount(g) = ...
            sum(idx);


        mechanismImportance(g) = ...
