    N = NaN(nBins,1);

    FeatureMin = NaN(nBins,1);
    FeatureQ25 = NaN(nBins,1);
    FeatureMedian = NaN(nBins,1);
    FeatureQ75 = NaN(nBins,1);
    FeatureMax = NaN(nBins,1);

    SHAPQ25 = NaN(nBins,1);
    SHAPMedian = NaN(nBins,1);
    SHAPQ75 = NaN(nBins,1);


    for b = 1:nBins


        rows = ...
            binID == ...
            b;


        xb = ...
            x(rows);


        yb = ...
            y(rows);


        N(b) = ...
            numel(xb);


        FeatureMin(b) = min(xb);
        FeatureQ25(b) = prctile(xb,25);
        FeatureMedian(b) = median(xb);
        FeatureQ75(b) = prctile(xb,75);
        FeatureMax(b) = max(xb);

        SHAPQ25(b) = prctile(yb,25);
        SHAPMedian(b) = median(yb);
        SHAPQ75(b) = prctile(yb,75);

    end


    T = ...
        table( ...
        Bin, ...
        N, ...
        FeatureMin, ...
        FeatureQ25, ...
        FeatureMedian, ...
        FeatureQ75, ...
        FeatureMax, ...
        SHAPQ25, ...
        SHAPMedian, ...
        SHAPQ75);


end


function T = ...
    calculateM3SpatialAttribution( ...
    rawFiles, ...
    cfg, ...
    expectedNPixel, ...
    testYear)


    nModel = ...
        numel(rawFiles);


    nDomain = ...
        numel(cfg.DomainNames);


    nMechanism = ...
        numel(cfg.MechanismGroupNames);


    DomainSigned = ...
        NaN( ...
        expectedNPixel, ...
        nModel, ...
        nDomain);


    DomainAbsFraction = ...
        NaN( ...
        expectedNPixel, ...
        nModel, ...
        nDomain);


    MechanismSigned = ...
        NaN( ...
        expectedNPixel, ...
        nModel, ...
        nMechanism);


    MechanismAbsFraction = ...
        NaN( ...
        expectedNPixel, ...
        nModel, ...
        nMechanism);


    pixelID = [];
    lat = [];
    lon = [];


    for m = 1:nModel


        Raw = ...
            loadStandardRawCase( ...
            rawFiles{m});


        if isempty(pixelID)


            pixelID = ...
                Raw.PixelID;


            lat = ...
                Raw.Lat;


            lon = ...
                Raw.Lon;


        else


            if ~isequal( ...
                    Raw.PixelID, ...
                    pixelID)

                error( ...
                    'M3 spatial pixel alignment failed.');

            end

        end


        SHAP = ...
            Raw.SHAPValues;


        totalAbs = ...
            sum( ...
            abs(SHAP), ...
            2);


        validTotal = ...
            totalAbs > 0;


        %% ----------------------------------------------------
        % Domains
        % -----------------------------------------------------

        for d = 1:nDomain


            idx = ...
                cfg.DomainID == ...
                d;


            signed = ...
                sum( ...
                SHAP(:,idx), ...
                2);


            absolute = ...
                sum( ...
                abs( ...
                SHAP(:,idx)), ...
                2);


            fraction = ...
                NaN( ...
                expectedNPixel, ...
                1);


            fraction(validTotal) = ...
                absolute(validTotal) ./ ...
                totalAbs(validTotal);


            DomainSigned(:,m,d) = ...
                signed;


            DomainAbsFraction(:,m,d) = ...
                fraction;

        end


        %% ----------------------------------------------------
        % Mechanisms
        % -----------------------------------------------------

        for g = 1:nMechanism


            idx = ...
                cfg.MechanismID == ...
                g;


            signed = ...
                sum( ...
                SHAP(:,idx), ...
                2);


            absolute = ...
                sum( ...
                abs( ...
                SHAP(:,idx)), ...
                2);


            fraction = ...
                NaN( ...
                expectedNPixel, ...
                1);


            fraction(validTotal) = ...
                absolute(validTotal) ./ ...
                totalAbs(validTotal);


            MechanismSigned(:,m,g) = ...
                signed;


            MechanismAbsFraction(:,m,g) = ...
                fraction;

        end

    end


    %% ========================================================
    % Across nine targets within this test year
    % ========================================================

    domainSignedMedian = ...
        squeeze( ...
        median( ...
        DomainSigned, ...
        2));


    domainAbsMedian = ...
        squeeze( ...
        median( ...
        DomainAbsFraction, ...
        2));


    domainAbsQ25 = ...
        squeeze( ...
        prctile( ...
        DomainAbsFraction, ...
        25, ...
        2));


    domainAbsQ75 = ...
        squeeze( ...
        prctile( ...
        DomainAbsFraction, ...
        75, ...
        2));


    mechanismSignedMedian = ...
        squeeze( ...
        median( ...
        MechanismSigned, ...
        2));


    mechanismAbsMedian = ...
        squeeze( ...
        median( ...
        MechanismAbsFraction, ...
        2));


    T = ...
        table( ...
        pixelID, ...
        lat, ...
        lon, ...
        repmat(testYear,expectedNPixel,1), ...
        'VariableNames', { ...
        'PixelID', ...
        'Lat', ...
        'Lon', ...
        'TestYear'});


    %% Domains.

    for d = 1:nDomain


        base = ...
            matlab.lang.makeValidName( ...
            cfg.DomainNames{d});


        T.(sprintf( ...
            '%sSignedSHAP_MedianAcrossTargets', ...
            base)) = ...
            domainSignedMedian(:,d);


        T.(sprintf( ...
            '%sAbsFraction_MedianAcrossTargets', ...
            base)) = ...
            domainAbsMedian(:,d);


        T.(sprintf( ...
            '%sAbsFraction_Q25AcrossTargets', ...
            base)) = ...
            domainAbsQ25(:,d);


        T.(sprintf( ...
            '%sAbsFraction_Q75AcrossTargets', ...
            base)) = ...
            domainAbsQ75(:,d);

    end


    %% Convenience aliases.

    hydroDomain = ...
        find( ...
        strcmp( ...
        cfg.DomainNames, ...
        'Hydroclimate'));


    dgwsDomain = ...
        find( ...
        strcmp( ...
        cfg.DomainNames, ...
        'dGWS'));


    T.HydroAbsFraction_Median = ...
        domainAbsMedian(:,hydroDomain);


    T.dGWSAbsFraction_Median = ...
        domainAbsMedian(:,dgwsDomain);


    T.HydroSignedSHAP_Median = ...
        domainSignedMedian(:,hydroDomain);


    T.dGWSSignedSHAP_Median = ...
        domainSignedMedian(:,dgwsDomain);


    %% Mechanisms.

    for g = 1:nMechanism


        base = ...
            matlab.lang.makeValidName( ...
            cfg.MechanismGroupNames{g});


        T.(sprintf( ...
            '%sAbsFraction_Median', ...
            base)) = ...
            mechanismAbsMedian(:,g);


        T.(sprintf( ...
            '%sSignedSHAP_Median', ...
            base)) = ...
            mechanismSignedMedian(:,g);

    end


end


function Global = ...
    combineM3SpatialAcrossYears( ...
    YearTables, ...
    cfg)


    nYear = ...
        numel(YearTables);


    Ref = ...
        YearTables{1};


    nPixel = ...
        height(Ref);


    for iy = 2:nYear


        if ~isequal( ...
                YearTables{iy}.PixelID, ...
                Ref.PixelID)

            error( ...
                'Pixel order differs across M3 spatial years.');

        end

    end


    hydro = ...
        NaN( ...
        nPixel, ...
        nYear);


    dgws = ...
        NaN( ...
        nPixel, ...
        nYear);


    for iy = 1:nYear


        hydro(:,iy) = ...
            YearTables{iy}.HydroAbsFraction_Median;


        dgws(:,iy) = ...
            YearTables{iy}.dGWSAbsFraction_Median;

    end


    Global = ...
        table( ...
        Ref.PixelID, ...
        Ref.Lat, ...
        Ref.Lon, ...
        median(hydro,2), ...
        prctile(hydro,25,2), ...
        prctile(hydro,75,2), ...
        median(dgws,2), ...
        'VariableNames', { ...
        'PixelID', ...
        'Lat', ...
        'Lon', ...
        'HydroAbsFraction_Median2022_2024', ...
        'HydroAbsFraction_Q25AcrossYears', ...
        'HydroAbsFraction_Q75AcrossYears', ...
        'dGWSAbsFraction_Median2022_2024'});


    %% --------------------------------------------------------
    % Mechanism absolute fractions can also be summarized
    % across years because they are normalized local fractions.
    % ---------------------------------------------------------

    for g = 1:numel(cfg.MechanismGroupNames)


        base = ...
            matlab.lang.makeValidName( ...
            cfg.MechanismGroupNames{g});


        variableName = ...
            sprintf( ...
            '%sAbsFraction_Median', ...
            base);


        values = ...
            NaN( ...
            nPixel, ...
            nYear);


        for iy = 1:nYear


            values(:,iy) = ...
                YearTables{iy}.(variableName);

        end


        Global.(sprintf( ...
            '%sAbsFraction_Median2022_2024', ...
            base)) = ...
            median( ...
            values, ...
            2);

    end


end


