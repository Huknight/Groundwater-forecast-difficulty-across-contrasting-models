        mechanismSigned(:,g) = ...
            sum( ...
            SHAPValues(:,idx), ...
            2);


        d = ...
            cfg.MechanismDomainID(g);


        mechanismDomain{g} = ...
            cfg.DomainNames{d};


        mechanismWithinDomainShare(g) = ...
            mechanismImportance(g) / ...
            domainImportance(d);

    end


    mechanismTotalShare = ...
        mechanismImportance / ...
        totalImportance;


    mechanismMeanSigned = ...
        mean( ...
        mechanismSigned, ...
        1)';


    mechanismMedianSigned = ...
        median( ...
        mechanismSigned, ...
        1)';


    mechanismQ25Signed = ...
        prctile( ...
        mechanismSigned, ...
        25, ...
        1)';


    mechanismQ75Signed = ...
        prctile( ...
        mechanismSigned, ...
        75, ...
        1)';


    mechanismImportancePerFeature = ...
        mechanismImportance ./ ...
        mechanismFeatureCount;


    MechanismTable = ...
        table( ...
        repmat({cfg.Name},nMechanism,1), ...
        repmat(testYear,nMechanism,1), ...
        repmat({targetModel},nMechanism,1), ...
        cfg.MechanismGroupNames(:), ...
        cfg.MechanismClassNames(:), ...
        mechanismDomain, ...
        mechanismFeatureCount, ...
        mechanismImportance, ...
        mechanismTotalShare, ...
        mechanismWithinDomainShare, ...
        mechanismImportancePerFeature, ...
