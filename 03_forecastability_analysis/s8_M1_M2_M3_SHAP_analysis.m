    cell(nYear,nModel);


counter = ...
    0;


for v = 1:nVariant


    cfg = ...
        Configs(v);


    fprintf('\n');
    fprintf('------------------------------------------------------------\n');
    fprintf('PROCESSING %s\n',cfg.Name);
    fprintf('------------------------------------------------------------\n');


    for iy = 1:nYear


        testYear = ...
            outerTestYears(iy);


        for m = 1:nModel


            counter = ...
                counter + ...
                1;


            targetModel = ...
                modelNames{m};


            rawFile = ...
                RawFileMap{v,iy,m};


            fprintf( ...
                '%s | %d | %-6s ... ', ...
                cfg.Name, ...
                testYear, ...
                targetModel);


            Raw = ...
                loadStandardRawCase( ...
                rawFile);


            %% =================================================
            % COMPLETION
            % ==================================================

            if ~Raw.Completed

                error( ...
                    'Incomplete raw SHAP file:\n%s', ...
                    rawFile);

            end


            %% =================================================
            % SHAP DIMENSIONS
            % ==================================================

            [nPixel,nFeature] = ...
                size( ...
                Raw.SHAPValues);


            if nPixel ~= ...
                    expectedNPixel

                error( ...
                    ['Expected %d pixels but found %d:\n%s'], ...
                    expectedNPixel, ...
                    nPixel, ...
                    rawFile);

            end


            if nFeature ~= ...
                    numel(cfg.FeatureNames)

                error( ...
                    ['Feature dimension mismatch:\n%s'], ...
                    rawFile);

            end


            if any( ...
                    ~isfinite( ...
                    Raw.SHAPValues(:)))

                error( ...
                    'Non-finite SHAP values:\n%s', ...
                    rawFile);

            end


            if isempty(Raw.FeatureValues)

                error( ...
                    ['FeatureValues missing. They are required ', ...
                     'for dependence analysis:\n%s'], ...
                    rawFile);

            end


            if ~isequal( ...
                    size(Raw.FeatureValues), ...
                    size(Raw.SHAPValues))

                error( ...
                    'FeatureValues / SHAP size mismatch:\n%s', ...
                    rawFile);

            end


            %% =================================================
            % METADATA
            % ==================================================

            if ~isempty(Raw.Meta)


                if isfield(Raw.Meta,'test_year')


                    if double(Raw.Meta.test_year) ~= ...
                            testYear

                        error( ...
                            'Metadata test-year mismatch.');

                    end

                end


                if isfield(Raw.Meta,'target_model')


                    if string(Raw.Meta.target_model) ~= ...
                            string(targetModel)

                        error( ...
                            'Metadata target-model mismatch.');

                    end

                end


                if isfield(Raw.Meta,'feature_names')


                    metaFeatureNames = ...
                        cellstr( ...
                        string( ...
                        Raw.Meta.feature_names(:)))';


                    if ~isequal( ...
                            metaFeatureNames, ...
                            cfg.FeatureNames)

                        error( ...
                            ['Metadata feature order mismatch ', ...
                             'for %s / %d / %s.'], ...
                            cfg.Name, ...
                            testYear, ...
                            targetModel);

                    end

                end

            end


            %% =================================================
            % TEST ROW / PIXEL ALIGNMENT
            % ==================================================

            if isempty(Raw.PixelID) || ...
                    isempty(Raw.Lat) || ...
                    isempty(Raw.Lon)

                error( ...
                    'Pixel coordinates/IDs missing:\n%s', ...
                    rawFile);

            end


            if v == 1


                AlignmentReference{iy,m} = ...
                    struct( ...
                    'PixelID',Raw.PixelID, ...
                    'Lat',Raw.Lat, ...
                    'Lon',Raw.Lon, ...
                    'TestYear',Raw.TestYear);


            else


                Ref = ...
                    AlignmentReference{iy,m};


                if ~isequal( ...
                        Raw.PixelID, ...
                        Ref.PixelID)

                    error( ...
                        ['Cross-variant pixel_id mismatch ', ...
                         'for %d / %s.'], ...
                        testYear, ...
                        targetModel);

                end


                if any( ...
                        abs( ...
                        Raw.Lat - ...
                        Ref.Lat) > ...
                        coordinateTolerance)

                    error( ...
                        ['Cross-variant latitude mismatch ', ...
                         'for %d / %s.'], ...
                        testYear, ...
                        targetModel);

                end


                if any( ...
                        abs( ...
                        Raw.Lon - ...
                        Ref.Lon) > ...
                        coordinateTolerance)

                    error( ...
                        ['Cross-variant longitude mismatch ', ...
                         'for %d / %s.'], ...
                        testYear, ...
                        targetModel);

                end

            end


            %% =================================================
            % BACKGROUND CHECK
            % ==================================================

            backgroundRows = ...
                extractBackgroundRows( ...
                Raw);


            backgroundRowsAvailable = ...
                ~isempty(backgroundRows);


            if backgroundRowsAvailable


                if ~isequal( ...
                        double(backgroundRows(:)), ...
                        ExpectedBackgroundRows{iy}(:))

                    error( ...
                        ['Background row mismatch for ', ...
                         '%s / %d / %s.'], ...
                        cfg.Name, ...
                        testYear, ...
                        targetModel);

                end

            end


            %% =================================================
            % ADDITIVITY
            % ==================================================

            maxAdditivityResidual = ...
                NaN;


            meanAdditivityResidual = ...
                NaN;


            if ~isempty(Raw.PredictedLogTarget) && ...
                    ~isempty(Raw.ExpectedValue)


                reconstructed = ...
                    double(Raw.ExpectedValue(1)) + ...
                    sum( ...
                    Raw.SHAPValues, ...
                    2);


                residual = ...
                    Raw.PredictedLogTarget - ...
                    reconstructed;


                maxAdditivityResidual = ...
                    max( ...
                    abs(residual));


                meanAdditivityResidual = ...
                    mean( ...
                    abs(residual));


                if maxAdditivityResidual > ...
                        additivityTolerance

                    error( ...
                        ['Final SHAP additivity audit failed ', ...
                         'for %s / %d / %s.\n', ...
                         'Max residual = %.12g'], ...
                        cfg.Name, ...
                        testYear, ...
                        targetModel, ...
                        maxAdditivityResidual);

                end

            end


            %% =================================================
            % CASE SUMMARIES
            % ==================================================

            [ ...
                featureTable, ...
                domainTable, ...
                mechanismTable, ...
                hydroVariableTable] = ...
                summarizeSHAPCase( ...
                Raw.SHAPValues, ...
                cfg, ...
                testYear, ...
                targetModel);


            FeatureCaseCells{counter} = ...
                featureTable;


            DomainCaseCells{counter} = ...
                domainTable;


            MechanismCaseCells{counter} = ...
                mechanismTable;


            HydroVariableCaseCells{counter} = ...
                hydroVariableTable;


            %% =================================================
            % QC TABLE
            % ==================================================

            QCCells{counter} = ...
                table( ...
                {cfg.Name}, ...
                testYear, ...
                {targetModel}, ...
                nPixel, ...
                nFeature, ...
                Raw.Completed, ...
                backgroundRowsAvailable, ...
                maxAdditivityResidual, ...
                meanAdditivityResidual, ...
                {rawFile}, ...
                'VariableNames', { ...
                'Variant', ...
