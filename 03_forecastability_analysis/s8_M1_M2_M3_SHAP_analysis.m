function rawFile = ...
    locateRawSHAPFile( ...
    cfg, ...
    testYear, ...
    modelName)


    safeModel = ...
        matlab.lang.makeValidName( ...
        modelName);


    candidateNames = { ...
        sprintf( ...
        '%s_TreeSHAP_raw_%d_%s.mat', ...
        cfg.Name, ...
        testYear, ...
        safeModel), ...
        ...
        sprintf( ...
        '%s_TreeSHAP_%d_%s.mat', ...
        cfg.Name, ...
        testYear, ...
        safeModel)};


    for i = 1:numel(candidateNames)


        candidate = ...
            fullfile( ...
            cfg.RawFolder, ...
            candidateNames{i});


        if exist(candidate,'file')

            rawFile = ...
                candidate;

            return

        end

    end


    %% --------------------------------------------------------
    % Fallback:
    % inspect metadata from all MAT files.
    % ---------------------------------------------------------

    files = ...
        dir( ...
        fullfile( ...
        cfg.RawFolder, ...
        '*.mat'));


    matched = {};


    for i = 1:numel(files)


        thisFile = ...
            fullfile( ...
            files(i).folder, ...
            files(i).name);


        try


            info = ...
                whos( ...
                '-file', ...
                thisFile);


            names = ...
                {info.name};


            if ~ismember('Meta',names)

                continue

            end


            S = ...
                load( ...
                thisFile, ...
                'Meta');


            Meta = ...
                S.Meta;


            if ~isfield(Meta,'test_year') || ...
                    ~isfield(Meta,'target_model')

                continue

            end


            if double(Meta.test_year) == ...
                    testYear && ...
                    string(Meta.target_model) == ...
                    string(modelName)


                matched{end+1,1} = ...
                    thisFile; %#ok<AGROW>

            end


        catch

            continue

        end

    end


    if isempty(matched)

        error( ...
            ['Could not locate raw SHAP file:\n', ...
             '%s / %d / %s\nFolder:\n%s'], ...
            cfg.Name, ...
            testYear, ...
            modelName, ...
            cfg.RawFolder);

    end


    if numel(matched) > 1

        fprintf('\nMultiple raw files matched:\n');

        disp(matched);

        error( ...
            ['Multiple files matched %s / %d / %s.'], ...
            cfg.Name, ...
            testYear, ...
            modelName);

    end


    rawFile = ...
        matched{1};


end


