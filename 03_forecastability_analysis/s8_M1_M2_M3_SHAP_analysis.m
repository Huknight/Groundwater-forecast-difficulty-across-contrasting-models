%% s8_M1_M2_M3_SHAP_analysis.m
%
% ============================================================
% FINAL INTEGRATED SHAP ANALYSIS FOR M1 / M2 / M3
% ============================================================
%
% PURPOSE
%
% Integrate all formally computed exact Tree-SHAP results:
%
%   M1 = dGWS-only
%   M2 = Hydroclimate-only
%   M3 = dGWS + Hydroclimate
%
%
% ============================================================
% IMPORTANT
% ============================================================
%
% This script:
%
%   DOES NOT train any model.
%   DOES NOT calculate any new Tree SHAP.
%
% It only reads the completed s7 raw SHAP outputs and performs:
%
%   1. Final QC
%   2. Common attribution profiles
%   3. Matched M1-M3 and M2-M3 structural comparisons
%   4. Temporal stability
%   5. Algorithm stability
%   6. Signed SHAP dependence
%   7. Spatial attribution analysis
%   8. Figure-ready data preparation
%
%
% ============================================================
% SCIENTIFIC INTERPRETATION
% ============================================================
%
% SHAP target:
%
%   log1p(NRMSE_Q10Q90)
%
% Therefore:
%
%   SHAP > 0
%       -> increases predicted future forecast error
%       -> worse forecastability
%
%   SHAP < 0
%       -> decreases predicted future forecast error
%       -> better forecastability
%
%
% ============================================================
% GLOBAL IMPORTANCE
% ============================================================
%
% Feature importance:
%
%   I_j = mean_i |phi_ij|
%
%
% Total normalized share:
%
%   R_j = I_j / sum_all I
%
%
% In M3, within-domain normalized share:
%
%   R_j|D =
%       I_j / sum_(k in D) I_k
%
%
% ============================================================
% CRITICAL COMPARISON RULE
% ============================================================
%
% M1 dGWS shares are compared against:
%
%   M3 WITHIN-dGWS shares
%
% NOT M3 total shares.
%
%
% M2 hydro shares are compared against:
%
%   M3 WITHIN-Hydro shares
%
% NOT M3 total shares.
%
%
% This avoids artificial denominator effects caused by the
% second information domain entering M3.
%
%
% ============================================================
% MATCHED STRUCTURAL CHANGE
% ============================================================
%
% For each identical:
%
%   year x target-model
%
% calculate:
%
%   DeltaShare =
%       M3_within_domain_share
%       -
%       standalone_share
%
%
% M1 -> M3:
%
%   dGWS feature and mechanism structure
%
%
% M2 -> M3:
%
%   hydro feature, mechanism and variable structure
%
%
% IMPORTANT:
%
% These are descriptive attribution changes.
%
% They are NOT interpreted as independent causal or
% incremental performance contributions.
%
%
% ============================================================
% STABILITY
% ============================================================
%
% Profile similarity uses Spearman correlation.
%
% We calculate:
%
%   across all 27 model-year cases
%
%   within the same test year across 9 targets
%
%   within the same target across 3 years
%
%
% ============================================================
% SIGNED DEPENDENCE
% ============================================================
%
% Automatically select the top N features according to:
%
%   M3 common median TOTAL SHAP share
%
% Default:
%
%   N = 6
%
%
% For each selected feature:
%
%   - average/median across the nine target meta-models
%     at each physical pixel within each test year
%
%   - construct rank-based quantile bins
%
%   - calculate:
%
%       median signed SHAP
%       Q25 signed SHAP
%       Q75 signed SHAP
%
%
% Dependence is kept YEAR-SPECIFIC because each outer year has
% its own SHAP expected value/background reference.
%
%
% ============================================================
% SPATIAL ANALYSIS
% ============================================================
%
% M3 primary spatial metric:
%
%   Hydro absolute-attribution fraction:
%
%     sum_hydro |phi|
%     ----------------
%     sum_all37 |phi|
%
%
% This is calculated at each pixel for every target model.
%
% Then:
%
%   median across nine target models within each year
%
% and finally:
%
%   median across 2022-2024
%
%
% Because this is a normalized absolute fraction, it can be
% meaningfully summarized across years.
%
%
% Signed SHAP maps:
%
%   are retained separately for each year.
%
% We DO NOT directly average raw signed SHAP across years,
% because expected values/background references differ.
%
%
% ============================================================
% OUTPUT
% ============================================================
%
% s8_M1_M2_M3_SHAP_analysis_outputs\
%
%   01_QC\
%   02_common_profiles\
%   03_matched_comparisons\
%   04_stability\
%   05_dependence\
%   06_spatial\
%   07_performance_context\
%   logs\
%
%
% Final MAT:
