function [Matched,Summary,RankTable] = ...
    matchedStructuralComparison( ...
    standalone, ...
    combined, ...
    itemVariable, ...
    standaloneShareVariable, ...
    combinedShareVariable, ...
    comparisonName)


    years = ...
        unique( ...
        standalone.TestYear)';


    targets = ...
        unique( ...
        string(standalone.TargetModel), ...
        'stable');


    items = ...
        unique( ...
        string(standalone.(itemVariable)), ...
        'stable');


    rowsCell = {};


    rankCell = {};


    for iy = 1:numel(years)


        year = ...
            years(iy);


        for m = 1:numel(targets)


            target = ...
                targets(m);


            Stand = ...
                standalone( ...
                standalone.TestYear == year & ...
                string(standalone.TargetModel) == target, ...
                :);


            Comb = ...
                combined( ...
                combined.TestYear == year & ...
                string(combined.TargetModel) == target, ...
                :);


            standaloneVector = ...
                NaN(numel(items),1);


            combinedVector = ...
                NaN(numel(items),1);


            for i = 1:numel(items)


                item = ...
                    items(i);


                r1 = ...
                    string(Stand.(itemVariable)) == ...
                    item;


                r2 = ...
                    string(Comb.(itemVariable)) == ...
                    item;


                if sum(r1) ~= 1 || ...
                        sum(r2) ~= 1

                    error( ...
                        ['Matched structural comparison failed ', ...
                         'for %s / %d / %s / %s.'], ...
                        comparisonName, ...
                        year, ...
                        target, ...
                        item);

                end


                s1 = ...
                    Stand.(standaloneShareVariable)(r1);


                s2 = ...
                    Comb.(combinedShareVariable)(r2);


                standaloneVector(i) = ...
                    s1;


                combinedVector(i) = ...
                    s2;


                rowsCell{end+1,1} = ...
                    table( ...
                    {comparisonName}, ...
                    year, ...
                    {char(target)}, ...
                    {char(item)}, ...
                    s1, ...
                    s2, ...
                    s2-s1, ...
                    abs(s2-s1), ...
                    'VariableNames', { ...
                    'Comparison', ...
                    'TestYear', ...
                    'TargetModel', ...
                    'Item', ...
                    'StandaloneShare', ...
                    'CombinedWithinShare', ...
                    'DeltaShare', ...
                    'AbsoluteDeltaShare'}); %#ok<SAGROW>

            end


            rho = ...
                corr( ...
                standaloneVector, ...
                combinedVector, ...
                'Type', ...
                'Spearman', ...
                'Rows', ...
                'complete');


            l1 = ...
                sum( ...
                abs( ...
                combinedVector - ...
                standaloneVector));


            maxDiff = ...
                max( ...
                abs( ...
                combinedVector - ...
                standaloneVector));


            rankCell{end+1,1} = ...
                table( ...
                {comparisonName}, ...
                year, ...
                {char(target)}, ...
                rho, ...
                l1, ...
                maxDiff, ...
                'VariableNames', { ...
                'Comparison', ...
                'TestYear', ...
                'TargetModel', ...
                'SpearmanProfileCorrelation', ...
                'L1ProfileDifference', ...
                'MaximumShareDifference'}); %#ok<SAGROW>

        end

    end


    Matched = ...
        vertcat( ...
        rowsCell{:});


    RankTable = ...
        vertcat( ...
        rankCell{:});


    %% --------------------------------------------------------
    % Item-level summary across the 27 matched cases
    % ---------------------------------------------------------

    itemNames = ...
        unique( ...
        string(Matched.Item), ...
        'stable');


    nItem = ...
        numel(itemNames);


    Item = cellstr(itemNames);

    MedianStandaloneShare = NaN(nItem,1);
    MedianCombinedWithinShare = NaN(nItem,1);

    MedianDeltaShare = NaN(nItem,1);
    Q25DeltaShare = NaN(nItem,1);
    Q75DeltaShare = NaN(nItem,1);
    MinDeltaShare = NaN(nItem,1);
    MaxDeltaShare = NaN(nItem,1);

    MedianAbsoluteDeltaShare = NaN(nItem,1);

    FractionDeltaPositive = NaN(nItem,1);
    FractionDeltaNegative = NaN(nItem,1);


    for i = 1:nItem


        rows = ...
            string(Matched.Item) == ...
            itemNames(i);


        delta = ...
            Matched.DeltaShare(rows);


        MedianStandaloneShare(i) = ...
            median( ...
            Matched.StandaloneShare(rows));


        MedianCombinedWithinShare(i) = ...
            median( ...
            Matched.CombinedWithinShare(rows));


        MedianDeltaShare(i) = ...
            median(delta);


        Q25DeltaShare(i) = ...
            prctile(delta,25);


        Q75DeltaShare(i) = ...
            prctile(delta,75);


        MinDeltaShare(i) = ...
            min(delta);


        MaxDeltaShare(i) = ...
            max(delta);


        MedianAbsoluteDeltaShare(i) = ...
            median(abs(delta));


        FractionDeltaPositive(i) = ...
            mean(delta > 0);


        FractionDeltaNegative(i) = ...
            mean(delta < 0);

    end


    Summary = ...
        table( ...
        Item, ...
        MedianStandaloneShare, ...
        MedianCombinedWithinShare, ...
        MedianDeltaShare, ...
        Q25DeltaShare, ...
        Q75DeltaShare, ...
        MinDeltaShare, ...
        MaxDeltaShare, ...
        MedianAbsoluteDeltaShare, ...
