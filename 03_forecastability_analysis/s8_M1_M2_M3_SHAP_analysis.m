% 25. CALCULATE SIGNED DEPENDENCE
% ============================================================

DependenceBinCells = {};
DependenceDirectionCells = {};


for iFeature = 1:height(SelectedDependenceFeatures)


    featureName = ...
        SelectedDependenceFeatures.FeatureName{iFeature};


    featureDomain = ...
        SelectedDependenceFeatures.Domain{iFeature};


    if strcmp( ...
            featureDomain, ...
            'dGWS')


        variantsToAnalyze = ...
            [1 3];


    elseif strcmp( ...
            featureDomain, ...
            'Hydroclimate')


        variantsToAnalyze = ...
            [2 3];


    else


        error( ...
            'Unexpected feature domain.');

    end


    fprintf('\nFeature: %s\n', ...
        featureName);


    for v = variantsToAnalyze


        cfg = ...
            Configs(v);


        featureIndex = ...
            find( ...
            strcmp( ...
            cfg.FeatureNames, ...
            featureName));


        if numel(featureIndex) ~= 1

            error( ...
                ['Could not uniquely locate %s in %s.'], ...
                featureName, ...
                cfg.Name);

        end


        for iy = 1:nYear


            testYear = ...
                outerTestYears(iy);


            [ ...
                pixelID, ...
                featureValue, ...
                medianSignedSHAP] = ...
                extractTargetMedianFeatureSHAP( ...
                squeeze( ...
                RawFileMap(v,iy,:)), ...
                featureIndex, ...
                expectedNPixel);


            binTable = ...
                rankQuantileDependence( ...
                featureValue, ...
                medianSignedSHAP, ...
                nDependenceBins);


            nRowsBin = ...
                height(binTable);


            binTable = ...
                addvars( ...
                binTable, ...
                repmat({featureName},nRowsBin,1), ...
                repmat({featureDomain},nRowsBin,1), ...
                repmat({cfg.Name},nRowsBin,1), ...
                repmat(testYear,nRowsBin,1), ...
                'Before', ...
                1, ...
                'NewVariableNames', { ...
                'FeatureName', ...
                'Domain', ...
                'Variant', ...
                'TestYear'});


            DependenceBinCells{end+1,1} = ...
                binTable; %#ok<SAGROW>


            %% -----------------------------------------------
            % Overall monotonic direction summary
            % -----------------------------------------------

            rho = ...
                corr( ...
                featureValue, ...
                medianSignedSHAP, ...
                'Type', ...
                'Spearman', ...
                'Rows', ...
                'complete');


            [~,order] = ...
                sort( ...
                featureValue, ...
                'ascend');


            n = ...
                numel(order);


            nDecile = ...
                max( ...
                1, ...
                floor(n*0.10));


            lowIndex = ...
                order(1:nDecile);


            highIndex = ...
                order(end-nDecile+1:end);


            lowMedianSHAP = ...
                median( ...
                medianSignedSHAP(lowIndex));


            highMedianSHAP = ...
                median( ...
                medianSignedSHAP(highIndex));


            highMinusLow = ...
                highMedianSHAP - ...
                lowMedianSHAP;


            DependenceDirectionCells{end+1,1} = ...
                table( ...
                {featureName}, ...
                {featureDomain}, ...
                {cfg.Name}, ...
                testYear, ...
                numel(pixelID), ...
                rho, ...
                lowMedianSHAP, ...
                highMedianSHAP, ...
                highMinusLow, ...
                'VariableNames', { ...
                'FeatureName', ...
                'Domain', ...
                'Variant', ...
