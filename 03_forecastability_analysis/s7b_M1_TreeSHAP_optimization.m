function [ ...
    EnsembleSHAP, ...
    EnsembleIntercept, ...
    MethodAudit, ...
    RuntimeMinutes] = ...
    computeEnsembleTreeSHAP( ...
    Trees, ...
    Xbackground, ...
    Xquery, ...
    supportsNumObservationsToSample)


    nTrees = ...
        numel(Trees);


    nQuery = ...
        size(Xquery,1);


    nFeature = ...
        size(Xquery,2);


    TreeSHAP = ...
        NaN( ...
        nQuery, ...
        nFeature, ...
        nTrees);


    TreeIntercept = ...
        NaN(nTrees,1);


    TreeMethod = ...
        strings(nTrees,1);


    timerAll = ...
        tic;


    parfor t = 1:nTrees


        thisTree = ...
            Trees{t};


        if supportsNumObservationsToSample


            explainer = ...
                shapley( ...
                thisTree, ...
                Xbackground, ...
                'Method', ...
                'interventional', ...
                'NumObservationsToSample', ...
                'all');


        else


            explainer = ...
                shapley( ...
                thisTree, ...
                Xbackground, ...
                'Method', ...
                'interventional');

        end


        fitted = ...
            fit( ...
            explainer, ...
            Xquery, ...
            'Method', ...
            'interventional', ...
            'UseParallel', ...
            false);


        TreeSHAP(:,:,t) = ...
            extractRegressionSHAP( ...
            fitted, ...
            nFeature, ...
            nQuery);


        TreeIntercept(t) = ...
            double( ...
            fitted.Intercept);


        TreeMethod(t) = ...
            string( ...
            fitted.Method);

    end


    RuntimeMinutes = ...
        toc(timerAll) / ...
        60;


    EnsembleSHAP = ...
        mean( ...
        TreeSHAP, ...
        3);


    EnsembleIntercept = ...
        mean( ...
        TreeIntercept);


    MethodAudit = ...
        struct();


    MethodAudit.TreeMethod = ...
        TreeMethod;


    MethodAudit.AllInterventionalTree = ...
        all( ...
        TreeMethod == ...
        "interventional-tree");


    MethodAudit.NumberInterventionalTree = ...
        sum( ...
        TreeMethod == ...
        "interventional-tree");


end


function SHAPValues = ...
    extractRegressionSHAP( ...
    fittedExplainer, ...
    nFeature, ...
    nQuery)


    if isprop( ...
            fittedExplainer, ...
            'Shapley')


        T = ...
            fittedExplainer.Shapley;


    elseif isprop( ...
            fittedExplainer, ...
            'ShapleyValues')


        T = ...
            fittedExplainer.ShapleyValues;


    else


        error( ...
            'Could not locate SHAP-value property.');

    end


    variableNames = ...
        T.Properties.VariableNames;


    if ismember( ...
            'Value', ...
            variableNames)


        V = ...
            T.Value;


    elseif ismember( ...
            'ShapleyValue', ...
            variableNames)


        V = ...
            T.ShapleyValue;


    else


        V = ...
            T{:,2:end};

    end


    if iscell(V)

        V = ...
            cell2mat(V);

    end


    V = ...
        double(V);


    if size(V,1) == nFeature && ...
            size(V,2) == nQuery


        SHAPValues = ...
            V';


    elseif size(V,1) == nQuery && ...
            size(V,2) == nFeature


        SHAPValues = ...
            V;


    elseif nQuery == 1 && ...
            numel(V) == nFeature


        SHAPValues = ...
            V(:)';


    else


        error( ...
            ['Unexpected SHAP dimensions: %d x %d. ', ...
             'Expected %d features and %d queries.'], ...
            size(V,1), ...
            size(V,2), ...
            nFeature, ...
            nQuery);

    end


    if any(~isfinite(SHAPValues(:)))

        error( ...
            'Non-finite SHAP values detected.');

    end


end


function [GroupSigned,GroupAbs] = ...
    computeLocalGroups( ...
    SHAPValues, ...
    featureGroupID, ...
    nGroup)


    nSample = ...
        size(SHAPValues,1);


    GroupSigned = ...
        zeros( ...
        nSample, ...
        nGroup);


    GroupAbs = ...
        zeros( ...
        nSample, ...
        nGroup);


    for g = 1:nGroup


        idx = ...
            featureGroupID == ...
            g;


        GroupSigned(:,g) = ...
            sum( ...
            SHAPValues(:,idx), ...
            2);


        GroupAbs(:,g) = ...
            sum( ...
            abs( ...
            SHAPValues(:,idx)), ...
            2);

    end


end


function backgroundSets = ...
    selectNestedStratifiedBackgroundRows( ...
    forecastYear, ...
    testYear, ...
    requestedSizes, ...
    seed)


    requestedSizes = ...
        requestedSizes(:)';


    if any(diff(requestedSizes) <= 0)

        error( ...
            'Background sizes must be strictly increasing.');

    end


    trainYears = ...
        unique( ...
        forecastYear( ...
        forecastYear < ...
        testYear))';


    nTrainYear = ...
        numel(trainYears);


    maxSize = ...
        max(requestedSizes);


    maxCounts = ...
        allocateStratumCounts( ...
        maxSize, ...
        nTrainYear);


    rng(seed,'twister');


    yearRandomRows = ...
        cell(nTrainYear,1);


    for iy = 1:nTrainYear


        candidateRows = ...
            find( ...
            forecastYear == ...
            trainYears(iy));


        if maxCounts(iy) > ...
                numel(candidateRows)

            error( ...
                'Requested background exceeds candidates.');

        end


        permutation = ...
            randperm( ...
            numel(candidateRows));


        yearRandomRows{iy} = ...
            candidateRows(permutation);

    end


    backgroundSets = ...
        cell( ...
        numel(requestedSizes), ...
        1);


    for is = 1:numel(requestedSizes)


        counts = ...
            allocateStratumCounts( ...
            requestedSizes(is), ...
            nTrainYear);


        rows = ...
            zeros( ...
            requestedSizes(is), ...
            1);


        cursor = ...
            0;


        for iy = 1:nTrainYear


            nSelect = ...
                counts(iy);


            rows( ...
                cursor + ...
                (1:nSelect)) = ...
                yearRandomRows{iy}(1:nSelect);


            cursor = ...
                cursor + ...
                nSelect;

        end


        backgroundSets{is} = ...
            rows;

    end


end


function backgroundRows = ...
    selectStratifiedBackgroundRows( ...
    forecastYear, ...
    testYear, ...
    backgroundSize, ...
    seed)


    trainYears = ...
        unique( ...
        forecastYear( ...
        forecastYear < ...
        testYear))';


    nTrainYear = ...
        numel(trainYears);


    counts = ...
        allocateStratumCounts( ...
        backgroundSize, ...
        nTrainYear);


    rng(seed,'twister');


    backgroundRows = ...
        zeros( ...
        backgroundSize, ...
        1);


    cursor = ...
        0;


    for iy = 1:nTrainYear


        candidateRows = ...
            find( ...
            forecastYear == ...
            trainYears(iy));


        nSelect = ...
            counts(iy);


        selectedLocal = ...
            randperm( ...
            numel(candidateRows), ...
            nSelect);


        selectedRows = ...
            candidateRows(selectedLocal);


        backgroundRows( ...
            cursor + ...
            (1:nSelect)) = ...
            selectedRows;


        cursor = ...
            cursor + ...
            nSelect;

    end


    if numel(unique(backgroundRows)) ~= ...
            backgroundSize

        error( ...
            'Duplicate background rows detected.');

    end


end


function counts = ...
    allocateStratumCounts( ...
    totalCount, ...
    nStrata)


    baseCount = ...
        floor( ...
        totalCount / ...
        nStrata);


    remainderCount = ...
        mod( ...
        totalCount, ...
        nStrata);


    counts = ...
        repmat( ...
        baseCount, ...
        nStrata, ...
        1);


    if remainderCount > 0

        counts(1:remainderCount) = ...
            counts(1:remainderCount) + ...
            1;

    end


end


function composition = ...
    backgroundYearComposition( ...
    forecastYear, ...
    rows)


    years = ...
        unique( ...
        forecastYear(rows))';


    parts = ...
        cell( ...
        numel(years), ...
        1);


    for i = 1:numel(years)


        parts{i} = ...
            sprintf( ...
            '%d:%d', ...
            years(i), ...
            sum( ...
            forecastYear(rows) == ...
            years(i)));

    end


    composition = ...
        strjoin( ...
        parts, ...
        '; ');


end


function [AuditTable,Summary] = ...
    auditBackgroundRepresentativeness( ...
    Xfull, ...
    Xbackground, ...
    featureNames)


    nFeature = ...
        size(Xfull,2);


    FeatureID = ...
        (1:nFeature)';


    FeatureName = ...
        featureNames(:);


    Full_P01 = NaN(nFeature,1);
    Full_P05 = NaN(nFeature,1);
    Full_P25 = NaN(nFeature,1);
    Full_Median = NaN(nFeature,1);
    Full_P75 = NaN(nFeature,1);
    Full_P95 = NaN(nFeature,1);
    Full_P99 = NaN(nFeature,1);

    BG_P01 = NaN(nFeature,1);
    BG_P05 = NaN(nFeature,1);
    BG_P25 = NaN(nFeature,1);
    BG_Median = NaN(nFeature,1);
    BG_P75 = NaN(nFeature,1);
    BG_P95 = NaN(nFeature,1);
    BG_P99 = NaN(nFeature,1);

    KS_D = ...
        NaN(nFeature,1);


    NormalizedMedianDifference = ...
        NaN(nFeature,1);


    BG_BelowFullP01_Fraction = ...
        NaN(nFeature,1);


    BG_AboveFullP99_Fraction = ...
        NaN(nFeature,1);


    for j = 1:nFeature


        fullData = ...
            Xfull(:,j);


        bgData = ...
            Xbackground(:,j);


        qFull = ...
            prctile( ...
            fullData, ...
            [1 5 25 50 75 95 99]);


        qBG = ...
            prctile( ...
            bgData, ...
            [1 5 25 50 75 95 99]);


        Full_P01(j) = qFull(1);
        Full_P05(j) = qFull(2);
        Full_P25(j) = qFull(3);
        Full_Median(j) = qFull(4);
        Full_P75(j) = qFull(5);
        Full_P95(j) = qFull(6);
        Full_P99(j) = qFull(7);

        BG_P01(j) = qBG(1);
        BG_P05(j) = qBG(2);
        BG_P25(j) = qBG(3);
        BG_Median(j) = qBG(4);
        BG_P75(j) = qBG(5);
        BG_P95(j) = qBG(6);
        BG_P99(j) = qBG(7);


        [~,~,ksStatistic] = ...
            kstest2( ...
            fullData, ...
            bgData);


        KS_D(j) = ...
            ksStatistic;


        robustScale = ...
            qFull(6) - ...
            qFull(2);


        if robustScale > 0


            NormalizedMedianDifference(j) = ...
                abs( ...
                qBG(4) - ...
                qFull(4)) / ...
                robustScale;


        else


            NormalizedMedianDifference(j) = ...
                0;

        end


        BG_BelowFullP01_Fraction(j) = ...
            mean( ...
            bgData < ...
            qFull(1));


        BG_AboveFullP99_Fraction(j) = ...
            mean( ...
            bgData > ...
            qFull(7));

    end


    ExtremeLowDeviationFromExpected = ...
        abs( ...
        BG_BelowFullP01_Fraction - ...
        0.01);


    ExtremeHighDeviationFromExpected = ...
        abs( ...
        BG_AboveFullP99_Fraction - ...
        0.01);


    AuditTable = ...
        table( ...
        FeatureID, ...
        FeatureName, ...
        Full_P01, ...
        Full_P05, ...
        Full_P25, ...
        Full_Median, ...
        Full_P75, ...
        Full_P95, ...
        Full_P99, ...
        BG_P01, ...
        BG_P05, ...
        BG_P25, ...
        BG_Median, ...
        BG_P75, ...
        BG_P95, ...
        BG_P99, ...
        KS_D, ...
        NormalizedMedianDifference, ...
        BG_BelowFullP01_Fraction, ...
        BG_AboveFullP99_Fraction, ...
        ExtremeLowDeviationFromExpected, ...
        ExtremeHighDeviationFromExpected);


    Summary = ...
        emptyAuditSummary();


    Summary.MedianKS = ...
        median(KS_D);


    Summary.MaxKS = ...
        max(KS_D);


    Summary.MeanNormalizedMedianDifference = ...
        mean( ...
        NormalizedMedianDifference);


    Summary.MaxNormalizedMedianDifference = ...
        max( ...
        NormalizedMedianDifference);


    Summary.MaxExtremeFractionDeviation = ...
        max( ...
        [ ...
        ExtremeLowDeviationFromExpected; ...
        ExtremeHighDeviationFromExpected]);


end


