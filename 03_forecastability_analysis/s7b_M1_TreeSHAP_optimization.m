%% s7b_M1_TreeSHAP_optimization.m
%
% ============================================================
% PURPOSE
% ============================================================
%
% Optimize and validate the computational settings for formal
% M1 exact Tree SHAP analysis.
%
% This script runs ONLY:
%
%   M1 / AR / outer test year 2022
%
%
% It performs four stages:
%
%   A. Worker-count scaling
%   B. Query-block-size optimization
%   C. Background-size robustness
%   D. Background random-sampling robustness
%
%
% ============================================================
% TREE-SHAP METHOD
% ============================================================
%
% M1 is a 500-tree CompactTreeBagger.
%
% For regression:
%
%   RF prediction
%       =
%   mean prediction across 500 CompactRegressionTree learners
%
% Exact Tree SHAP is calculated for every individual tree:
%
%   phi_RF
%       =
%   mean(phi_tree_1,...,phi_tree_500)
%
% Previous s7a validation demonstrated:
%
%   RF prediction = mean(tree predictions)
%
%   exact ensemble SHAP additivity
%
%   500 / 500 trees used:
%
%       interventional-tree
%
%
% IMPORTANT:
%
% DO NOT specify MaxNumSubsets for individual tree SHAP.
%
% Otherwise MATLAB will switch from exact Tree SHAP to
% Kernel SHAP.
%
%
% ============================================================
% STAGE A — WORKER SCALING
% ============================================================
%
% Candidate worker counts:
%
%   4
%   8
%   12
%
% Fixed:
%
%   BG = 100
%   query = 500 pixels
%
% The fastest successful configuration is selected.
%
%
% ============================================================
% STAGE B — QUERY SIZE
% ============================================================
%
% Candidate query sizes:
%
%   20
%   100
%   500
%   1000
%   2000
%   5000
%
% Fixed:
%
%   BG = 100
%
% We evaluate:
%
%   total runtime
%   seconds/query
%   exact additivity
%
% Recommended query block:
%
%   smallest block whose seconds/query is within 5% of the
%   fastest observed throughput.
%
% This avoids unnecessarily large blocks when throughput has
% already reached a plateau.
%
%
% ============================================================
% STAGE C — BACKGROUND SIZE
% ============================================================
%
% Fixed foreground:
%
%   1000 outer-test pixels
%
% Nested background sizes:
%
%   100
%   300
%   500
%   1000
%
% Compare against BG1000:
%
%   feature SHAP shares
%   mechanism-group shares
%   local pixel-level SHAP
%   local signed grouped SHAP
%   expected value
%   background representativeness
%
%
% ============================================================
% STAGE D — BACKGROUND RANDOM-SEED ROBUSTNESS
% ============================================================
%
% Independently test:
%
%   BG300 x 5 seeds
%   BG500 x 5 seeds
%
% All runs use EXACTLY THE SAME foreground pixels.
%
%
% ============================================================
% BACKGROUND REPRESENTATIVENESS
% ============================================================
%
% Each background is compared with the complete outer-training
% population using:
%
%   P01
%   P05
%   P25
%   Median
%   P75
%   P95
%   P99
%   KS D
%   fraction below full-training P01
%   fraction above full-training P99
%
%
% ============================================================
% M1 MECHANISM GROUPS
% ============================================================
%
% 1 Memory / persistence
%
%   ACF1
%   ACF6
%   ACF memory length
%   Sign persistence
%
% 2 Seasonal / spectral
%
%   ACF12
%   STL seasonality
%   Annual spectral power
%   Seasonal-pattern stability
%   Spectral entropy
%
% 3 Local complexity
%
%   Permutation entropy
%
% 4 Recent state / nonstationarity
%
%   Recent variability
%   Recent median shift
%   Distribution shift
%
% ============================================================

