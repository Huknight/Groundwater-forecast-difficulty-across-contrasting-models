function restartParallelPool(nWorkers)


    cluster = ...
        parcluster('local');


    nWorkers = ...
        min( ...
        nWorkers, ...
        cluster.NumWorkers);


    pool = ...
        gcp('nocreate');


    if ~isempty(pool) && ...
            pool.NumWorkers ~= ...
            nWorkers


        delete(pool);


        pool = ...
            [];

    end


    if isempty(pool)


        fprintf( ...
            'Starting parallel pool with %d workers...\n', ...
            nWorkers);


        parpool( ...
            'local', ...
            nWorkers);

    end


end


function r = ...
    safeCorrelation( ...
    x, ...
    y, ...
    typeName)


    x = ...
        double(x(:));


    y = ...
        double(y(:));


    valid = ...
        isfinite(x) & ...
        isfinite(y);


    x = ...
        x(valid);


    y = ...
        y(valid);


    if numel(x) < 3 || ...
            std(x) == 0 || ...
            std(y) == 0


        r = ...
            NaN;


        return

    end


    r = ...
        corr( ...
        x, ...
        y, ...
        'Type', ...
        typeName, ...
        'Rows', ...
        'complete');


end