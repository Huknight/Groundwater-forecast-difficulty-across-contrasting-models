%% s7a_M1_SHAP_TreeSHAP_validation.m
%
% ============================================================
% PURPOSE
% ============================================================
%
% Validate whether SHAP for a CompactTreeBagger RF can be
% computed efficiently as the average of SHAP values from
% its individual CompactRegressionTree learners.
%
%
% TEST MODEL
%
%   M1
%   target    = AR
%   test year = 2022
%   trees     = 500
%
%
% TEST DESIGN
%
% 1. Reproduce the RF prediction using:
%
%       mean(prediction of 500 individual trees)
%
% 2. Compute Tree SHAP separately for every tree.
%
% 3. Aggregate:
%
%       RF_SHAP = mean(Tree_SHAP_t)
%
%       RF_Intercept = mean(Tree_Intercept_t)
%
% 4. Check exact additivity:
%
%       RF_Intercept + sum(RF_SHAP)
%
%   against:
%
%       predict(CompactRF,Xquery)
%
% 5. Compute the old forest-level Kernel SHAP approach for
%    only 5 query pixels as a reference comparison.
%
%
% IMPORTANT:
%
% DO NOT specify MaxNumSubsets for individual tree SHAP.
%
% Specifying MaxNumSubsets forces MATLAB to use Kernel SHAP.
%
%
% ============================================================

