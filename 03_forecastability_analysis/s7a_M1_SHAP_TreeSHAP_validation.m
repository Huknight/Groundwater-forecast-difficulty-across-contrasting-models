%% ============================================================
% 15. OPTIONAL OLD KERNEL-SHAP REFERENCE
% ============================================================

Kernel = ...
    struct();


if runKernelReference


    fprintf('\n');
    fprintf('============================================================\n');
    fprintf('KERNEL SHAP REFERENCE\n');
    fprintf('Queries       : %d\n', kernelQuerySize);
    fprintf('Background    : %d\n', backgroundSizeUsed);
    fprintf('MaxSubsets    : %d\n', kernelMaxNumSubsets);
    fprintf('Workers       : %d\n', kernelWorkers);
    fprintf('============================================================\n');


    restartParallelPool(kernelWorkers);


    forestPredictFcn = ...
        @(Xnew) predict( ...
        CompactRF, ...
        Xnew);


    if supportsNumObservationsToSample


        kernelExplainer = ...
            shapley( ...
            forestPredictFcn, ...
            Xbackground, ...
            'Method', ...
            'interventional', ...
            'MaxNumSubsets', ...
            kernelMaxNumSubsets, ...
            'NumObservationsToSample', ...
            'all');


    else


        kernelExplainer = ...
            shapley( ...
            forestPredictFcn, ...
            Xbackground, ...
            'Method', ...
            'interventional', ...
            'MaxNumSubsets', ...
            kernelMaxNumSubsets);

    end


    kernelTimer = ...
        tic;


    try


        kernelFitted = ...
            fit( ...
            kernelExplainer, ...
            XqueryKernel, ...
            'Method', ...
            'interventional', ...
            'MaxNumSubsets', ...
            kernelMaxNumSubsets, ...
            'UseParallel', ...
            true);


        kernelExecutionMode = ...
            "parallel";


    catch ME


        warning( ...
            'M1SHAP:ParallelKernelSHAPFailed', ...
            ['Parallel Kernel SHAP failed.\n', ...
            '%s\n', ...
            'Retrying serially.'], ...
        ME.message);


        pool = ...
            gcp('nocreate');


        if ~isempty(pool)

            delete(pool);

        end


        kernelFitted = ...
            fit( ...
            kernelExplainer, ...
            XqueryKernel, ...
            'Method', ...
            'interventional', ...
            'MaxNumSubsets', ...
            kernelMaxNumSubsets, ...
            'UseParallel', ...
            false);


        kernelExecutionMode = ...
            "serial";

    end


    Kernel.RuntimeMinutes = ...
        toc(kernelTimer) / ...
        60;


    Kernel.SHAPValues = ...
        extractRegressionSHAP( ...
        kernelFitted, ...
        nFeature, ...
        kernelQuerySize);


    Kernel.Intercept = ...
        double( ...
        kernelFitted.Intercept);


    Kernel.Method = ...
        string( ...
        kernelFitted.Method);


    Kernel.ExecutionMode = ...
        kernelExecutionMode;


    kernelPrediction = ...
        predict( ...
        CompactRF, ...
        XqueryKernel);


    kernelReconstructed = ...
        Kernel.Intercept + ...
        sum( ...
        Kernel.SHAPValues, ...
        2);


    Kernel.AdditivityResidual = ...
        kernelPrediction - ...
        kernelReconstructed;


    fprintf('\nKernel result:\n');

    fprintf( ...
        '  Method      : %s\n', ...
        Kernel.Method);


    fprintf( ...
        '  Mode        : %s\n', ...
        Kernel.ExecutionMode);


    fprintf( ...
        '  Runtime     : %.3f min\n', ...
        Kernel.RuntimeMinutes);


    fprintf( ...
        '  Sec/query   : %.3f\n', ...
        Kernel.RuntimeMinutes * ...
        60 / ...
        kernelQuerySize);


    fprintf( ...
        '  Max residual: %.3e\n', ...
        max( ...
        abs( ...
        Kernel.AdditivityResidual)));


    clear kernelExplainer ...
        kernelFitted;


    pool = ...
        gcp('nocreate');


    if ~isempty(pool)

        delete(pool);

    end

end


%% ============================================================
% 16. TREE SHAP
% ============================================================
%
% IMPORTANT:
%
% NO MaxNumSubsets parameter is supplied.
