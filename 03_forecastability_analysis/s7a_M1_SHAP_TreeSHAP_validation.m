function SHAPValues = ...
    extractRegressionSHAP( ...
    fittedExplainer, ...
    nFeature, ...
    nQuery)


    if isprop( ...
            fittedExplainer, ...
            'Shapley')


        T = ...
            fittedExplainer.Shapley;


    elseif isprop( ...
            fittedExplainer, ...
            'ShapleyValues')


        T = ...
            fittedExplainer.ShapleyValues;


    else


        error( ...
            'Could not find SHAP property.');

    end


    variableNames = ...
        T.Properties.VariableNames;


    if ismember( ...
            'Value', ...
            variableNames)


        V = ...
            T.Value;


    elseif ismember( ...
            'ShapleyValue', ...
            variableNames)


        V = ...
            T.ShapleyValue;


    else


        V = ...
            T{:,2:end};

    end


    if iscell(V)

        V = ...
            cell2mat(V);

    end


    V = ...
        double(V);


    if size(V,1) == nFeature && ...
            size(V,2) == nQuery


        SHAPValues = ...
            V';


    elseif size(V,1) == nQuery && ...
            size(V,2) == nFeature


        SHAPValues = ...
            V;


    elseif nQuery == 1 && ...
            numel(V) == nFeature


        SHAPValues = ...
            V(:)';


    else


        error( ...
            ['Unexpected SHAP dimensions: %d x %d. ', ...
             'Expected %d features x %d queries.'], ...
            size(V,1), ...
            size(V,2), ...
            nFeature, ...
            nQuery);

    end


    if any(~isfinite(SHAPValues(:)))

        error( ...
            'Non-finite SHAP values detected.');

    end


end


function r = ...
    safeCorrelation( ...
    x, ...
    y, ...
    typeName)


    x = ...
        double(x(:));


    y = ...
        double(y(:));


    valid = ...
        isfinite(x) & ...
        isfinite(y);


    x = ...
        x(valid);


    y = ...
        y(valid);


    if numel(x) < 3 || ...
            std(x) == 0 || ...
            std(y) == 0


        r = ...
            NaN;


        return

    end


    r = ...
        corr( ...
        x, ...
        y, ...
        'Type', ...
        typeName, ...
        'Rows', ...
        'complete');


end