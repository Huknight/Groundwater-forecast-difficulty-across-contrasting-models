function backgroundSets = ...
    selectNestedStratifiedBackgroundRows( ...
    forecastYear, ...
    testYear, ...
    requestedSizes, ...
    seed)


    requestedSizes = ...
        requestedSizes(:)';


    trainYears = ...
        unique( ...
        forecastYear( ...
        forecastYear < ...
        testYear))';


    nTrainYear = ...
        numel(trainYears);


    maxSize = ...
        max(requestedSizes);


    maxCounts = ...
        allocateStratumCounts( ...
        maxSize, ...
        nTrainYear);


    rng(seed,'twister');


    yearRandomRows = ...
        cell(nTrainYear,1);


    for iy = 1:nTrainYear


        candidateRows = ...
            find( ...
            forecastYear == ...
            trainYears(iy));


        if maxCounts(iy) > numel(candidateRows)

            error( ...
                'Requested background exceeds candidates.');

        end


        p = ...
            randperm( ...
            numel(candidateRows));


        yearRandomRows{iy} = ...
            candidateRows(p);

    end


    backgroundSets = ...
        cell( ...
        numel(requestedSizes), ...
        1);


    for is = 1:numel(requestedSizes)


        counts = ...
            allocateStratumCounts( ...
            requestedSizes(is), ...
            nTrainYear);


        rows = ...
            zeros( ...
            requestedSizes(is), ...
            1);


        cursor = ...
            0;


        for iy = 1:nTrainYear


            nSelect = ...
                counts(iy);


            rows( ...
                cursor + ...
                (1:nSelect)) = ...
                yearRandomRows{iy}(1:nSelect);


            cursor = ...
                cursor + ...
                nSelect;

        end


        backgroundSets{is} = ...
            rows;

    end


end


function counts = ...
    allocateStratumCounts( ...
    totalCount, ...
    nStrata)


    baseCount = ...
        floor( ...
        totalCount / ...
        nStrata);


    remainderCount = ...
        mod( ...
        totalCount, ...
        nStrata);


    counts = ...
        repmat( ...
        baseCount, ...
        nStrata, ...
        1);


    if remainderCount > 0

        counts(1:remainderCount) = ...
            counts(1:remainderCount) + ...
            1;

    end


end


