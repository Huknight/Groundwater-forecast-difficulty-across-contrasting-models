fprintf('============================================================\n');


%% Use the local profile limit if it is less than requested.

localCluster = ...
    parcluster('local');


treeWorkers = ...
    min( ...
    requestedTreeWorkers, ...
    localCluster.NumWorkers);


restartParallelPool(treeWorkers);


fprintf( ...
    'Tree-level parallel workers = %d\n', ...
    treeWorkers);


Trees = ...
    CompactRF.Trees;


TreeSHAP = ...
    NaN( ...
    treeQuerySize, ...
    nFeature, ...
    nTrees);


TreeIntercept = ...
    NaN( ...
    nTrees, ...
    1);


TreeRuntimeSeconds = ...
    NaN( ...
    nTrees, ...
    1);


TreeMethod = ...
    strings( ...
    nTrees, ...
    1);


treeSHAPTimer = ...
    tic;


parfor t = 1:nTrees


    thisTree = ...
        Trees{t};


    thisTimer = ...
        tic;


    %% --------------------------------------------------------
    % Create SHAP explainer for ONE native tree model.
    %
    % CRITICAL:
    %
    % Do NOT specify MaxNumSubsets here.
    % ---------------------------------------------------------

    if supportsNumObservationsToSample


        thisExplainer = ...
            shapley( ...
            thisTree, ...
            Xbackground, ...
            'Method', ...
            'interventional', ...
            'NumObservationsToSample', ...
            'all');


    else


        thisExplainer = ...
            shapley( ...
            thisTree, ...
            Xbackground, ...
            'Method', ...
            'interventional');

    end


    %% Internal parallelism is deliberately OFF.
    %
    % Parallelism is already occurring across trees.

    thisFitted = ...
        fit( ...
        thisExplainer, ...
        XqueryTree, ...
        'Method', ...
        'interventional', ...
        'UseParallel', ...
        false);


    TreeSHAP(:,:,t) = ...
        extractRegressionSHAP( ...
        thisFitted, ...
        nFeature, ...
        treeQuerySize);


    TreeIntercept(t) = ...
        double( ...
        thisFitted.Intercept);


    TreeMethod(t) = ...
        string( ...
        thisFitted.Method);


    TreeRuntimeSeconds(t) = ...
        toc(thisTimer);


end


TreeSHAP_TotalRuntimeMinutes = ...
    toc(treeSHAPTimer) / ...
    60;


