%% Step 6: Forecastability target correlation analysis
% File name:
%   s6_forecastability_target_correlation.m
%
% Purpose:
%   Examine whether the nine forecasting-model targets share
%   a common forecastability structure.
%
% ============================================================
% PRIMARY QUESTION
% ============================================================
%
% If one pixel-year is difficult to forecast for one model,
% is it also generally difficult for the other models?
%
%
% ============================================================
% PRIMARY FORECASTABILITY TARGET
% ============================================================
%
%   NRMSE_Q10Q90
%
% Main association metric:
%
%   Spearman correlation
%
% Reason:
%   NRMSE has a heavy right tail, and the main scientific
%   question concerns relative forecastability ranking.
%
%
% ============================================================
% SECONDARY ASSOCIATION METRIC
% ============================================================
%
%   Pearson correlation of:
%
%       log1p(NRMSE_Q10Q90)
%
% This matches the response scale used to train the RF
% forecastability meta-models.
%
%
% ============================================================
% DENOMINATOR SENSITIVITY ANALYSIS
% ============================================================
%
% The nine NRMSE targets for the same pixel-year share the
% same denominator:
%
%   Q90(pre-origin dGWS) - Q10(pre-origin dGWS)
%
% Therefore high NRMSE correlations could partly arise from
% this common denominator.
%
% To test this, repeat the analysis using:
%
%   raw 12-month RMSE
%
% Main:
%
%   Spearman(RMSE_m, RMSE_n)
%
% Secondary:
%
%   Pearson(log1p(RMSE_m), log1p(RMSE_n))
%
%
% ============================================================
% TEMPORAL ANALYSIS
% ============================================================
%
% 1. Pooled 2019-2024
%
% 2. Year-specific:
%       2019
%       2020
%       2021
%       2022
%       2023
%       2024
%
% 3. Primary out-of-time evaluation years:
%
%       2022
%       2023
%       2024
%
% The 2022-2024 results are especially important because
% these correspond to the independent outer-test years used
% by M1/M2/M3.
%
%
% ============================================================
% OUTPUTS
% ============================================================
%
% Main MAT:
%
%   s6_forecastability_target_correlation.mat
%
% Tables:
%
%   pooled correlation matrices
%   yearly correlation matrices
%   all 36 model-pair statistics
%   selected model-pair statistics
%   overall commonality summary
%
% Figures:
%
%   pooled NRMSE Spearman heatmap
%   pooled RMSE Spearman heatmap
%   NRMSE-vs-RMSE correlation difference
%   year-specific NRMSE Spearman heatmaps
%   year-specific RMSE Spearman heatmaps
%
%
% ============================================================
% INTERPRETATION
% ============================================================
%
% Strong NRMSE correlation + strong RMSE correlation:
%
%   supports a common model-independent forecastability
%   component.
%
%
% Strong NRMSE correlation but much weaker RMSE correlation:
%
%   indicates that part of the apparent common structure may
%   arise from the shared NRMSE denominator.
%
%
% Stable correlations across 2022, 2023 and 2024:
%
%   supports temporal robustness of the common forecastability
%   structure.
%
%
% ============================================================

