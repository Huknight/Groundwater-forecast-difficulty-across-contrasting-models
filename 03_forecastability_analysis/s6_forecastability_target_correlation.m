function C = correlationMatrix( ...
    X, ...
    correlationType)


    X = ...
        double(X);


    if strcmpi( ...
            correlationType, ...
            'Spearman')


        C = ...
            corr( ...
            X, ...
            'Type', ...
            'Spearman', ...
            'Rows', ...
            'pairwise');


    elseif strcmpi( ...
            correlationType, ...
            'Pearson')


        C = ...
            corr( ...
            X, ...
            'Type', ...
            'Pearson', ...
            'Rows', ...
            'pairwise');


    else


        error( ...
            'Unknown correlation type: %s', ...
            correlationType);

    end


    C = ...
        double(C);


    %% Enforce exact symmetry against tiny numerical differences.

    C = ...
        ( ...
        C + ...
        C.' ...
        ) / ...
        2;


    for i = 1:size(C, 1)

        C(i, i) = ...
            1;

    end

end


function S = offDiagonalStats(C)


    C = ...
        double(C);


    n = ...
        size(C, 1);


    upperMask = ...
        triu( ...
        true(n), ...
        1);


    values = ...
        C(upperMask);


    values = ...
        values( ...
        isfinite(values));


    if isempty(values)

        error( ...
            'No finite off-diagonal correlations.');

    end


    S = ...
        struct();


    S.N = ...
        numel(values);


    S.Mean = ...
        mean(values);


    S.Median = ...
        median(values);


    S.Minimum = ...
        min(values);


    S.Maximum = ...
        max(values);


    S.Std = ...
        std(values);


    S.Values = ...
        values;

end


function saveCorrelationMatrixCSV( ...
    C, ...
    modelNames, ...
    filePath)


    validVariableNames = ...
        matlab.lang.makeValidName( ...
        modelNames);


    T = ...
        array2table( ...
        C, ...
        'VariableNames', ...
        validVariableNames);


    T = ...
        addvars( ...
        T, ...
        modelNames(:), ...
        'Before', ...
        1, ...
        'NewVariableNames', ...
        'TargetModel');


    writetable( ...
        T, ...
        filePath);

end


function saveCorrelationHeatmap( ...
    C, ...
    modelNames, ...
    figureTitle, ...
    filePath, ...
    annotateValues, ...
    scaleType)


    fig = ...
        figure( ...
        'Color', ...
        'w', ...
        'Visible', ...
        'off', ...
        'Position', ...
        [100 100 900 760]);


    imagesc(C);


    axis square;


    n = ...
        numel(modelNames);


    set( ...
        gca, ...
        'XTick', ...
        1:n, ...
        'XTickLabel', ...
        modelNames, ...
        'YTick', ...
        1:n, ...
        'YTickLabel', ...
        modelNames, ...
        'TickLength', ...
        [0 0]);


    xtickangle(45);


    if strcmpi( ...
            scaleType, ...
            'correlation')


        clim([-1 1]);


    elseif strcmpi( ...
            scaleType, ...
            'difference')


        maxAbs = ...
            max( ...
            abs(C(:)));


        if maxAbs == 0

            maxAbs = ...
                1;

        end


        clim( ...
            [-maxAbs maxAbs]);


    else


        error( ...
            'Unknown heatmap scale type.');

    end


    cb = ...
        colorbar;


    if strcmpi(scaleType, 'correlation')

        ylabel( ...
            cb, ...
            'Correlation coefficient');


    else

        ylabel( ...
            cb, ...
            '\Delta Spearman');

    end


    title( ...
        figureTitle, ...
        'Interpreter', ...
        'none');


    if annotateValues

        annotateMatrix(C);

    end


    box on;


    exportgraphics( ...
        fig, ...
        filePath, ...
        'Resolution', ...
        300);


    [folderPath, baseName, ~] = ...
        fileparts(filePath);


    savefig( ...
        fig, ...
        fullfile( ...
        folderPath, ...
        [baseName, '.fig']));


    close(fig);

end


function annotateMatrix(C)


    nRow = ...
        size(C, 1);


    nCol = ...
        size(C, 2);


    cLimits = ...
        clim;


    midpoint = ...
        mean(cLimits);


    for i = 1:nRow


        for j = 1:nCol


            value = ...
                C(i, j);


            if ~isfinite(value)

                continue

            end


            if value > midpoint

                textColor = ...
                    [1 1 1];

            else

                textColor = ...
                    [0 0 0];

            end


            text( ...
                j, ...
                i, ...
                sprintf('%.2f', value), ...
                'HorizontalAlignment', ...
                'center', ...
                'VerticalAlignment', ...
                'middle', ...
                'Color', ...
                textColor, ...
                'FontSize', ...
                8);

        end

    end

end