for j = [1 2 3]

    z = ...
        X(:, j);

    z = ...
        z(isfinite(z));

    if any( ...
            z < -1 - 1e-10 | ...
            z > 1 + 1e-10)

        error( ...
            'Feature %s contains invalid autocorrelation values.', ...
            featureNames{j});

    end

end

%% ----- Memory length constrained to 0-24 -----

z = ...
    X(:, 4);

z = ...
    z(isfinite(z));

if any( ...
        z < 0 | ...
