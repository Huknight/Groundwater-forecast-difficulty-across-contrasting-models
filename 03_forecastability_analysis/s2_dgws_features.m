fprintf('Features     : %d\n', nFeature);
fprintf('Raw period   : %d - %d\n', ymRaw(1), ymRaw(end));

%% ===================== Initialize outputs =====================

X = ...
    NaN(nSample, nFeature);

% Keep raw versions of features 11 and 12 for auditing only.
% They are NOT included in the modeling feature matrix X.
recentVariabilityRatioRaw = ...
    NaN(nSample, 1);

recentMedianShiftRaw = ...
    NaN(nSample, 1);

historyMonths = ...
    zeros(nSample, 1, 'uint16');

historyStartYM = ...
    zeros(nSample, 1, 'uint32');

historyEndYM = ...
    zeros(nSample, 1, 'uint32');

referenceMonths = ...
    zeros(nSample, 1, 'uint16');

%% ===================== Calculate features =====================

fprintf('\n');
fprintf('============================================================\n');
fprintf('CALCULATING ALL-PRE-ORIGIN dGWS FEATURES\n');
fprintf('============================================================\n');

for y = 1:nYear

    thisYear = ...
        forecastYears(y);

    fprintf('\nForecast year %d\n', thisYear);

    %% ----- Master rows -----

    rows = ...
        find( ...
        double(Master.forecast_year) == thisYear);

    if numel(rows) ~= nValid

        error( ...
            'Forecast year %d has %d rows; expected %d.', ...
            thisYear, ...
            numel(rows), ...
            nValid);

    end

    pixelOrder = ...
        double(Master.pixel_id(rows));

    if numel(unique(pixelOrder)) ~= nValid || ...
            any(sort(pixelOrder) ~= (1:nValid)')

        error( ...
            'Pixel IDs for forecast year %d are inconsistent.', ...
            thisYear);

    end

    %% ----- Define all pre-origin history -----

    startYM = ...
        historyStartYear * 100 + ...
        historyStartMonth;

    endYM = ...
        (thisYear - 1) * 100 + 12;

    expectedYM = ...
        makeYMList( ...
        historyStartYear, ...
        historyStartMonth, ...
        thisYear - 1, ...
        12);

    nHistoryMonth = ...
        numel(expectedYM);

    nReferenceMonth = ...
        nHistoryMonth - recentWindow;

    if nReferenceMonth <= 0

        error( ...
            ['Forecast year %d does not contain enough history ', ...
             'for a %d-month recent window.'], ...
            thisYear, ...
            recentWindow);

    end

    if mod(nHistoryMonth, seasonPeriod) ~= 0

        error( ...
            ['Pre-origin history for forecast year %d does not ', ...
             'contain complete 12-month years.'], ...
            thisYear);

    end

    [tf, historyIdx] = ...
        ismember( ...
        expectedYM, ...
        ymRaw);

    if any(~tf)

        missingYM = ...
            expectedYM(~tf);

        error( ...
            ['Raw dGWS data are missing required feature months ', ...
             'for forecast %d: %s'], ...
            thisYear, ...
            mat2str(missingYM(:)'));

    end

    if numel(unique(historyIdx)) ~= nHistoryMonth

        error( ...
            'Duplicate feature-month matching for forecast %d.', ...
            thisYear);

    end

    historyBlock = ...
        dGWS_valid(:, historyIdx);

    if ~isequal( ...
            size(historyBlock), ...
            [nValid, nHistoryMonth])

        error( ...
            'Unexpected historyBlock dimensions for forecast %d.', ...
            thisYear);

    end

    historyOrdered = ...
        historyBlock(pixelOrder, :);

    %% ----- Check forecast origin -----

    expectedOriginYM = ...
        uint32(endYM);

    if any( ...
            Master.forecast_origin_ym(rows) ~= ...
            expectedOriginYM)

        error( ...
            ['Master.forecast_origin_ym is inconsistent ', ...
             'for forecast year %d.'], ...
            thisYear);

    end

    %% ----- Save audit information -----

    historyMonths(rows) = ...
        uint16(nHistoryMonth);

    historyStartYM(rows) = ...
        uint32(startYM);

    historyEndYM(rows) = ...
        uint32(endYM);

    referenceMonths(rows) = ...
        uint16(nReferenceMonth);

    fprintf( ...
        '  Full history     : %d - %d\n', ...
        startYM, ...
        endYM);

    fprintf( ...
        '  History months   : %d\n', ...
        nHistoryMonth);

    fprintf( ...
        '  Complete years   : %d\n', ...
        nHistoryMonth / 12);

    fprintf( ...
        '  Reference months : %d\n', ...
        nReferenceMonth);

    fprintf( ...
        '  Recent months    : %d\n', ...
        recentWindow);

    fprintf( ...
        '  Samples          : %d\n', ...
        numel(rows));

    %% ----- Calculate features -----

    featureBlock = ...
        NaN(nValid, nFeature);

    rawRatioBlock = ...
        NaN(nValid, 1);

    rawShiftBlock = ...
        NaN(nValid, 1);

    parfor i = 1:nValid

        x = ...
            historyOrdered(i, :).';

        [featureBlock(i, :), ...
            rawRatioBlock(i), ...
            rawShiftBlock(i)] = ...
            extractDGWSFeatures( ...
            x, ...
            seasonPeriod, ...
            maxACFLag, ...
            memoryThreshold, ...
            recentWindow);

    end

    X(rows, :) = ...
        featureBlock;

    recentVariabilityRatioRaw(rows) = ...
        rawRatioBlock;

    recentMedianShiftRaw(rows) = ...
        rawShiftBlock;

    %% ----- Year diagnostics -----

    nCompleteInput = ...
        sum( ...
        all(isfinite(historyOrdered), 2));

    nCompleteFeatures = ...
        sum( ...
        all(isfinite(featureBlock), 2));

    fprintf( ...
        '  Complete input histories : %d / %d\n', ...
        nCompleteInput, ...
        nValid);

    fprintf( ...
        '  All 13 features finite   : %d / %d\n', ...
        nCompleteFeatures, ...
        nValid);

    clear historyBlock historyOrdered featureBlock;
    clear rawRatioBlock rawShiftBlock;

end

%% ===================== Final consistency checks =====================

fprintf('\nRunning final feature checks...\n');

if ~isequal( ...
        size(X), ...
        [nSample, nFeature])

    error( ...
        'Feature matrix dimensions are inconsistent.');

end

%% ----- Features constrained to [0,1] -----

boundedFeatures = [ ...
    5, ...   % Sign persistence
    6, ...   % STL seasonality strength
    7, ...   % Annual spectral power ratio
    9, ...   % Permutation entropy
    10, ...  % Spectral entropy
    13];     % KS distribution shift

for j = boundedFeatures

    z = ...
        X(:, j);

    z = ...
        z(isfinite(z));

    if any( ...
            z < -1e-12 | ...
