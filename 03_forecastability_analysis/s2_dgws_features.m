%% Step 2: Build 2019-2024 dGWS-only feature database
% File name:
%   s2_dgws_features.m
%
% Purpose:
%   Calculate 13 pre-forecast dGWS-only time-series features for each
%   pixel x forecast_year sample.
%
% Basic sample:
%   one sample = one valid pixel x one forecast year
%
% Forecast years:
%   2019-2024
%
% Historical feature window:
%   ALL dGWS observations available from 2004-01 through the
%   forecast origin (December of the preceding year).
%
% Examples:
%   Forecast 2019:
%       2004-01 to 2018-12 = 180 months
%
%   Forecast 2024:
%       2004-01 to 2023-12 = 240 months
%
% Features 1-10:
%   calculated from the entire pre-origin history.
%
% Features 11-13:
%   Recent period    = final 24 months before forecast origin
%   Reference period = all earlier pre-origin history
%
% Final 13 modeling features:
%
%   1  ACF1
%   2  ACF6
%   3  ACF12
%   4  ACF_memory_length
%   5  Sign_persistence
%
%   6  STL_seasonality_strength
%   7  Annual_spectral_power_ratio
%   8  Seasonal_pattern_stability
%
%   9  Permutation_entropy
%   10 Spectral_entropy
%
%   11 Recent_variability_logratio
%   12 Recent_median_shift_signedlog
%   13 Distribution_shift
%
% Feature 11:
%
%     raw_ratio =
%         robust_sigma(recent24) /
%         robust_sigma(reference)
%
%     feature =
%         log(raw_ratio)
%
% Interpretation:
%     = 0 : recent variability unchanged
%     > 0 : recent variability increased
%     < 0 : recent variability decreased
%
% Feature 12:
%
%     z =
%       [median(recent24) - median(reference)]
%       --------------------------------------
%             robust_sigma(reference)
%
%     feature =
%       sign(z) * log1p(abs(z))
%
% This preserves the sign and ordering of the original standardized
% median shift while compressing extreme values caused by very small
% reference-period robust variability.
%
% No percentile clipping/winsorization is applied.
%
% Missing-data rule:
%   No interpolation.
%
%   If any value in the full pre-origin history is non-finite,
%   all 13 features for that pixel-year sample are set to NaN.
%
% Output:
%   E:\P1_SKLGB\M_manuscript2\s3_analysis\s2_dgws_features.mat
%
% Saved variable:
%   FeatureData
%
% Important:
%   FeatureData row order exactly follows:
%   s1_master_database_pixel_year.mat
%
% Sample order:
%   forecast_year -> pixel_id

