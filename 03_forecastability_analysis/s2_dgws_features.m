end

%% ----- Seasonal stability constrained to [-1,1] -----

z = ...
    X(:, 8);

z = ...
    z(isfinite(z));

if any( ...
        z < -1 - 1e-10 | ...
        z > 1 + 1e-10)

    error( ...
        'Seasonal_pattern_stability contains values outside [-1,1].');

end

%% ----- Feature 11 should be finite wherever raw ratio is positive -----

validRawRatio = ...
    isfinite(recentVariabilityRatioRaw) & ...
