    'pixel_id', ...
    'lat', ...
    'lon', ...
    'forecast_year', ...
    'forecast_origin_ym', ...
    'validLinearIndex'};

for k = 1:numel(requiredMasterFields)

    if ~isfield(Master, requiredMasterFields{k})

        error( ...
            'Master is missing required field: %s', ...
            requiredMasterFields{k});

    end

end

%% ===================== Load raw dGWS =====================

fprintf('Loading raw dGWS data...\n');

D = load( ...
    rawDataFile, ...
    'dGWS_valid', ...
    'validLinearIndex', ...
    'validLat', ...
    'validLon', ...
    'ym');

requiredRawFields = { ...
    'dGWS_valid', ...
    'validLinearIndex', ...
    'validLat', ...
    'validLon', ...
    'ym'};

for k = 1:numel(requiredRawFields)

    if ~isfield(D, requiredRawFields{k})

        error( ...
            'Raw file is missing required variable: %s', ...
            requiredRawFields{k});

    end

end

dGWS_valid = ...
    double(D.dGWS_valid);

validLinearIndex = ...
    double(D.validLinearIndex(:));

validLat = ...
    double(D.validLat(:));

validLon = ...
    double(D.validLon(:));

ymRaw = ...
    double(D.ym(:));

clear D;

[nValid, nRawMonth] = ...
    size(dGWS_valid);

nYear = ...
    numel(forecastYears);

nSample = ...
    numel(Master.pixel_id);

%% ===================== Alignment checks =====================

fprintf('Checking Master/raw-data alignment...\n');

if nSample ~= nValid * nYear

    error( ...
        ['Unexpected number of pixel-year samples: %d. ', ...
         'Expected %d x %d = %d.'], ...
        nSample, ...
        nValid, ...
        nYear, ...
        nValid * nYear);

end

if numel(ymRaw) ~= nRawMonth

    error( ...
        'Raw dGWS time dimension does not match ym.');

end

if ~isequal( ...
        double(Master.validLinearIndex(:)), ...
        validLinearIndex)

    error( ...
        'Master.validLinearIndex does not match raw data.');

end

if numel(validLat) ~= nValid || ...
        numel(validLon) ~= nValid

    error( ...
        'validLat/validLon do not match nValid.');

end

masterYears = ...
    unique(double(Master.forecast_year(:)))';

if ~isequal( ...
        masterYears, ...
        forecastYears)

    error( ...
        ['Forecast years in Master do not match expected years.\n', ...
         'Expected: %s\nFound: %s'], ...
        mat2str(forecastYears), ...
        mat2str(masterYears));

end

%% ----- Confirm complete monthly raw time axis -----

firstYear = ...
    floor(ymRaw(1) / 100);

firstMonth = ...
    mod(ymRaw(1), 100);

lastYear = ...
    floor(ymRaw(end) / 100);

lastMonth = ...
    mod(ymRaw(end), 100);

expectedRawYM = ...
    makeYMList( ...
    firstYear, ...
    firstMonth, ...
    lastYear, ...
    lastMonth);

if ~isequal( ...
        ymRaw, ...
        expectedRawYM)

    error( ...
        'Raw ym is not a complete continuous monthly sequence.');

end

