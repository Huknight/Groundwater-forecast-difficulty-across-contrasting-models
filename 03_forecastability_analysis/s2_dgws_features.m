    ['Lag-1 autocorrelation calculated using the complete ', ...
     'pre-origin dGWS history.'], ...
    ['Lag-6 autocorrelation calculated using the complete ', ...
     'pre-origin dGWS history.'], ...
    ['Lag-12 autocorrelation calculated using the complete ', ...
     'pre-origin dGWS history.'], ...
    ['Largest consecutive lag beginning at lag 1 for which ', ...
     '|ACF| >= 0.20; maximum evaluated lag = 24 months.'], ...
    ['Fraction of adjacent non-zero dGWS pairs having the same ', ...
     'sign over the complete pre-origin history.'], ...
    ['STL annual seasonality strength = ', ...
