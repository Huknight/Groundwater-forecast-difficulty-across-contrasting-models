function [features, rawVariabilityRatio, rawMedianShift] = ...
    extractDGWSFeatures( ...
    x, ...
    seasonPeriod, ...
    maxACFLag, ...
    memoryThreshold, ...
    recentWindow)

    nFeature = 13;

    features = ...
        NaN(1, nFeature);

    rawVariabilityRatio = ...
        NaN;

    rawMedianShift = ...
        NaN;

    x = ...
        double(x(:));

    n = ...
        numel(x);

    %% ----- Strict validity rule -----

    if n <= recentWindow
        return
    end

    if any(~isfinite(x))
        return
    end

    if mod(n, seasonPeriod) ~= 0
        return
    end

    %% =========================================================
    %  1-4. Autocorrelation and memory
    % ==========================================================

    acfValues = ...
        sampleACF( ...
        x, ...
        maxACFLag);

    features(1) = ...
        acfValues(1);

    features(2) = ...
        acfValues(6);

    features(3) = ...
        acfValues(12);

    if all(isfinite(acfValues))

        absACF = ...
            abs(acfValues);

        if absACF(1) < memoryThreshold

            memoryLength = ...
                0;

        else

            firstBelow = ...
                find( ...
                absACF < memoryThreshold, ...
                1, ...
                'first');

            if isempty(firstBelow)

                memoryLength = ...
                    maxACFLag;

            else

                memoryLength = ...
                    firstBelow - 1;

            end

        end

        features(4) = ...
            memoryLength;

    end

    %% =========================================================
    %  5. Sign persistence
    % ==========================================================

    s = ...
        sign(x);

    validPair = ...
        s(1:end-1) ~= 0 & ...
        s(2:end) ~= 0;

    if any(validPair)

        sameSign = ...
            s(1:end-1) == ...
            s(2:end);

        features(5) = ...
            mean( ...
            sameSign(validPair));

    end

    %% =========================================================
    %  6. STL seasonality strength
    % ==========================================================

    try

        [~, seasonal, remainder] = ...
            trenddecomp( ...
            x, ...
            "stl", ...
            seasonPeriod);

        seasonal = ...
            double(seasonal(:));

        remainder = ...
            double(remainder(:));

        denominator = ...
            var( ...
            seasonal + remainder, ...
            0);

        if isfinite(denominator) && ...
                denominator > 0

            strength = ...
                1 - ...
                var(remainder, 0) / ...
                denominator;

            strength = ...
                max( ...
                0, ...
                min(1, strength));

            features(6) = ...
                strength;

        end

    catch

        features(6) = ...
            NaN;

    end

    %% =========================================================
    %  7 + 10. Spectral features
    % ==========================================================

    [annualRatio, spectralEntropy] = ...
        calculateSpectralFeatures( ...
        x, ...
        seasonPeriod);

    features(7) = ...
        annualRatio;

    features(10) = ...
        spectralEntropy;

    %% =========================================================
    %  8. Seasonal-pattern stability
    % ==========================================================

    features(8) = ...
        seasonalPatternStability( ...
        x, ...
        seasonPeriod);

    %% =========================================================
    %  9. Permutation entropy
    % ==========================================================

    features(9) = ...
        permutationEntropyM3(x);

    %% =========================================================
    %  11-13. Recent-change features
    % ==========================================================

    reference = ...
        x(1:end-recentWindow);

    recent = ...
        x(end-recentWindow+1:end);

    sigmaReference = ...
        robustSigma(reference);

    sigmaRecent = ...
        robustSigma(recent);

    %% ----- 11. Recent variability log-ratio -----

    if isfinite(sigmaReference) && ...
            sigmaReference > 0 && ...
            isfinite(sigmaRecent)

        rawVariabilityRatio = ...
            sigmaRecent / ...
            sigmaReference;

        % Natural logarithm is valid only for positive ratios.
        if rawVariabilityRatio > 0

            features(11) = ...
                log(rawVariabilityRatio);

        end

    end

    %% ----- 12. Recent median shift: signed-log transform -----

    if isfinite(sigmaReference) && ...
            sigmaReference > 0

        rawMedianShift = ...
            ( ...
            median(recent) - ...
            median(reference) ...
            ) / ...
            sigmaReference;

        if isfinite(rawMedianShift)

            features(12) = ...
                sign(rawMedianShift) .* ...
                log1p(abs(rawMedianShift));

        end

    end

    %% ----- 13. Distribution shift -----

    features(13) = ...
        twoSampleKSStatistic( ...
        recent, ...
        reference);

end


function acfValues = sampleACF( ...
    x, ...
    maxLag)

    x = ...
        double(x(:));

    n = ...
        numel(x);

    acfValues = ...
        NaN(maxLag, 1);

    if maxLag >= n
        return
    end

    mu = ...
        mean(x);

    xc = ...
        x - mu;

    denominator = ...
        sum(xc.^2);

    if ~isfinite(denominator) || ...
            denominator <= 0

        return

    end

    for lag = 1:maxLag

        acfValues(lag) = ...
            sum( ...
            xc(1:n-lag) .* ...
            xc(1+lag:n)) / ...
            denominator;

    end

end


function sigma = robustSigma(x)

    x = ...
        double(x(:));

    if isempty(x) || ...
            any(~isfinite(x))

        sigma = ...
            NaN;

        return

    end

    medX = ...
        median(x);

    sigma = ...
        1.4826 * ...
        median( ...
        abs(x - medX));

end


function [annualRatio, spectralEntropy] = ...
    calculateSpectralFeatures( ...
    x, ...
    seasonPeriod)

    x = ...
        double(x(:));

    n = ...
        numel(x);

    annualRatio = ...
        NaN;

    spectralEntropy = ...
        NaN;

    %% ----- Remove mean -----

    x0 = ...
        x - mean(x);

    %% ----- FFT power -----

    Y = ...
        fft(x0);

    powerSpectrum = ...
        abs(Y).^2;

    positiveK = ...
        (1:floor(n / 2))';

    positivePower = ...
        powerSpectrum( ...
        positiveK + 1);

    totalPower = ...
        sum(positivePower);

    if ~isfinite(totalPower) || ...
            totalPower <= 0

        return

    end

    %% ----- Annual spectral power ratio -----

    annualKExact = ...
        n / seasonPeriod;

    if abs( ...
            annualKExact - ...
            round(annualKExact)) < 1e-12

        annualK = ...
            round(annualKExact);

        if annualK >= 1 && ...
                annualK <= floor(n / 2)

            annualPower = ...
                powerSpectrum( ...
                annualK + 1);

            annualRatio = ...
                annualPower / ...
                totalPower;

            annualRatio = ...
                max( ...
                0, ...
                min(1, annualRatio));

        end

    end

    %% ----- Spectral entropy -----

    p = ...
        positivePower / ...
        totalPower;

    p = ...
        p( ...
        isfinite(p) & ...
        p > 0);

    if isempty(p)
        return
    end

    H = ...
        -sum( ...
        p .* log(p));

    Hmax = ...
        log( ...
        numel(positivePower));

    if Hmax > 0

        spectralEntropy = ...
            H / Hmax;

        spectralEntropy = ...
            max( ...
            0, ...
            min(1, spectralEntropy));

    end

end


function stability = seasonalPatternStability( ...
    x, ...
    seasonPeriod)

    x = ...
        double(x(:));

    n = ...
        numel(x);

    stability = ...
        NaN;

    if mod(n, seasonPeriod) ~= 0
        return
    end

    nYears = ...
        n / seasonPeriod;

    if nYears < 3
        return
    end

    yearMatrix = ...
        reshape( ...
        x, ...
        seasonPeriod, ...
        nYears).';

    rValues = ...
        NaN(nYears, 1);

    for y = 1:nYears

        useYear = ...
            true(nYears, 1);

        useYear(y) = ...
            false;

        climatology = ...
            mean( ...
            yearMatrix(useYear, :), ...
            1);

        thisYear = ...
            yearMatrix(y, :);

        rValues(y) = ...
            pearsonCorrelation( ...
            thisYear, ...
            climatology);

    end

    rValues = ...
        rValues(isfinite(rValues));

    if ~isempty(rValues)

        stability = ...
            median(rValues);

    end

end


function r = pearsonCorrelation( ...
    a, ...
    b)

    a = ...
        double(a(:));

    b = ...
        double(b(:));

    r = ...
        NaN;

    if numel(a) ~= numel(b) || ...
            numel(a) < 2 || ...
            any(~isfinite(a)) || ...
            any(~isfinite(b))

        return

    end

    a = ...
        a - mean(a);

    b = ...
        b - mean(b);

    denominator = ...
        sqrt( ...
        sum(a.^2) * ...
        sum(b.^2));

    if ~isfinite(denominator) || ...
            denominator <= 0

        return

    end

    r = ...
        sum(a .* b) / ...
        denominator;

    r = ...
        max( ...
        -1, ...
        min(1, r));

end


function Hnorm = permutationEntropyM3(x)

    x = ...
        double(x(:));

    n = ...
        numel(x);

    Hnorm = ...
        NaN;

    if n < 3 || ...
            any(~isfinite(x))

        return

    end

    W = [ ...
        x(1:n-2), ...
        x(2:n-1), ...
        x(3:n)];

    [~, order] = ...
        sort( ...
        W, ...
        2, ...
        'ascend');

    codes = ...
        order(:, 1) * 100 + ...
        order(:, 2) * 10 + ...
        order(:, 3);

    possibleCodes = ...
        [123, 132, 213, 231, 312, 321];

    counts = ...
        zeros(6, 1);

    for k = 1:6

        counts(k) = ...
            sum( ...
            codes == possibleCodes(k));

    end

    totalCount = ...
        sum(counts);

    if totalCount <= 0
        return
    end

    p = ...
        counts / ...
        totalCount;

    p = ...
        p(p > 0);

    H = ...
        -sum( ...
        p .* log(p));

    Hnorm = ...
        H / log(6);

    Hnorm = ...
        max( ...
        0, ...
        min(1, Hnorm));

end


function D = twoSampleKSStatistic( ...
    x, ...
    y)

    x = ...
        double(x(:));

    y = ...
        double(y(:));

    D = ...
        NaN;

    if isempty(x) || ...
            isempty(y) || ...
            any(~isfinite(x)) || ...
            any(~isfinite(y))

        return

    end

    nx = ...
        numel(x);

    ny = ...
        numel(y);

    combined = ...
        [x; y];

    [~, ~, group] = ...
        unique(combined);

    nGroup = ...
        max(group);

    countX = ...
        accumarray( ...
        group(1:nx), ...
        1, ...
        [nGroup, 1]);

    countY = ...
        accumarray( ...
        group(nx+1:end), ...
        1, ...
        [nGroup, 1]);

    Fx = ...
        cumsum(countX) / nx;

    Fy = ...
        cumsum(countY) / ny;

    D = ...
        max( ...
        abs(Fx - Fy));

    D = ...
        max( ...
        0, ...
        min(1, D));

end


