     'pattern calculated from all other pre-origin years.'], ...
    ['Normalized permutation entropy using embedding dimension ', ...
     'm=3 and delay tau=1.'], ...
    ['Normalized Shannon entropy of the positive-frequency power ', ...
     'spectrum after removal of the mean.'], ...
    ['Natural logarithm of robust_sigma(recent 24 months) divided ', ...
     'by robust_sigma(all earlier pre-origin months).'], ...
    ['Signed log transform of the standardized median difference: ', ...
     'sign(z)*log1p(abs(z)), where z=(median(recent24)-', ...
     'median(reference))/robust_sigma(reference).'], ...
    ['Two-sample Kolmogorov-Smirnov D statistic comparing the ', ...
     'final 24 months with all earlier pre-origin history.']};

nFeature = numel(featureNames);

