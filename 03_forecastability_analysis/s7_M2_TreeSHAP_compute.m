        NaN(nFeature,1);


    for j = 1:nFeature


        fullData = ...
            Xfull(:,j);


        bgData = ...
            Xbackground(:,j);


        qFull = ...
            prctile( ...
            fullData, ...
            [1 5 25 50 75 95 99]);


