function modelFile = ...
    locateM2ModelFile( ...
    modelFolder, ...
    testYear, ...
    modelName)


    safeModel = ...
        matlab.lang.makeValidName( ...
        modelName);


    %% --------------------------------------------------------
    % Try likely exact names first.
    % ---------------------------------------------------------

    candidateNames = { ...
        sprintf( ...
        'RFmeta_M2_%d_%s.mat', ...
        testYear, ...
        safeModel), ...
        ...
        sprintf( ...
        'RFmeta_%d_%s.mat', ...
        testYear, ...
        safeModel)};


    for i = 1:numel(candidateNames)


        candidate = ...
            fullfile( ...
            modelFolder, ...
            candidateNames{i});


        if exist(candidate,'file')

            modelFile = ...
                candidate;

            return

        end

    end


    %% --------------------------------------------------------
    % If file naming differs, search all MATs and inspect
    % ModelInfo rather than guessing.
    % ---------------------------------------------------------

    files = ...
        dir( ...
        fullfile( ...
        modelFolder, ...
        '*.mat'));


    matchedFiles = ...
        cell(0,1);


    for i = 1:numel(files)


        thisFile = ...
            fullfile( ...
            files(i).folder, ...
            files(i).name);


        try


            info = ...
                load( ...
                thisFile, ...
                'ModelInfo');


            if ~isfield(info,'ModelInfo')

                continue

            end


            MI = ...
                info.ModelInfo;


            if ~isfield(MI,'target_model') || ...
                    ~isfield(MI,'test_year')

                continue

            end


            if strcmp( ...
                    string(MI.target_model), ...
                    string(modelName)) && ...
                    double(MI.test_year) == ...
                    testYear


                matchedFiles{end+1,1} = ...
                    thisFile; %#ok<AGROW>

            end


        catch

            continue

        end

    end


    if isempty(matchedFiles)

        error( ...
            ['Could not locate M2 CompactRF for:\n', ...
             'Target   : %s\n', ...
             'Test year: %d\n', ...
             'Folder   : %s'], ...
            modelName, ...
            testYear, ...
            modelFolder);

    end


    if numel(matchedFiles) > 1

        fprintf('\nMultiple model files matched:\n');

        disp(matchedFiles);

        error( ...
            ['More than one M2 model file matches ', ...
             '%s / %d.'], ...
            modelName, ...
            testYear);

    end


    modelFile = ...
        matchedFiles{1};


end


function [CompactRF,ModelInfo] = ...
    loadAndVerifyM2Model( ...
    modelFile, ...
    expectedTarget, ...
    expectedYear, ...
    expectedFeatureNames, ...
    expectedNTrees)


    S = ...
        load( ...
        modelFile, ...
        'CompactRF', ...
        'ModelInfo');


    if ~isfield(S,'CompactRF')

        error( ...
            'CompactRF missing:\n%s', ...
            modelFile);

    end


    if ~isfield(S,'ModelInfo')

        error( ...
            'ModelInfo missing:\n%s', ...
            modelFile);

    end


    CompactRF = ...
        S.CompactRF;


    ModelInfo = ...
        S.ModelInfo;


    if ~isfield(ModelInfo,'target_model') || ...
            string(ModelInfo.target_model) ~= ...
            string(expectedTarget)

        error( ...
            'M2 target-model mismatch:\n%s', ...
            modelFile);

    end


    if ~isfield(ModelInfo,'test_year') || ...
            double(ModelInfo.test_year) ~= ...
            expectedYear

        error( ...
            'M2 test-year mismatch:\n%s', ...
            modelFile);

    end


    if ~isfield(ModelInfo,'feature_names')

