    if ~isequal( ...
            storedFeatureNames, ...
            expectedFeatureNames)

        error( ...
            'M2 saved RF feature order mismatch:\n%s', ...
            modelFile);

    end


    if CompactRF.NumTrees ~= ...
            expectedNTrees

        error( ...
            ['Expected %d trees; found %d:\n%s'], ...
            expectedNTrees, ...
            CompactRF.NumTrees, ...
            modelFile);

    end


    if string(CompactRF.Method) ~= ...
            "regression"

        error( ...
            'M2 saved RF is not a regression forest.');

    end


    for t = 1:CompactRF.NumTrees


        thisClass = ...
            string( ...
            class( ...
            CompactRF.Trees{t}));


        if thisClass ~= ...
                "classreg.learning.regr.CompactRegressionTree" && ...
                thisClass ~= ...
                "CompactRegressionTree"

            error( ...
                ['Unexpected M2 learner class in ', ...
                 'tree %d:\n%s'], ...
                t, ...
                thisClass);

        end

    end


end


function [ ...
    EnsembleSHAP, ...
    EnsembleIntercept, ...
    TreeIntercept, ...
    MethodAudit, ...
    RuntimeMinutes] = ...
    computeEnsembleTreeSHAP( ...
    Trees, ...
    Xbackground, ...
    Xquery, ...
    supportsNumObservationsToSample)


    nTrees = ...
        numel(Trees);


    nQuery = ...
        size(Xquery,1);


    nFeature = ...
        size(Xquery,2);


    %% --------------------------------------------------------
    % M2 at 5000 queries:
    %
    % 5000 x 24 x 500 doubles
    %
    % approximately 480 MB client-side temporary storage.
    % ---------------------------------------------------------

    TreeSHAP = ...
        NaN( ...
        nQuery, ...
        nFeature, ...
        nTrees);


    TreeIntercept = ...
        NaN(nTrees,1);


    TreeMethod = ...
        strings(nTrees,1);


    timerAll = ...
        tic;


    parfor t = 1:nTrees


        thisTree = ...
            Trees{t};


        %% ----------------------------------------------------
        % DO NOT specify MaxNumSubsets.
        % -----------------------------------------------------

        if supportsNumObservationsToSample


            explainer = ...
                shapley( ...
                thisTree, ...
                Xbackground, ...
                'Method', ...
                'interventional', ...
                'NumObservationsToSample', ...
                'all');


        else


            %% Current R2024a path.

            explainer = ...
                shapley( ...
                thisTree, ...
                Xbackground, ...
                'Method', ...
                'interventional');

        end


        fitted = ...
            fit( ...
            explainer, ...
            Xquery, ...
            'Method', ...
            'interventional', ...
            'UseParallel', ...
            false);


        TreeSHAP(:,:,t) = ...
            extractRegressionSHAP( ...
            fitted, ...
            nFeature, ...
            nQuery);


        TreeIntercept(t) = ...
            double( ...
            fitted.Intercept);


        TreeMethod(t) = ...
            string( ...
            fitted.Method);

    end


    RuntimeMinutes = ...
        toc(timerAll) / ...
        60;


    EnsembleSHAP = ...
        mean( ...
        TreeSHAP, ...
        3);


    EnsembleIntercept = ...
        mean( ...
        TreeIntercept);


    MethodAudit = ...
        struct();


    MethodAudit.TreeMethod = ...
        TreeMethod;


    MethodAudit.AllInterventionalTree = ...
        all( ...
        TreeMethod == ...
        "interventional-tree");


    MethodAudit.NumberInterventionalTree = ...
        sum( ...
        TreeMethod == ...
        "interventional-tree");


end


function SHAPValues = ...
    extractRegressionSHAP( ...
    fittedExplainer, ...
    nFeature, ...
    nQuery)


    if isprop( ...
            fittedExplainer, ...
            'Shapley')


        T = ...
            fittedExplainer.Shapley;


    elseif isprop( ...
            fittedExplainer, ...
            'ShapleyValues')


        T = ...
            fittedExplainer.ShapleyValues;


    else


        error( ...
            'Could not locate SHAP-value property.');

    end


    if isempty(T)

        error( ...
            'SHAP table is empty.');

    end


    variableNames = ...
        T.Properties.VariableNames;


    if ismember( ...
            'Value', ...
            variableNames)


        V = ...
            T.Value;


    elseif ismember( ...
            'ShapleyValue', ...
            variableNames)


        V = ...
            T.ShapleyValue;


    else


        V = ...
            T{:,2:end};

    end


    if iscell(V)

        V = ...
            cell2mat(V);

    end


    V = ...
        double(V);


    if size(V,1) == nFeature && ...
            size(V,2) == nQuery


        SHAPValues = ...
            V';


    elseif size(V,1) == nQuery && ...
            size(V,2) == nFeature


        SHAPValues = ...
            V;


    elseif nQuery == 1 && ...
            numel(V) == nFeature


        SHAPValues = ...
            V(:)';


    else


        error( ...
            ['Unexpected M2 SHAP dimensions.\n', ...
             'Found    : %d x %d\n', ...
             'Features : %d\n', ...
             'Queries  : %d'], ...
            size(V,1), ...
            size(V,2), ...
            nFeature, ...
            nQuery);

    end


    if any(~isfinite(SHAPValues(:)))

        error( ...
            'Non-finite M2 SHAP values detected.');

    end


end


