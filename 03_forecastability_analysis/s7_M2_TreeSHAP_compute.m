function [AuditTable,Summary] = ...
    auditBackgroundRepresentativeness( ...
    Xfull, ...
    Xbackground, ...
    featureNames)


    nFeature = ...
        size(Xfull,2);


    FeatureID = ...
        (1:nFeature)';


    FeatureName = ...
        featureNames(:);


