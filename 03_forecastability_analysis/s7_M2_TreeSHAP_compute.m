%% s7_M2_TreeSHAP_compute.m
%
% ============================================================
% FORMAL M2 EXACT TREE-SHAP COMPUTATION
% ============================================================
%
% M2:
%
%   24 pre-origin hydroclimatic features
%               ->
%   RF forecastability meta-model
%               ->
%   predicted log1p(NRMSE_Q10Q90)
%
%
% ============================================================
% OUTER TEST DESIGN
% ============================================================
%
% train 2019-2021 -> explain 2022
% train 2019-2022 -> explain 2023
% train 2019-2023 -> explain 2024
%
% 9 forecast-model targets:
%
%   AR
%   ARIMA
%   SARIMA
%   SVM
%   RF
%   LSTM
%   SVMX
%   RFX
%   LSTMX
%
% Total:
%
%   3 years x 9 targets = 27 RF meta-models
%
%
% ============================================================
% SHAP METHOD
% ============================================================
%
% Each CompactTreeBagger contains 500 CompactRegressionTree
% learners.
%
% Exact Tree SHAP is calculated separately for each tree:
%
%   phi_RF =
%       mean(phi_tree_1,...,phi_tree_500)
%
% and:
%
%   intercept_RF =
%       mean(intercept_tree_1,...,intercept_tree_500)
%
%
% IMPORTANT:
%
% NO MaxNumSubsets is specified.
%
% This preserves native exact:
%
%   interventional-tree
%
%
% ============================================================
% FORMAL SETTINGS
% ============================================================
%
% Initial workers:
%
%   15
%
% Background:
%
%   SAME BG300 ROWS AS FORMAL M1 SHAP
%
% Foreground:
%
%   ALL 17,284 independent outer-test pixels
%
% Initial query batch:
%
%   5000 pixels
%
%
% ============================================================
% BACKGROUND DESIGN
% ============================================================
%
% M2 DOES NOT DRAW A NEW BACKGROUND.
%
% It directly loads:
%
%   s7_M1_TreeSHAP_outputs\
%       backgrounds\
%       M1_TreeSHAP_Background_2022.mat
%
%   M1_TreeSHAP_Background_2023.mat
%
%   M1_TreeSHAP_Background_2024.mat
%
% and uses:
%
%   Background.rows
%
% Therefore:
%
%   B_M1 = B_M2
%
% at the pixel-year row level.
%
% The same background is shared by all nine target RFs
% within each test year.
%
%
% A NEW representativeness audit is performed on the
% 24-dimensional M2 hydro feature space.
%
%
% ============================================================
% SHAP SIGN
% ============================================================
%
% Target:
%
%   log1p(NRMSE)
%
% Therefore:
%
%   SHAP > 0
%       -> pushes predicted future forecast error upward
%       -> worse forecastability
%
%   SHAP < 0
%       -> pushes predicted future forecast error downward
%       -> better forecastability
%
%
% ============================================================
% M2 MECHANISM GROUPS
% ============================================================
%
% 1 Hydroclimatic background
%
%   P_LongTermMean
%   ET_LongTermMean
%   Runoff_LongTermMean
%   T_LongTermMean
%
%
% 2 Long-term variability
%
%   P_RobustSpread
%   ET_RobustSpread
%   Runoff_RobustSpread
%   T_RobustSpread
%   dSM_RobustSpread
%
%
% 3 Seasonality
%
%   P_SeasonalityStrength
%   ET_SeasonalityStrength
%   Runoff_SeasonalityStrength
%   T_SeasonalityStrength
%   dSM_SeasonalityStrength
%
%
% 4 Recent state
%
%   P_RecentLevelShift
%   P_RecentVariability
%
%   ET_RecentLevelShift
%   ET_RecentVariability
%
%   Runoff_RecentLevelShift
%   Runoff_RecentVariability
%
%   T_RecentLevelShift
%   T_RecentVariability
%
%   dSM_RecentTendency
%   dSM_RecentVariability
%
%
% Group sizes:
%
%   4 / 5 / 5 / 10
%
%
% ============================================================
% SECONDARY VARIABLE GROUPS
% ============================================================
%
% P       : features  1-5
% ET      : features  6-10
% Runoff  : features 11-15
% T       : features 16-20
% dSM     : features 21-24
%
%
% This is a SECONDARY partition of the same 24 SHAP features.
%
% Mechanism shares and variable shares must therefore NOT be
% added together.
%
%
% ============================================================
% LOCAL GROUP ATTRIBUTION
% ============================================================
%
% Mechanism signed SHAP:
%
%   MechanismSigned(i,g) =
%       sum_j in mechanism g phi(i,j)
%
%
% Mechanism absolute attribution:
%
%   MechanismAbs(i,g) =
%       sum_j in mechanism g |phi(i,j)|
%
%
% Variable signed SHAP:
%
%   VariableSigned(i,v) =
%       sum_j in variable v phi(i,j)
%
%
% Variable absolute attribution:
%
%   VariableAbs(i,v) =
%       sum_j in variable v |phi(i,j)|
%
%
% ============================================================
% GLOBAL IMPORTANCE
% ============================================================
%
% Feature:
%
%   I_j =
%       mean_i |phi(i,j)|
%
%
% Normalized feature share:
%
%   R_j =
%       I_j / sum_k I_k
%
%
% Mechanism share:
%
%   R_g =
%       sum_j in g I_j / sum_all I_j
%
%
% Variable share:
%
%   R_v =
%       sum_j in v I_j / sum_all I_j
%
%
% Also save:
%
%   group attribution / number of features
%
% to avoid group-size interpretation artifacts.
%
%
% ============================================================
% MEMORY SAFETY
% ============================================================
%
% Initial:
%
%   workers = 15
%   batch   = 5000
%
% If a genuine memory/deserialization failure occurs:
%
% Batch:
%
%   5000 -> 2500 -> 1000 -> 500
%
% Then workers:
%
%   15 -> 12 -> 8 -> 4 -> 2
%
% Scientific definition, samples and background NEVER change.
%
%
% ============================================================
% CHECKPOINT / RESUME
% ============================================================
%
% Each model-year raw MAT stores:
%
%   CompletedThrough
%
% Every successful query batch is immediately written to disk.
%
% An interrupted run resumes from the first unfinished pixel.
%
% ============================================================

