function ensureParallelPool(nWorkers)


    cluster = ...
        parcluster('local');


    if cluster.NumWorkers < nWorkers

        error( ...
            ['Local cluster supports only %d workers, ', ...
             'but %d were requested.'], ...
            cluster.NumWorkers, ...
            nWorkers);

    end


    pool = ...
        gcp('nocreate');


    if ~isempty(pool) && ...
            pool.NumWorkers ~= ...
            nWorkers


        fprintf( ...
            ['Restarting parallel pool: ', ...
             '%d -> %d workers.\n'], ...
            pool.NumWorkers, ...
            nWorkers);


        delete(pool);


        pool = ...
            [];

    end


    if isempty(pool)


        fprintf( ...
            'Starting parallel pool with %d workers...\n', ...
            nWorkers);


        pool = ...
            parpool( ...
            'local', ...
            nWorkers);


        if pool.NumWorkers ~= nWorkers

            error( ...
                ['Requested %d workers but MATLAB ', ...
                 'started %d.'], ...
                nWorkers, ...
                pool.NumWorkers);

        end

    end


end


