                         'Residual = %.12g'], ...
                        mechanismPartitionResidual);

                end


                if hydroVariablePartitionResidual > ...
                        groupAdditivityTolerance

                    error( ...
                        ['M3 hydro-variable partition failed.\n', ...
                         'Residual = %.12g'], ...
                        hydroVariablePartitionResidual);

                end


                %% --------------------------------------------
                % WRITE RAW RESULTS
                % ---------------------------------------------

                rawMat.SHAPValues( ...
                    localIndex, ...
                    :) = ...
                    batchSHAP;


                rawMat.DomainSignedSHAP( ...
                    localIndex, ...
                    :) = ...
                    domainSignedBatch;


                rawMat.DomainAbsAttribution( ...
                    localIndex, ...
                    :) = ...
                    domainAbsBatch;


                rawMat.MechanismSignedSHAP( ...
                    localIndex, ...
                    :) = ...
                    mechanismSignedBatch;


                rawMat.MechanismAbsAttribution( ...
                    localIndex, ...
                    :) = ...
                    mechanismAbsBatch;


                rawMat.HydroVariableSignedSHAP( ...
                    localIndex, ...
                    :) = ...
                    hydroVariableSignedBatch;


                rawMat.HydroVariableAbsAttribution( ...
                    localIndex, ...
                    :) = ...
                    hydroVariableAbsBatch;


                %% --------------------------------------------
                % Batch log
                % ---------------------------------------------

                successfulBatchCount = ...
                    successfulBatchCount + ...
                    1;


                if successfulBatchCount > ...
                        maxBatchRecords

                    error( ...
                        'M3 batch-log overflow.');

                end


                rawMat.BatchStart( ...
                    successfulBatchCount,1) = ...
                    firstIndex;


                rawMat.BatchEnd( ...
                    successfulBatchCount,1) = ...
                    finalIndex;


                rawMat.BatchSizeUsed( ...
                    successfulBatchCount,1) = ...
                    numel(localIndex);


                rawMat.BatchWorkersUsed( ...
                    successfulBatchCount,1) = ...
                    currentWorkers;


                rawMat.BatchRuntimeMinutes( ...
                    successfulBatchCount,1) = ...
                    batchRuntimeMinutes;


                rawMat.BatchMaxAdditivityResidual( ...
                    successfulBatchCount,1) = ...
                    maxResidual;


                rawMat.BatchMeanAdditivityResidual( ...
                    successfulBatchCount,1) = ...
                    meanResidual;


                rawMat.BatchInterceptDifference( ...
                    successfulBatchCount,1) = ...
                    interceptDifference;


                %% --------------------------------------------
                % Checkpoint
                % ---------------------------------------------

                completedThrough = ...
                    finalIndex;


                rawMat.CompletedThrough = ...
                    completedThrough;


                rawMat.CurrentBatchSize = ...
                    currentBatchSize;


                rawMat.CurrentWorkers = ...
                    currentWorkers;


                rawMat.SuccessfulBatchCount = ...
                    successfulBatchCount;


                fprintf( ...
                    ['SUCCESS | %.3f min | ', ...
                     'max residual %.3e | ', ...
                     'completed %d/%d (%.1f%%)\n'], ...
                    batchRuntimeMinutes, ...
                    maxResidual, ...
                    completedThrough, ...
                    nTest, ...
                    100 * ...
                    completedThrough / ...
                    nTest);


