                        ['Retrying with %d workers and ', ...
                         'batch size %d.\n'], ...
                        currentWorkers, ...
                        currentBatchSize);


                    ensureParallelPool( ...
                        currentWorkers);


                    continue

                end


                fprintf( ...
                    '\nNo further M3 memory fallback remains.\n');


                rethrow(ME);

            end

        end


        %% ====================================================
        % 22.4.6 COMPLETE MODEL-YEAR
        % ====================================================

        rawMat.Completed = ...
            true;


        completedBatchRuntime = ...
            rawMat.BatchRuntimeMinutes( ...
            1:successfulBatchCount, ...
