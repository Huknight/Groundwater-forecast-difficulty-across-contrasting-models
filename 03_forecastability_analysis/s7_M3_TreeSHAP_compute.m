%% s7_M3_TreeSHAP_compute.m
%
% ============================================================
% FORMAL M3 EXACT TREE-SHAP COMPUTATION
% ============================================================
%
% M3:
%
%   13 pre-origin dGWS features
%              +
%   24 pre-origin hydroclimatic features
%              =
%   37 predictors
%
%              ->
%
%   RF forecastability meta-model
%
%              ->
%
%   predicted log1p(NRMSE_Q10Q90)
%
%
% ============================================================
% OUTER TEST DESIGN
% ============================================================
%
% train 2019-2021 -> explain 2022
% train 2019-2022 -> explain 2023
% train 2019-2023 -> explain 2024
%
% Nine forecast-model targets:
%
%   AR
%   ARIMA
%   SARIMA
%   SVM
%   RF
%   LSTM
%   SVMX
%   RFX
%   LSTMX
%
% Total:
%
%   3 years x 9 targets = 27 RF meta-models
%
%
% ============================================================
% SHAP METHOD
% ============================================================
%
% Each saved CompactTreeBagger contains:
%
%   500 CompactRegressionTree learners
%
% Exact interventional Tree SHAP is calculated separately
% for each tree:
%
%   phi_RF =
%       mean(phi_tree_1,...,phi_tree_500)
%
% and:
%
%   intercept_RF =
%       mean(intercept_tree_1,...,intercept_tree_500)
%
%
% IMPORTANT:
%
% NO MaxNumSubsets is specified anywhere.
%
% Therefore MATLAB can use native:
%
%   interventional-tree
%
%
% ============================================================
% FORMAL COMPUTATIONAL SETTINGS
% ============================================================
%
% Initial workers:
%
%   15
%
% Background:
%
%   SAME BG300 ROWS AS FORMAL M1 SHAP
%
% Foreground:
%
%   ALL 17,284 outer-test pixels
%
% Initial query batch:
%
%   5000 pixels
%
%
% ============================================================
% BACKGROUND
% ============================================================
%
% M3 DOES NOT DRAW NEW BACKGROUNDS.
%
% It loads:
%
%   M1_TreeSHAP_Background_2022.mat
%   M1_TreeSHAP_Background_2023.mat
%   M1_TreeSHAP_Background_2024.mat
%
% and reuses:
%
%   Background.rows
%
% Therefore:
%
%   B_M1 = B_M2 = B_M3
%
% at the pixel-year row level.
%
%
% A NEW representativeness audit is performed in the complete
% 37-dimensional M3 feature space.
%
%
% ============================================================
% M3 HIERARCHICAL ATTRIBUTION
% ============================================================
%
% LEVEL 1 — DOMAIN
%
%   1 dGWS
%       features 1-13
%
%   2 Hydroclimate
%       features 14-37
%
%
% LEVEL 2 — DOMAIN-SPECIFIC MECHANISMS
%
% dGWS:
%
%   1 dGWS_Memory_persistence
%   2 dGWS_Seasonal_spectral
%   3 dGWS_Local_complexity
%   4 dGWS_Recent_state
%
% Hydro:
%
%   5 Hydro_Hydroclimatic_background
%   6 Hydro_LongTerm_variability
%   7 Hydro_Seasonality
%   8 Hydro_Recent_state
%
%
% LEVEL 3 — 37 INDIVIDUAL FEATURES
%
%
% ============================================================
% SECONDARY HYDRO VARIABLE GROUPING
% ============================================================
%
% Hydro features are additionally partitioned by variable:
%
%   P
%   ET
%   Runoff
%   T
%   dSM
%
% This is an alternative grouping of the 24 hydro features.
%
% It must NOT be added to the mechanism grouping.
%
%
% ============================================================
% TOTAL vs WITHIN-DOMAIN SHARES
% ============================================================
%
% For each feature/mechanism:
%
% TOTAL SHARE:
%
%   I_j / I_all37
%
% answers:
%
%   How much of total M3 attribution is assigned here?
%
%
% WITHIN-DOMAIN SHARE:
%
%   I_j / I_domain
%
% answers:
%
%   Conditional on dGWS or Hydro attribution, how is that
%   domain internally structured?
%
%
% This is essential for:
%
%   M1 dGWS structure
%       vs
%   M3 dGWS-within-domain structure
%
% and:
%
%   M2 Hydro structure
%       vs
%   M3 Hydro-within-domain structure
%
%
% ============================================================
% INTERPRETATION WARNING
% ============================================================
%
% Hydroclimate domain SHAP share in M3 is NOT interpreted as:
%
%   independent hydro contribution
%
% or:
%
%   percentage of incremental M3-M1 skill.
%
% Incremental information is assessed separately by the
% paired M3-vs-M1 performance comparison.
%
% M3 SHAP only describes how the fitted combined RF uses the
% available predictors.
%
%
% ============================================================
% SHAP SIGN
% ============================================================
%
% Target:
%
%   log1p(NRMSE)
%
% SHAP > 0:
%
%   pushes predicted future error upward
%   -> worse forecastability
%
% SHAP < 0:
%
%   pushes predicted future error downward
%   -> better forecastability
%
%
% ============================================================
% MEMORY SAFETY
% ============================================================
%
% Initial:
%
%   workers = 15
%   batch   = 5000
%
% If memory/deserialization failure:
%
%   batch:
%       5000 -> 2500 -> 1000 -> 500
%
% If still unsuccessful:
%
%   workers:
%       15 -> 12 -> 8 -> 4 -> 2
%
% Background, foreground, model and SHAP definition
% never change.
%
%
% ============================================================
% CHECKPOINT
% ============================================================
%
% Every successful foreground batch is written immediately
% into a v7.3 MAT file.
%
% Interrupted runs resume from:
%
%   CompletedThrough + 1
%
% ============================================================

