function [ ...
    EnsembleSHAP, ...
    EnsembleIntercept, ...
    TreeIntercept, ...
    MethodAudit, ...
    RuntimeMinutes] = ...
    computeEnsembleTreeSHAP( ...
    Trees, ...
    Xbackground, ...
    Xquery, ...
    supportsNumObservationsToSample)


    nTrees = ...
        numel(Trees);


    nQuery = ...
        size(Xquery,1);


    nFeature = ...
        size(Xquery,2);


    %% --------------------------------------------------------
    % At Nquery=5000:
    %
    % 5000 x 37 x 500 doubles
    %
    % approximately 740 MB for this client-side array.
    % ---------------------------------------------------------

    TreeSHAP = ...
        NaN( ...
        nQuery, ...
        nFeature, ...
        nTrees);


    TreeIntercept = ...
        NaN(nTrees,1);


    TreeMethod = ...
        strings(nTrees,1);


    timerAll = ...
        tic;


    parfor t = 1:nTrees


        thisTree = ...
            Trees{t};


        %% ----------------------------------------------------
        % NO MaxNumSubsets.
        % -----------------------------------------------------

        if supportsNumObservationsToSample


            explainer = ...
                shapley( ...
                thisTree, ...
                Xbackground, ...
                'Method', ...
                'interventional', ...
                'NumObservationsToSample', ...
                'all');


        else


            %% MATLAB R2024a

            explainer = ...
                shapley( ...
                thisTree, ...
                Xbackground, ...
                'Method', ...
                'interventional');

        end


        %% Outer tree loop is already parallel.
        %
        % Never create nested SHAP parallelism.

        fitted = ...
            fit( ...
            explainer, ...
            Xquery, ...
            'Method', ...
            'interventional', ...
            'UseParallel', ...
            false);


        TreeSHAP(:,:,t) = ...
            extractRegressionSHAP( ...
            fitted, ...
            nFeature, ...
            nQuery);


        TreeIntercept(t) = ...
            double( ...
            fitted.Intercept);


        TreeMethod(t) = ...
            string( ...
            fitted.Method);

    end


    RuntimeMinutes = ...
        toc(timerAll) / ...
        60;


    EnsembleSHAP = ...
        mean( ...
        TreeSHAP, ...
        3);


    EnsembleIntercept = ...
        mean( ...
        TreeIntercept);


    MethodAudit = ...
        struct();


    MethodAudit.TreeMethod = ...
        TreeMethod;


    MethodAudit.AllInterventionalTree = ...
        all( ...
        TreeMethod == ...
        "interventional-tree");


    MethodAudit.NumberInterventionalTree = ...
        sum( ...
        TreeMethod == ...
        "interventional-tree");


end


function SHAPValues = ...
    extractRegressionSHAP( ...
    fittedExplainer, ...
    nFeature, ...
    nQuery)


    if isprop( ...
            fittedExplainer, ...
            'Shapley')


        T = ...
            fittedExplainer.Shapley;


    elseif isprop( ...
            fittedExplainer, ...
            'ShapleyValues')


        T = ...
            fittedExplainer.ShapleyValues;


    else


        error( ...
            'Could not locate SHAP-value property.');

    end


    if isempty(T)

        error( ...
            'M3 SHAP table is empty.');

    end


    variableNames = ...
        T.Properties.VariableNames;


    if ismember( ...
            'Value', ...
            variableNames)


        V = ...
            T.Value;


    elseif ismember( ...
            'ShapleyValue', ...
            variableNames)


        V = ...
            T.ShapleyValue;


    else


        V = ...
            T{:,2:end};

    end


    if iscell(V)

        V = ...
            cell2mat(V);

    end


    V = ...
        double(V);


    if size(V,1) == nFeature && ...
            size(V,2) == nQuery


        SHAPValues = ...
            V';


    elseif size(V,1) == nQuery && ...
            size(V,2) == nFeature


        SHAPValues = ...
            V;


    elseif nQuery == 1 && ...
            numel(V) == nFeature


        SHAPValues = ...
            V(:)';


    else


        error( ...
            ['Unexpected M3 SHAP dimensions.\n', ...
             'Found    : %d x %d\n', ...
             'Features : %d\n', ...
             'Queries  : %d'], ...
            size(V,1), ...
            size(V,2), ...
            nFeature, ...
            nQuery);

    end


    if any(~isfinite(SHAPValues(:)))

        error( ...
            'Non-finite M3 SHAP values detected.');

    end


end


function [GroupSigned,GroupAbs] = ...
    computeLocalGroups( ...
    SHAPValues, ...
    groupID, ...
    nGroup)


    nSample = ...
        size(SHAPValues,1);


    GroupSigned = ...
        zeros( ...
        nSample, ...
        nGroup);


    GroupAbs = ...
        zeros( ...
        nSample, ...
        nGroup);


    for g = 1:nGroup


        idx = ...
            groupID == ...
            g;


        if ~any(idx)

            error( ...
                'Empty SHAP group %d.', ...
                g);

        end


        GroupSigned(:,g) = ...
            sum( ...
            SHAPValues(:,idx), ...
            2);


        GroupAbs(:,g) = ...
            sum( ...
            abs( ...
            SHAPValues(:,idx)), ...
            2);

    end


end


