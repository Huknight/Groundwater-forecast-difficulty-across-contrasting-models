%% Step 2: Build hydroclimatic features for forecastability meta-model
% File name:
%   s2_dgws_features_hydro.m
%
% Purpose:
%   Construct 24 pre-origin hydroclimatic meta-features for
%   each pixel x forecast-year sample.
%
% Output:
%   s2_dgws_features_hydro.mat
%
% ============================================================
% SAMPLE DEFINITION
% ============================================================
%
% One sample = one valid grid cell x one forecast year.
%
% Forecast years:
%
%   2019 2020 2021 2022 2023 2024
%
% Expected:
%
%   17284 pixels x 6 years = 103704 samples
%
% Final feature matrix:
%
%   103704 x 24
%
%
% ============================================================
% FORECAST-ORIGIN CONSTRAINT
% ============================================================
%
% All features use ONLY information available before forecast
% origin.
%
% Forecast 2019:
%   history = 2004-01 : 2018-12
%
% Forecast 2020:
%   history = 2004-01 : 2019-12
%
% Forecast 2021:
%   history = 2004-01 : 2020-12
%
% Forecast 2022:
%   history = 2004-01 : 2021-12
%
% Forecast 2023:
%   history = 2004-01 : 2022-12
%
% Forecast 2024:
%   history = 2004-01 : 2023-12
%
%
% ============================================================
% RECENT / REFERENCE WINDOWS
% ============================================================
%
% Recent:
%   last 24 pre-origin months
%
% Reference:
%   all earlier pre-origin months
%
% Example:
%
% Forecast 2024:
%
%   reference = 2004-01 : 2021-12
%   recent    = 2022-01 : 2023-12
%
%
% ============================================================
% FINAL 24 FEATURES
% ============================================================
%
% Precipitation:
%
%   1  P_LongTermMean
%   2  P_RobustSpread
%   3  P_SeasonalityStrength
%   4  P_RecentLevelShift
%   5  P_RecentVariability
%
%
% Evapotranspiration:
%
%   6  ET_LongTermMean
%   7  ET_RobustSpread
%   8  ET_SeasonalityStrength
%   9  ET_RecentLevelShift
%  10  ET_RecentVariability
%
%
% Runoff:
%
%  11  Runoff_LongTermMean
%  12  Runoff_RobustSpread
%  13  Runoff_SeasonalityStrength
%  14  Runoff_RecentLevelShift
%  15  Runoff_RecentVariability
%
%
% Surface temperature:
%
%  16  T_LongTermMean
%  17  T_RobustSpread
%  18  T_SeasonalityStrength
%  19  T_RecentLevelShift
%  20  T_RecentVariability
%
%
% Soil-moisture change:
%
%  21  dSM_RobustSpread
%  22  dSM_SeasonalityStrength
%  23  dSM_RecentTendency
%  24  dSM_RecentVariability
%
%
% ============================================================
% ROBUST SPREAD
% ============================================================
%
% For any series x:
%
%   S(x) = Q90(x) - Q10(x)
%
% This replaces MAD-based RobustSigma because precipitation,
% runoff and soil-moisture-change series can contain many zero
% or near-identical values.
%
%
% ============================================================
% SEASONALITY STRENGTH
% ============================================================
%
% STL decomposition:
%
%   period = 12 months
%
% strength =
%
%   1 - Var(remainder) / Var(seasonal + remainder)
%
% constrained to:
%
%   [0, 1]
%
%
% ============================================================
% RECENT LEVEL SHIFT
% ============================================================
%
% For P / ET / Runoff / T:
%
%   Sall = Q90(history) - Q10(history)
%
%   z =
%
%     median(recent) - median(reference)
%     ----------------------------------
%                   Sall
%
%   RecentLevelShift =
%
%     sign(z) * log1p(abs(z))
%
% If Sall == 0:
%
%   RecentLevelShift = 0
%
%
% ============================================================
% RECENT VARIABILITY
% ============================================================
%
% Define:
%
%   Sall    = Q90(history)   - Q10(history)
%   Srecent = Q90(recent)    - Q10(recent)
%   Sref    = Q90(reference) - Q10(reference)
%
% Then:
%
%   RecentVariability =
%
%       log(1 + Srecent/Sall)
%       -
%       log(1 + Sref/Sall)
%
% Interpretation:
%
%   > 0 : recent window is relatively more variable
%   = 0 : recent/reference variability is similar
%   < 0 : recent window is relatively less variable
%
% If Sall == 0:
%
%   RecentVariability = 0
%
% This formulation is finite and does not require an arbitrary
% epsilon or numerical floor.
%
%
% ============================================================
% dSM RECENT TENDENCY
% ============================================================
%
% IMPORTANT:
%
% dSM2m_valid is already monthly soil-moisture change.
% NO additional differencing is performed.
%
% Define:
%
%   Sall = Q90(dSM_history) - Q10(dSM_history)
%
%   z =
%
%       mean(dSM_recent) - mean(dSM_reference)
%       ---------------------------------------
%                       Sall
%
%   dSM_RecentTendency =
%
%       sign(z) * log1p(abs(z))
%
% If Sall == 0:
%
%   dSM_RecentTendency = 0
%
%
% ============================================================
% FEATURE MECHANISM GROUPS
% ============================================================
%
% Hydroclimatic background:
%   4
%
% Long-term variability:
%   5
%
% Seasonality:
%   5
%
% Recent state / departure:
%   10
%
% Total:
%   24
%
%
% ============================================================
% IMPORTANT
% ============================================================
%
% No:
%
%   future information
%   winsorization
%   percentile clipping of feature values
%   RF-oriented standardization
%   second differencing of dSM
%   artificial epsilon denominator
%
