function pixelFeatures = computePixelFeatures( ...
    Prec, ...
    ET, ...
    Runoff, ...
    Tsurf, ...
    dSM, ...
    historyEndColumn, ...
    recentMonths, ...
    seasonalPeriod)


    Prec = ...
        double(Prec(:));


    ET = ...
        double(ET(:));


    Runoff = ...
        double(Runoff(:));


    Tsurf = ...
        double(Tsurf(:));


    dSM = ...
        double(dSM(:));


    nYear = ...
        numel(historyEndColumn);


    nFeature = ...
        24;


    pixelFeatures = ...
        NaN( ...
        nYear, ...
        nFeature);


    for iy = 1:nYear

        nHist = ...
            historyEndColumn(iy);


        referenceEnd = ...
            nHist - ...
            recentMonths;


        recentStart = ...
            referenceEnd + ...
            1;


        %% ====================================================
        % PRECIPITATION
        % =====================================================

        xHist = ...
            Prec(1:nHist);


        xReference = ...
            Prec(1:referenceEnd);


        xRecent = ...
            Prec(recentStart:nHist);


        pixelFeatures(iy, 1:5) = ...
            standardHydroFeatures( ...
            xHist, ...
            xReference, ...
            xRecent, ...
            seasonalPeriod);


        %% ====================================================
        % EVAPOTRANSPIRATION
        % =====================================================

        xHist = ...
            ET(1:nHist);


        xReference = ...
            ET(1:referenceEnd);


        xRecent = ...
            ET(recentStart:nHist);


        pixelFeatures(iy, 6:10) = ...
            standardHydroFeatures( ...
            xHist, ...
            xReference, ...
            xRecent, ...
            seasonalPeriod);


        %% ====================================================
        % RUNOFF
        % =====================================================

        xHist = ...
            Runoff(1:nHist);


        xReference = ...
            Runoff(1:referenceEnd);


        xRecent = ...
            Runoff(recentStart:nHist);


        pixelFeatures(iy, 11:15) = ...
            standardHydroFeatures( ...
            xHist, ...
            xReference, ...
            xRecent, ...
            seasonalPeriod);


        %% ====================================================
        % SURFACE TEMPERATURE
        % =====================================================

        xHist = ...
            Tsurf(1:nHist);


        xReference = ...
            Tsurf(1:referenceEnd);


        xRecent = ...
            Tsurf(recentStart:nHist);


        pixelFeatures(iy, 16:20) = ...
            standardHydroFeatures( ...
            xHist, ...
            xReference, ...
            xRecent, ...
            seasonalPeriod);


        %% ====================================================
        % SOIL-MOISTURE CHANGE
        %
        % IMPORTANT:
        %
        % dSM2m_valid is already monthly soil-moisture change.
        % No additional differencing.
        % =====================================================

        xHist = ...
            dSM(1:nHist);


        xReference = ...
            dSM(1:referenceEnd);


        xRecent = ...
            dSM(recentStart:nHist);


        %% ----- Long-term robust spread -----

        dsmAllSpread = ...
            robustSpread80( ...
            xHist);


        %% ----- Seasonality -----

        dsmSeasonality = ...
            seasonalityStrengthSTL( ...
            xHist, ...
            seasonalPeriod);


        %% ----- Recent tendency -----

        tendencyDifference = ...
            mean(xRecent) - ...
            mean(xReference);


        if dsmAllSpread > 0

            tendencyZ = ...
                tendencyDifference / ...
                dsmAllSpread;


            dsmRecentTendency = ...
                signedLogTransform( ...
                tendencyZ);

        else

            dsmRecentTendency = ...
                0;

        end


        %% ----- Recent variability -----

        dsmReferenceSpread = ...
            robustSpread80( ...
            xReference);


        dsmRecentSpread = ...
            robustSpread80( ...
            xRecent);


        dsmRecentVariability = ...
            normalizedSpreadContrast( ...
            dsmRecentSpread, ...
            dsmReferenceSpread, ...
            dsmAllSpread);


        pixelFeatures(iy, 21:24) = [ ...
            dsmAllSpread, ...
            dsmSeasonality, ...
            dsmRecentTendency, ...
            dsmRecentVariability];

    end

end


function features = standardHydroFeatures( ...
    xHist, ...
    xReference, ...
    xRecent, ...
    seasonalPeriod)


    xHist = ...
        double(xHist(:));


    xReference = ...
        double(xReference(:));


    xRecent = ...
        double(xRecent(:));


    %% ========================================================
    % 1. LONG-TERM MEAN
    % ========================================================

    longTermMean = ...
        mean(xHist);


    %% ========================================================
    % 2. LONG-TERM Q90-Q10 ROBUST SPREAD
    % ========================================================

    allSpread = ...
        robustSpread80( ...
        xHist);


    %% ========================================================
    % 3. ANNUAL SEASONALITY STRENGTH
    % ========================================================

    seasonality = ...
        seasonalityStrengthSTL( ...
        xHist, ...
        seasonalPeriod);


    %% ========================================================
    % 4. RECENT LEVEL SHIFT
    % ========================================================

    levelDifference = ...
        median(xRecent) - ...
        median(xReference);


    if allSpread > 0

        levelShiftZ = ...
            levelDifference / ...
            allSpread;


        recentLevelShift = ...
            signedLogTransform( ...
            levelShiftZ);

    else

        recentLevelShift = ...
            0;

    end


    %% ========================================================
    % 5. RECENT VARIABILITY
    % ========================================================

    referenceSpread = ...
        robustSpread80( ...
        xReference);


    recentSpread = ...
        robustSpread80( ...
        xRecent);


    recentVariability = ...
        normalizedSpreadContrast( ...
        recentSpread, ...
        referenceSpread, ...
        allSpread);


    features = [ ...
        longTermMean, ...
        allSpread, ...
        seasonality, ...
        recentLevelShift, ...
        recentVariability];

end


function spread = robustSpread80(x)
%
% Robust central 80% spread:
%
%   Q90 - Q10
%

    x = ...
        double(x(:));


    q = ...
        prctile( ...
        x, ...
        [10 90]);


    spread = ...
        q(2) - ...
        q(1);


    %% Numerical protection against tiny negative values caused
    % by floating-point arithmetic.

    if spread < 0 && ...
            abs(spread) < 1e-12

        spread = ...
            0;

    end


    if spread < 0 || ...
            ~isfinite(spread)

        error( ...
            'Invalid Q90-Q10 spread detected.');

    end

end


function value = normalizedSpreadContrast( ...
    recentSpread, ...
    referenceSpread, ...
    allSpread)
%
% Zero-safe recent/reference variability contrast.
%
% value =
%
%   log(1 + recentSpread/allSpread)
%   -
%   log(1 + referenceSpread/allSpread)
%
% If allSpread == 0:
%
%   value = 0
%

    if allSpread > 0

        value = ...
            log1p( ...
            recentSpread / ...
            allSpread) ...
            - ...
            log1p( ...
            referenceSpread / ...
            allSpread);

    else

        value = ...
            0;

    end

end


function strength = seasonalityStrengthSTL( ...
    x, ...
    period)


    x = ...
        double(x(:));


    if numel(x) < ...
            2 * period

        strength = ...
            NaN;

        return

    end


    [~, seasonal, remainder] = ...
        trenddecomp( ...
        x, ...
        'stl', ...
        period);


    denominator = ...
        var( ...
        seasonal + ...
        remainder, ...
        0);


    numerator = ...
        var( ...
        remainder, ...
        0);


    if ~isfinite(denominator) || ...
            denominator <= 0

        strength = ...
            0;

        return

    end


    strength = ...
        1 - ...
        numerator / ...
        denominator;


    strength = ...
        max( ...
        0, ...
        min( ...
        1, ...
        strength));

end


function value = signedLogTransform(z)


    value = ...
        sign(z) .* ...
        log1p( ...
        abs(z));

end


function checkMatrixSize( ...
    X, ...
    expectedSize, ...
    variableName)


    if ~isequal( ...
            size(X), ...
            expectedSize)

        error( ...
            ['%s has wrong size.\n', ...
             'Found    : %s\n', ...
             'Expected : %s'], ...
            variableName, ...
            mat2str(size(X)), ...
            mat2str(expectedSize));

    end

end


function checkFiniteMatrix( ...
    X, ...
    variableName)


    if any( ...
            ~isfinite(X(:)))

        [row, column] = ...
            find( ...
            ~isfinite(X), ...
            1, ...
            'first');


        error( ...
            ['Non-finite value found in %s.\n', ...
             'Grid row    = %d\n', ...
             'Month column = %d'], ...
            variableName, ...
            row, ...
            column);

    end

end


function ym = buildMonthlyYM( ...
    startYear, ...
    startMonth, ...
    endYear, ...
    endMonth)


    startDate = ...
        datetime( ...
        startYear, ...
        startMonth, ...
        1);


    endDate = ...
        datetime( ...
        endYear, ...
        endMonth, ...
        1);


    dateVector = ...
        ( ...
        startDate : ...
        calmonths(1) : ...
        endDate ...
        )';


    ym = ...
        year(dateVector) * ...
        100 + ...
        month(dateVector);


    ym = ...
        double( ...
        ym(:));

end