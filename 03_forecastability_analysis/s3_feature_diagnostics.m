%% Step 3: Diagnose dGWS features
% File name:
%   s3_feature_diagnostics.m
%
% Purpose:
%   Diagnose the 13 dGWS-only features before RF meta-model training.
%
% Main tasks:
%   1. Feature distribution diagnostics
%   2. Detailed tail diagnostics for:
%        Recent_variability_ratio
%        Recent_median_shift
%   3. Global Spearman correlation matrix
%   4. Year-specific Spearman correlation matrices
%   5. Identify potentially redundant feature pairs
%
% IMPORTANT:
%   This script does NOT modify FeatureData.
%   No clipping, transformation, or feature deletion is performed.
%
% Input:
%   E:\P1_SKLGB\M_manuscript2\s3_analysis\s2_dgws_features.mat
%
% Output:
%   Console diagnostics
%   Figures
%   s3_feature_diagnostics.mat

clc;
clearvars;
close all;

%% ===================== Paths =====================

analysisFolder = ...
    'E:\P1_SKLGB\M_manuscript2\s3_analysis\';

featureFile = fullfile( ...
    analysisFolder, ...
    's2_dgws_features.mat');

outFile = fullfile( ...
    analysisFolder, ...
    's3_feature_diagnostics.mat');

if ~exist(featureFile, 'file')

    error( ...
        'Feature file not found:\n%s', ...
        featureFile);

end

%% ===================== Load data =====================

fprintf('Loading feature database...\n');

S = load( ...
    featureFile, ...
    'FeatureData');

if ~isfield(S, 'FeatureData')

    error( ...
        'FeatureData variable not found in:\n%s', ...
        featureFile);

end

FeatureData = ...
    S.FeatureData;

clear S;

X = ...
    double(FeatureData.X);

featureNames = ...
    FeatureData.feature_names;

forecastYear = ...
    double(FeatureData.forecast_year(:));

pixelID = ...
    double(FeatureData.pixel_id(:));

lat = ...
    double(FeatureData.lat(:));

lon = ...
    double(FeatureData.lon(:));

[nSample, nFeature] = ...
    size(X);

if nFeature ~= 13

    error( ...
        'Expected 13 features, but found %d.', ...
        nFeature);

end

forecastYears = ...
    unique(forecastYear)';

fprintf('Samples  : %d\n', nSample);
fprintf('Features : %d\n', nFeature);
fprintf('Years    : %s\n', mat2str(forecastYears));

%% ===================== Short display names =====================

shortNames = { ...
    'ACF1', ...
    'ACF6', ...
    'ACF12', ...
    'MemoryLength', ...
    'SignPersist', ...
    'STLSeason', ...
    'AnnualPower', ...
    'SeasonStability', ...
    'PermEntropy', ...
    'SpectralEntropy', ...
    'RecentVarRatio', ...
    'RecentMedianShift', ...
    'DistShift'};

%% ============================================================
%  PART 1
%  Detailed distribution diagnostics
% ============================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf('FEATURE DISTRIBUTION DIAGNOSTICS\n');
fprintf('============================================================\n');

% Percentiles to inspect.
pctLevels = [ ...
    0, ...
    0.1, ...
    0.5, ...
    1, ...
    5, ...
    25, ...
    50, ...
    75, ...
    95, ...
    99, ...
    99.5, ...
    99.9, ...
    100];

nPct = ...
    numel(pctLevels);

Pct = ...
    NaN(nFeature, nPct);

featureMean = ...
    NaN(nFeature, 1);

featureStd = ...
    NaN(nFeature, 1);

featureIQR = ...
    NaN(nFeature, 1);

featureUnique = ...
    NaN(nFeature, 1);

for j = 1:nFeature

    z = ...
        X(:, j);

    z = ...
        z(isfinite(z));

    Pct(j, :) = ...
        prctile( ...
        z, ...
        pctLevels);

    featureMean(j) = ...
        mean(z);

    featureStd(j) = ...
        std(z);

    featureIQR(j) = ...
        iqr(z);

    featureUnique(j) = ...
        numel(unique(z));

end

%% ----- Print compact summary -----

fprintf('\n');

fprintf( ...
    ['%-22s %10s %10s %10s %10s %10s ', ...
     '%10s %10s %10s\n'], ...
    'Feature', ...
    'Mean', ...
    'Std', ...
    'P1', ...
    'P5', ...
    'Median', ...
    'P95', ...
    'P99', ...
    'Max');

fprintf('%s\n', repmat('-', 1, 112));

for j = 1:nFeature

    fprintf( ...
        ['%-22s %10.4f %10.4f %10.4f %10.4f ', ...
         '%10.4f %10.4f %10.4f %10.4f\n'], ...
        shortNames{j}, ...
        featureMean(j), ...
        featureStd(j), ...
        Pct(j, pctLevels == 1), ...
        Pct(j, pctLevels == 5), ...
        Pct(j, pctLevels == 50), ...
        Pct(j, pctLevels == 95), ...
        Pct(j, pctLevels == 99), ...
        Pct(j, pctLevels == 100));

end

%% ----- Detailed percentile output -----

fprintf('\n');
fprintf('DETAILED PERCENTILES\n');

for j = 1:nFeature

    fprintf('\n%s\n', featureNames{j});

    for p = 1:nPct

        fprintf( ...
            '  P%-6g = %12.6f\n', ...
            pctLevels(p), ...
            Pct(j, p));

    end

    fprintf( ...
        '  Unique values = %d\n', ...
        featureUnique(j));

    fprintf( ...
        '  IQR           = %.6f\n', ...
        featureIQR(j));

end

%% ============================================================
%  PART 2
%  Detailed diagnostics for feature 11 and 12
% ============================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf('SPECIAL DIAGNOSTICS: RECENT-CHANGE FEATURES\n');
fprintf('============================================================\n');

%% ----- Feature 11: Recent variability ratio -----

varRatio = ...
    X(:, 11);

fprintf('\nFeature 11: Recent_variability_ratio\n');

ratioThresholds = [ ...
    2, ...
    3, ...
    5, ...
    10, ...
    20, ...
    50, ...
    100, ...
    500];

for k = 1:numel(ratioThresholds)

    threshold = ...
        ratioThresholds(k);

    nExtreme = ...
        sum(varRatio > threshold);

    fprintf( ...
        '  Ratio > %-6g : %6d / %d = %7.4f%%\n', ...
        threshold, ...
        nExtreme, ...
        nSample, ...
        100 * nExtreme / nSample);

end

fprintf('\nSelected upper percentiles:\n');

specialPct = [ ...
    90, ...
    95, ...
    97.5, ...
    99, ...
    99.5, ...
    99.9, ...
    99.95, ...
    99.99, ...
    100];

ratioPct = ...
    prctile( ...
    varRatio, ...
    specialPct);

for k = 1:numel(specialPct)

    fprintf( ...
        '  P%-6g = %12.6f\n', ...
        specialPct(k), ...
        ratioPct(k));

end

%% ----- Top 20 feature-11 cases -----

[sortedRatio, idxRatio] = ...
    sort( ...
    varRatio, ...
    'descend');

nShow = ...
    min(20, nSample);

fprintf('\nTop %d Recent_variability_ratio samples:\n\n', nShow);

fprintf( ...
    '%5s %8s %8s %10s %10s %14s\n', ...
    'Rank', ...
    'Pixel', ...
    'Year', ...
    'Lat', ...
    'Lon', ...
    'VarRatio');

for k = 1:nShow

    i = ...
        idxRatio(k);

    fprintf( ...
        '%5d %8d %8d %10.3f %10.3f %14.4f\n', ...
        k, ...
        pixelID(i), ...
        forecastYear(i), ...
        lat(i), ...
        lon(i), ...
        sortedRatio(k));

end

%% ----- Feature 12: Recent median shift -----

medianShift = ...
    X(:, 12);

absMedianShift = ...
    abs(medianShift);

fprintf('\nFeature 12: Recent_median_shift\n');

shiftThresholds = [ ...
    1, ...
    2, ...
    3, ...
    5, ...
    10, ...
    20, ...
    50, ...
    100];

for k = 1:numel(shiftThresholds)

    threshold = ...
        shiftThresholds(k);

    nExtreme = ...
        sum(absMedianShift > threshold);

    fprintf( ...
        '  |Shift| > %-5g : %6d / %d = %7.4f%%\n', ...
        threshold, ...
        nExtreme, ...
        nSample, ...
        100 * nExtreme / nSample);

end

fprintf('\nAbsolute-shift percentiles:\n');

shiftPct = ...
    prctile( ...
    absMedianShift, ...
    specialPct);

for k = 1:numel(specialPct)

    fprintf( ...
        '  P%-6g = %12.6f\n', ...
        specialPct(k), ...
        shiftPct(k));

end

%% ----- Top 20 feature-12 cases -----

[sortedShift, idxShift] = ...
    sort( ...
    absMedianShift, ...
    'descend');

fprintf('\nTop %d |Recent_median_shift| samples:\n\n', nShow);

fprintf( ...
    '%5s %8s %8s %10s %10s %14s %14s\n', ...
    'Rank', ...
    'Pixel', ...
    'Year', ...
    'Lat', ...
    'Lon', ...
    'Shift', ...
    '|Shift|');

for k = 1:nShow

    i = ...
        idxShift(k);

    fprintf( ...
        '%5d %8d %8d %10.3f %10.3f %14.4f %14.4f\n', ...
        k, ...
        pixelID(i), ...
        forecastYear(i), ...
        lat(i), ...
        lon(i), ...
        medianShift(i), ...
        sortedShift(k));

end

%% ============================================================
%  PART 3
%  Global Spearman correlation
% ============================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf('GLOBAL SPEARMAN CORRELATION\n');
fprintf('============================================================\n');

rhoGlobal = ...
    corr( ...
    X, ...
    'Type', ...
    'Spearman', ...
    'Rows', ...
    'pairwise');

%% ----- Print correlation matrix -----

fprintf('\nGlobal Spearman rho matrix:\n\n');

fprintf('%18s', '');

for j = 1:nFeature

    fprintf( ...
        '%9s', ...
        shortNames{j});

end

fprintf('\n');

for i = 1:nFeature

    fprintf( ...
        '%18s', ...
        shortNames{i});

    for j = 1:nFeature

        fprintf( ...
            '%9.3f', ...
            rhoGlobal(i, j));

    end

    fprintf('\n');

end

%% ============================================================
%  PART 4
%  Identify correlated pairs
% ============================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf('GLOBAL CORRELATED FEATURE PAIRS\n');
fprintf('============================================================\n');

pairInfo = [];

pairCounter = 0;

for i = 1:nFeature-1

    for j = i+1:nFeature

        pairCounter = ...
            pairCounter + 1;

        pairInfo(pairCounter).i = i;
        pairInfo(pairCounter).j = j;

        pairInfo(pairCounter).rho = ...
            rhoGlobal(i, j);

        pairInfo(pairCounter).absrho = ...
            abs(rhoGlobal(i, j));

    end

end

absRhoValues = ...
    [pairInfo.absrho];

[~, pairOrder] = ...
    sort( ...
    absRhoValues, ...
    'descend');

fprintf('\nTop 20 strongest global correlations:\n\n');

fprintf( ...
    '%4s %-22s %-22s %10s %10s\n', ...
    '#', ...
    'Feature 1', ...
    'Feature 2', ...
    'rho', ...
    '|rho|');

for k = 1:min(20, numel(pairOrder))

    p = ...
        pairInfo(pairOrder(k));

    fprintf( ...
        '%4d %-22s %-22s %10.4f %10.4f\n', ...
        k, ...
        shortNames{p.i}, ...
        shortNames{p.j}, ...
        p.rho, ...
        p.absrho);

end

%% ----- Threshold diagnostics -----

corrThresholds = [ ...
    0.70, ...
    0.80, ...
    0.85, ...
    0.90];

for t = 1:numel(corrThresholds)

    threshold = ...
        corrThresholds(t);

    fprintf( ...
        '\nPairs with |rho| >= %.2f:\n', ...
        threshold);

    found = ...
        false;

    for k = 1:numel(pairOrder)

        p = ...
            pairInfo(pairOrder(k));

        if p.absrho >= threshold

            found = ...
                true;

            fprintf( ...
                '  %-22s <-> %-22s : rho = %+7.4f\n', ...
                shortNames{p.i}, ...
                shortNames{p.j}, ...
                p.rho);

        end

    end

    if ~found

        fprintf('  None\n');

    end

end

%% ============================================================
%  PART 5
%  Year-specific Spearman correlations
% ============================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf('YEAR-SPECIFIC SPEARMAN CORRELATION\n');
fprintf('============================================================\n');

nYear = ...
    numel(forecastYears);

rhoYear = ...
    NaN( ...
    nFeature, ...
    nFeature, ...
    nYear);

for y = 1:nYear

    thisYear = ...
        forecastYears(y);

    mask = ...
        forecastYear == thisYear;

    rhoYear(:, :, y) = ...
        corr( ...
        X(mask, :), ...
        'Type', ...
        'Spearman', ...
        'Rows', ...
        'pairwise');

end

%% ----- Correlation stability for each pair -----

PairTable = ...
    table();

pairNo = ...
    0;

for i = 1:nFeature-1

    for j = i+1:nFeature

        pairNo = ...
            pairNo + 1;

        rYear = ...
            squeeze( ...
            rhoYear(i, j, :));

        PairTable.Feature1{pairNo, 1} = ...
            shortNames{i};

        PairTable.Feature2{pairNo, 1} = ...
            shortNames{j};

        PairTable.GlobalRho(pairNo, 1) = ...
            rhoGlobal(i, j);

        PairTable.MeanYearRho(pairNo, 1) = ...
            mean(rYear);

        PairTable.MinYearRho(pairNo, 1) = ...
            min(rYear);

        PairTable.MaxYearRho(pairNo, 1) = ...
            max(rYear);

        PairTable.MinAbsYearRho(pairNo, 1) = ...
            min(abs(rYear));

        PairTable.MaxAbsYearRho(pairNo, 1) = ...
            max(abs(rYear));

        PairTable.YearRange(pairNo, 1) = ...
            max(rYear) - min(rYear);

    end

end

%% ----- Sort by global |rho| -----

PairTable.AbsGlobalRho = ...
    abs(PairTable.GlobalRho);

PairTable = ...
    sortrows( ...
    PairTable, ...
    'AbsGlobalRho', ...
    'descend');

fprintf('\nTop 20 pairs: global vs year-specific correlation\n\n');

fprintf( ...
    ['%-22s %-22s %9s %9s %9s ', ...
     '%9s %9s\n'], ...
    'Feature 1', ...
    'Feature 2', ...
    'Global', ...
    'MeanYr', ...
    'MinYr', ...
    'MaxYr', ...
    'Range');

for k = 1:min(20, height(PairTable))

    fprintf( ...
        ['%-22s %-22s %9.4f %9.4f ', ...
         '%9.4f %9.4f %9.4f\n'], ...
        PairTable.Feature1{k}, ...
        PairTable.Feature2{k}, ...
        PairTable.GlobalRho(k), ...
        PairTable.MeanYearRho(k), ...
        PairTable.MinYearRho(k), ...
        PairTable.MaxYearRho(k), ...
        PairTable.YearRange(k));

end

%% ----- Persistent high correlations -----

fprintf('\n');
fprintf('Pairs with |rho| >= 0.80 in ALL six years:\n');

persistentMask = ...
    PairTable.MinAbsYearRho >= 0.80;

if any(persistentMask)

    T = ...
        PairTable(persistentMask, :);

    for k = 1:height(T)

        fprintf( ...
            ['  %-22s <-> %-22s | ', ...
             'global=%+.4f | min|year rho|=%.4f\n'], ...
            T.Feature1{k}, ...
            T.Feature2{k}, ...
            T.GlobalRho(k), ...
            T.MinAbsYearRho(k));

    end

else

    fprintf('  None\n');

end

%% ============================================================
%  PART 6
%  Feature distribution figures
% ============================================================

fprintf('\nCreating diagnostic figures...\n');

figure( ...
    'Name', ...
    'Feature distributions', ...
    'Color', ...
    'w', ...
    'Position', ...
    [100 50 1500 900]);

tiledlayout( ...
    4, ...
    4, ...
    'TileSpacing', ...
    'compact', ...
    'Padding', ...
    'compact');

for j = 1:nFeature

    nexttile;

    z = ...
        X(:, j);

    % For the two heavy-tailed features, show only P0.1-P99.9
    % in the main histogram so the central distribution is visible.
    if j == 11 || j == 12

        limits = ...
            prctile( ...
            z, ...
            [0.1 99.9]);

        plotMask = ...
            z >= limits(1) & ...
            z <= limits(2);

        histogram( ...
            z(plotMask), ...
            60);

        title( ...
            [shortNames{j}, ' (P0.1-P99.9)'], ...
            'Interpreter', ...
            'none');

    else

        histogram( ...
            z, ...
            60);

        title( ...
            shortNames{j}, ...
            'Interpreter', ...
            'none');

    end

    box on;

end

%% ============================================================
%  PART 7
%  Special tail figures
% ============================================================

figure( ...
    'Name', ...
    'Recent variability ratio', ...
    'Color', ...
    'w');

% log10 is used for visualization only.
% Original FeatureData is NOT transformed.
histogram( ...
    log10(varRatio), ...
    80);

xlabel('log10(Recent variability ratio)');
ylabel('Number of samples');
title('Distribution of Recent variability ratio');
box on;


figure( ...
    'Name', ...
    'Recent median shift', ...
    'Color', ...
    'w');

shiftLimits = ...
    prctile( ...
    medianShift, ...
    [0.1 99.9]);

shiftMask = ...
    medianShift >= shiftLimits(1) & ...
    medianShift <= shiftLimits(2);

histogram( ...
    medianShift(shiftMask), ...
    80);

xlabel('Recent median shift');
ylabel('Number of samples');
title('Recent median shift: P0.1-P99.9');
box on;

%% ============================================================
%  PART 8
%  Global correlation heatmap
% ============================================================

figure( ...
    'Name', ...
    'Global Spearman correlation', ...
    'Color', ...
    'w', ...
    'Position', ...
    [100 100 1050 900]);

h = ...
    heatmap( ...
    shortNames, ...
    shortNames, ...
    rhoGlobal);

h.Title = ...
    'Global Spearman correlation of dGWS features';

h.XLabel = ...
    'Feature';

h.YLabel = ...
    'Feature';

h.ColorLimits = ...
    [-1 1];

h.CellLabelFormat = ...
    '%.2f';

%% ============================================================
%  PART 9
%  Save diagnostics
% ============================================================

Diagnostics = struct();

Diagnostics.feature_names = ...
    featureNames;

Diagnostics.short_names = ...
    shortNames;

Diagnostics.percentile_levels = ...
    pctLevels;

Diagnostics.percentiles = ...
    Pct;

Diagnostics.mean = ...
    featureMean;

Diagnostics.std = ...
    featureStd;

Diagnostics.iqr = ...
    featureIQR;

Diagnostics.unique_values = ...
    featureUnique;

Diagnostics.rho_global = ...
    rhoGlobal;

Diagnostics.forecast_years = ...
    forecastYears;

Diagnostics.rho_year = ...
    rhoYear;

Diagnostics.pair_table = ...
    PairTable;

Diagnostics.recent_variability_ratio_special_percentiles = ...
    [specialPct(:), ratioPct(:)];

Diagnostics.recent_median_shift_abs_special_percentiles = ...
    [specialPct(:), shiftPct(:)];

save( ...
    outFile, ...
    'Diagnostics', ...
    '-v7.3');

fprintf('\nDiagnostics saved to:\n%s\n', outFile);

fprintf('\n');
fprintf('============================================================\n');
fprintf('DIAGNOSTICS COMPLETE\n');
fprintf('============================================================\n');