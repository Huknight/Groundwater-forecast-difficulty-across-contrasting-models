% 17. MAIN NESTED RF TRAINING
% ============================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf('STARTING M3 dGWS + HYDRO NESTED RF TRAINING\n');
fprintf('============================================================\n');


sessionStart = ...
    tic;


for oi = 1:nOuter


    testYear = ...
        outerTestYears(oi);


    %% --------------------------------------------------------
    % Outer temporal split
    % ---------------------------------------------------------

    outerTrainMask = ...
        forecastYear < ...
        testYear;


    outerTestMask = ...
        forecastYear == ...
        testYear;


    trainYears = ...
        unique( ...
        forecastYear(outerTrainMask))';


    nOuterTrain = ...
        sum(outerTrainMask);


