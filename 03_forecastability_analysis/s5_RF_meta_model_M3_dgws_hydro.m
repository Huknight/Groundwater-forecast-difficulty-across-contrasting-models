        % MARK COMPLETED
        % ====================================================

        Results.completed(oi, m) = ...
            true;


        %% ====================================================
        % CONSOLE SUMMARY
        % ====================================================

        fprintf('\n');
        fprintf('============================================================\n');
        fprintf('M3 TEST RESULT: %s | %d\n', ...
            modelName, ...
            testYear);
        fprintf('============================================================\n');


        fprintf('Selected RF:\n');


        fprintf( ...
            '  mtry        = %d\n', ...
            selectedMtry);


        fprintf( ...
            '  MinLeafSize = %d\n', ...
            selectedLeaf);


        fprintf( ...
            '  CV RMSE_log = %.6f\n', ...
            cvRMSE(selectedCombo));


        fprintf('\nLog target scale:\n');


        fprintf( ...
            '  R2       = %.4f\n', ...
            metricLog.R2);


        fprintf( ...
            '  RMSE     = %.4f\n', ...
            metricLog.RMSE);


        fprintf( ...
            '  MAE      = %.4f\n', ...
            metricLog.MAE);


        fprintf( ...
            '  Spearman = %.4f\n', ...
            metricLog.Spearman);


        fprintf('\nOriginal NRMSE scale:\n');


        fprintf( ...
            '  R2       = %.4f\n', ...
            metricRaw.R2);


        fprintf( ...
            '  RMSE     = %.4f\n', ...
            metricRaw.RMSE);


        fprintf( ...
            '  MAE      = %.4f\n', ...
            metricRaw.MAE);


        fprintf( ...
            '  Spearman = %.4f\n', ...
            metricRaw.Spearman);


        fprintf('\nBaseline comparison:\n');


        fprintf( ...
            '  Baseline RMSE_log = %.4f\n', ...
            baselineMetricLog.RMSE);


        fprintf( ...
            '  RF improvement    = %.2f%%\n', ...
            rmseImprovementLog);


        fprintf( ...
            '\nRuntime = %.2f min\n', ...
            Results.RuntimeMinutes(oi, m));


        fprintf('============================================================\n');


        %% ====================================================
        % CHECKPOINT
        % ====================================================

        fprintf('Saving M3 checkpoint...\n');


        save( ...
            checkpointFile, ...
            'Results', ...
            '-v7.3');


        %% ====================================================
        % PARTIAL SUMMARY
        % ====================================================

        PartialSummary = ...
            buildSummaryTable( ...
            Results, ...
            modelNames, ...
            outerTestYears, ...
            true);


        partialSummaryFile = ...
            fullfile( ...
            tableFolder, ...
            'RF_meta_model_M3_partial_summary.csv');


        writetable( ...
            PartialSummary, ...
            partialSummaryFile);


        clear PredictionTable PartialSummary

    end

end


