        % FINAL 500-TREE RF
        % ====================================================

        fprintf( ...
            '\n  Training final %d-tree M3 RF...\n', ...
            numTreesFinal);


        finalSeed = ...
            rfSeedBase + ...
            oi * 10000 + ...
            m * 100 + ...
            99;


        finalRF = ...
            trainTreeBaggerRF( ...
            numTreesFinal, ...
            Xtrain, ...
            yTrainLog, ...
            selectedMtry, ...
            selectedLeaf, ...
            finalSeed, ...
            useParallelActual);


