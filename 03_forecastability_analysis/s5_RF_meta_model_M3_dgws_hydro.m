function M = regressionMetrics( ...
    observed, ...
    predicted)


    observed = ...
        double(observed(:));


    predicted = ...
        double(predicted(:));


    valid = ...
        isfinite(observed) & ...
        isfinite(predicted);


    observed = ...
        observed(valid);


    predicted = ...
        predicted(valid);


    M = ...
        struct();


    if isempty(observed)


        M.R2 = NaN;
        M.RMSE = NaN;
        M.MAE = NaN;
        M.Spearman = NaN;


        return

    end


    errorVector = ...
        predicted - ...
        observed;


    M.RMSE = ...
        sqrt( ...
        mean( ...
        errorVector .^ 2));


    M.MAE = ...
        mean( ...
        abs(errorVector));


    denominator = ...
        sum( ...
        ( ...
        observed - ...
        mean(observed) ...
        ) .^ 2);


    if denominator > 0


        M.R2 = ...
            1 - ...
            sum(errorVector .^ 2) / ...
            denominator;


    else


        M.R2 = ...
            NaN;

    end


    if numel(observed) >= 3 && ...
            std(observed) > 0 && ...
            std(predicted) > 0


        M.Spearman = ...
            corr( ...
            observed, ...
            predicted, ...
            'Type', ...
            'Spearman', ...
            'Rows', ...
            'complete');


    else


        M.Spearman = ...
            NaN;

    end

end


function [selectedIdx, absoluteBestIdx] = ...
    selectRFCombination( ...
    cvRMSE, ...
    comboMtry, ...
    comboLeaf, ...
    tolerance)


    cvRMSE = ...
        double(cvRMSE(:));


    comboMtry = ...
        double(comboMtry(:));


    comboLeaf = ...
        double(comboLeaf(:));


    if any(~isfinite(cvRMSE))

        error( ...
            'Non-finite CV RMSE detected.');

    end


    %% ----- Absolute minimum -----

    [minimumRMSE, absoluteBestIdx] = ...
        min(cvRMSE);


    %% ----- Configurations within 1% -----

    eligible = ...
        cvRMSE <= ...
        minimumRMSE * ...
        (1 + tolerance);


    %% ----- Prefer larger MinLeafSize -----

    largestLeaf = ...
        max( ...
        comboLeaf(eligible));


    eligible = ...
        eligible & ...
        comboLeaf == ...
        largestLeaf;


    candidateIdx = ...
        find(eligible);


    %% ----- Then minimum RMSE -----

    candidateRMSE = ...
        cvRMSE(candidateIdx);


    bestCandidateRMSE = ...
        min(candidateRMSE);


    bestCandidates = ...
        candidateIdx( ...
        abs( ...
        candidateRMSE - ...
        bestCandidateRMSE) < ...
        1e-12);


    %% ----- Exact tie -> smaller mtry -----

    if numel(bestCandidates) > 1


        [~, ii] = ...
            min( ...
            comboMtry(bestCandidates));


        selectedIdx = ...
            bestCandidates(ii);


    else


        selectedIdx = ...
            bestCandidates;

    end

end


