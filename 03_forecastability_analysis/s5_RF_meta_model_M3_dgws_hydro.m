%% Step 5 M3: dGWS + hydroclimate RF forecastability meta-model
% File name:
%   s5_RF_meta_model_M3_dgws_hydro.m
%
% Purpose:
%   Train and evaluate nine independent RF forecastability
%   meta-models using:
%
%       13 pre-origin dGWS features
%       +
%       24 pre-origin hydroclimatic features
%
%   Total:
%
%       37 predictors
%
%
% ============================================================
% MODEL VARIANT
% ============================================================
%
% M1:
%   13 dGWS-only features
%
% M2:
%   24 hydroclimate-only features
%
% M3:
%   13 dGWS + 24 hydroclimate
%   = 37 features
%
%
% ============================================================
% SCIENTIFIC PURPOSE
% ============================================================
%
% M3 vs M1:
%
%   Tests whether hydroclimatic information provides
%   incremental forecastability information beyond the
%   intrinsic temporal structure of dGWS.
%
%
% M3 vs M2:
%
%   Tests whether groundwater temporal characteristics
%   provide additional information beyond hydroclimatic
%   context.
%
%
% ============================================================
% TARGETS
% ============================================================
%
% Future 12-month NRMSE_Q10Q90 for:
%
%   AR
%   ARIMA
%   SARIMA
%   SVM
%   RF
%   LSTM
%   SVMX
%   RFX
%   LSTMX
%
%
% Training target:
%
%   log1p(NRMSE_Q10Q90)
%
%
% ============================================================
% OUTER TEMPORAL VALIDATION
% ============================================================
%
% 2019-2021 -> 2022
% 2019-2022 -> 2023
% 2019-2023 -> 2024
%
%
% ============================================================
% INNER VALIDATION
% ============================================================
%
% Fixed grouped 10-fold CV by pixel ID.
%
% All years belonging to the same pixel are assigned to the
% same inner-CV fold.
%
%
% ============================================================
% RF GRID
% ============================================================
%
% Number of predictors:
%
%   p = 37
%
% NumPredictorsToSample:
%
%   [6 12 19 37]
%
% approximately:
%
%   sqrt(p)
%   p/3
%   p/2
%   p
%
%
% MinLeafSize:
%
%   [1 5 20 50]
%
%
% Total hyperparameter combinations:
%
%   16
%
%
% CV trees:
%
%   300
%
%
% Final trees:
%
%   500
%
%
% Selection criterion:
%
%   pooled grouped-CV RMSE on log1p(NRMSE)
%
%
% 1% tie rule:
%
%   All configurations within 1% of minimum CV RMSE are
%   treated as practically equivalent.
%
%   Preference:
%
%       1. larger MinLeafSize
%       2. lower CV RMSE
%       3. exact tie -> smaller mtry
%
%
% ============================================================
% IMPORTANT
% ============================================================
%
% M1, M2 and M3 use exactly the same:
%
%   samples
%   target values
%   target transformation
%   outer temporal validation
%   grouped-pixel inner CV
%   fold seed
%   RF seed scheme
%   tree counts
%   MinLeafSize grid
%   1% tie rule
%   constant baseline
%   evaluation metrics
%
% Only the predictor information set differs.
%
% ============================================================

