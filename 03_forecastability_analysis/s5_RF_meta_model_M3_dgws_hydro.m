            modelFolder, ...
            sprintf( ...
            'RFmeta_M3_%d_%s.mat', ...
            testYear, ...
            safeModel));


        if saveCompactModels


            CompactRF = ...
                compact(finalRF);


            ModelInfo = ...
                struct();


            ModelInfo.model_variant = ...
                modelVariant;


            ModelInfo.target_model = ...
                modelName;


            ModelInfo.test_year = ...
                testYear;


            ModelInfo.train_years = ...
                trainYears;


            ModelInfo.n_dgws_features = ...
                nFeatureDGWS;


            ModelInfo.n_hydro_features = ...
                nFeatureHydro;


            ModelInfo.n_total_features = ...
                nFeature;


            ModelInfo.feature_names = ...
                featureNames;


            ModelInfo.feature_groups = ...
                featureGroups;


            ModelInfo.feature_variables = ...
                featureVariables;


            ModelInfo.feature_sources = ...
                featureSources;


            ModelInfo.target_transform = ...
                'log1p(NRMSE_Q10Q90)';


            ModelInfo.NumTrees = ...
                numTreesFinal;


            ModelInfo.NumPredictorsToSample = ...
                selectedMtry;


            ModelInfo.MinLeafSize = ...
                selectedLeaf;


            ModelInfo.random_seed = ...
                finalSeed;


            ModelInfo.fold_seed = ...
                foldSeed;


            ModelInfo.parallel_workers = ...
                actualWorkers;


            save( ...
                modelFile, ...
                'CompactRF', ...
                'ModelInfo', ...
                '-v7.3');


            clear CompactRF ModelInfo;

        end


        %% ====================================================
        % OUTER TEST PREDICTION
        % ====================================================

        predTestLog = ...
            predict( ...
            finalRF, ...
            Xtest);


        predTestRaw = ...
            expm1(predTestLog);


        predTestRaw = ...
            max( ...
            predTestRaw, ...
            0);


        clear finalRF;


        %% ====================================================
        % OUTER TEST METRICS
        % ====================================================

        metricLog = ...
            regressionMetrics( ...
            yTestLog, ...
            predTestLog);


        metricRaw = ...
            regressionMetrics( ...
            yTestRaw, ...
            predTestRaw);


        %% ====================================================
        % CONSTANT BASELINE
        % ====================================================

        baselineLogValue = ...
            mean(yTrainLog);


        baselinePredLog = ...
            repmat( ...
            baselineLogValue, ...
            nTest, ...
            1);


        baselineRawValue = ...
            expm1( ...
            baselineLogValue);


        baselinePredRaw = ...
            repmat( ...
            baselineRawValue, ...
            nTest, ...
            1);


        baselineMetricLog = ...
            regressionMetrics( ...
            yTestLog, ...
            baselinePredLog);


        baselineMetricRaw = ...
            regressionMetrics( ...
            yTestRaw, ...
            baselinePredRaw);


        rmseImprovementLog = ...
            100 * ...
            ( ...
            baselineMetricLog.RMSE - ...
            metricLog.RMSE ...
            ) / ...
            baselineMetricLog.RMSE;


        %% ====================================================
        % SAVE PREDICTIONS
        % ====================================================

        Results.prediction_log(testRows, m) = ...
            predTestLog;


        Results.prediction_raw(testRows, m) = ...
            predTestRaw;


        %% ====================================================
        % SAVE METRICS
        % ====================================================

        Results.Metrics.Log.R2(oi, m) = ...
            metricLog.R2;


        Results.Metrics.Log.RMSE(oi, m) = ...
            metricLog.RMSE;


        Results.Metrics.Log.MAE(oi, m) = ...
            metricLog.MAE;


        Results.Metrics.Log.Spearman(oi, m) = ...
            metricLog.Spearman;


        Results.Metrics.Raw.R2(oi, m) = ...
