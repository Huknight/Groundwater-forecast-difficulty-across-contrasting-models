        sum(outerTestMask);


    Results.train_year_start(oi) = ...
        min(trainYears);


    Results.train_year_end(oi) = ...
        max(trainYears);


    Results.test_year(oi) = ...
        testYear;


    Results.n_train(oi) = ...
        nOuterTrain;


    Results.n_test(oi) = ...
        nOuterTest;


    fprintf('\n');
    fprintf('============================================================\n');
    fprintf('M3 OUTER ROUND %d / %d\n', oi, nOuter);
    fprintf('Train years : %s\n', mat2str(trainYears));
    fprintf('Test year   : %d\n', testYear);
    fprintf('Train cases : %d\n', nOuterTrain);
    fprintf('Test cases  : %d\n', nOuterTest);
    fprintf('Predictors  : %d dGWS + %d hydro = %d\n', ...
        nFeatureDGWS, ...
        nFeatureHydro, ...
        nFeature);
    fprintf('============================================================\n');


    %% ========================================================
    % Nine forecasting-model targets
    % ========================================================

    for m = 1:nModel


        modelName = ...
            modelNames{m};


        safeModel = ...
            matlab.lang.makeValidName( ...
            modelName);


        %% ----- Resume completed target-year -----

        if Results.completed(oi, m)

            fprintf( ...
                '\n[%d/%d] %s | %d already completed. Skipping.\n', ...
                m, ...
                nModel, ...
                modelName, ...
                testYear);

            continue

        end


        modelStart = ...
            tic;


        fprintf('\n');
        fprintf('------------------------------------------------------------\n');
        fprintf('M3 TARGET %d / %d : %s\n', ...
            m, ...
            nModel, ...
            modelName);
        fprintf('OUTER TEST YEAR    : %d\n', ...
            testYear);
        fprintf('------------------------------------------------------------\n');


        %% ----------------------------------------------------
        % Training/test data
        % -----------------------------------------------------

        trainMask = ...
            outerTrainMask & ...
            isfinite(Ylog(:, m));


        testMask = ...
            outerTestMask & ...
            isfinite(Ylog(:, m));


        Xtrain = ...
            X(trainMask, :);


        yTrainLog = ...
            Ylog(trainMask, m);


        Xtest = ...
            X(testMask, :);


        yTestLog = ...
            Ylog(testMask, m);


        yTestRaw = ...
            Yraw(testMask, m);


        trainFold = ...
            sampleFold(trainMask);


        testRows = ...
            find(testMask);


        nTrain = ...
            size(Xtrain, 1);


        nTest = ...
            size(Xtest, 1);


        %% ----- Fold safety checks -----

        for k = 1:nFold

            if ~any(trainFold == k)

                error( ...
                    'No validation samples in fold %d.', ...
                    k);

            end


            if ~any(trainFold ~= k)

                error( ...
                    'No training samples for fold %d.', ...
                    k);

            end

        end


        %% ====================================================
        % INNER GROUPED 10-FOLD GRID SEARCH
        % ====================================================

        cvRMSE = ...
            NaN(nCombo, 1);


        cvMAE = ...
            NaN(nCombo, 1);


        cvR2 = ...
            NaN(nCombo, 1);


        cvSpearman = ...
            NaN(nCombo, 1);


        for c = 1:nCombo


