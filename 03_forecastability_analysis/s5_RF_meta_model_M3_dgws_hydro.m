        Results.Metrics.Raw.RMSE(oi, m) = ...
            metricRaw.RMSE;


        Results.Metrics.Raw.MAE(oi, m) = ...
            metricRaw.MAE;


        Results.Metrics.Raw.Spearman(oi, m) = ...
