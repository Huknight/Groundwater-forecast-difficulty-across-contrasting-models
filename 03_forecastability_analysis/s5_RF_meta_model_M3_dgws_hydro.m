                comboMtry(c);


            thisLeaf = ...
                comboLeaf(c);


            comboStart = ...
                tic;


            fprintf( ...
                '\n  Combo %2d/%2d | mtry=%2d | MinLeaf=%2d\n', ...
                c, ...
                nCombo, ...
                thisMtry, ...
                thisLeaf);


            pooledPred = ...
                NaN(nTrain, 1);


            %% ----- 10 grouped folds -----

            for k = 1:nFold


                innerTrain = ...
                    trainFold ~= k;


                innerVal = ...
                    trainFold == k;


                foldStart = ...
                    tic;


                fprintf( ...
                    '    Fold %2d/%2d ... ', ...
                    k, ...
                    nFold);


                seed = ...
                    rfSeedBase + ...
                    oi * 10000 + ...
                    m * 100 + ...
                    k;


                RF = ...
                    trainTreeBaggerRF( ...
                    numTreesCV, ...
                    Xtrain(innerTrain, :), ...
                    yTrainLog(innerTrain), ...
                    thisMtry, ...
                    thisLeaf, ...
                    seed, ...
                    useParallelActual);


                foldPred = ...
                    predict( ...
                    RF, ...
                    Xtrain(innerVal, :));


                pooledPred(innerVal) = ...
                    foldPred;


                clear RF foldPred;


                fprintf( ...
                    '%.1f s\n', ...
                    toc(foldStart));

            end


            if any(~isfinite(pooledPred))

