                ['    CV RMSE=%.6f | MAE=%.6f | ', ...
                 'R2=%.4f | rho=%.4f | %.2f min\n'], ...
                cvRMSE(c), ...
                cvMAE(c), ...
                cvR2(c), ...
                cvSpearman(c), ...
                toc(comboStart) / 60);

        end


        %% ====================================================
        % HYPERPARAMETER SELECTION
        % ====================================================

        [selectedCombo, absoluteBestCombo] = ...
            selectRFCombination( ...
            cvRMSE, ...
            comboMtry, ...
            comboLeaf, ...
            tieTolerance);


        selectedMtry = ...
            comboMtry(selectedCombo);


        selectedLeaf = ...
            comboLeaf(selectedCombo);


        absoluteMtry = ...
            comboMtry(absoluteBestCombo);


        absoluteLeaf = ...
            comboLeaf(absoluteBestCombo);


        fprintf('\n');
        fprintf('  Absolute minimum CV RMSE:\n');


        fprintf( ...
            '    mtry=%d | MinLeaf=%d | RMSE=%.6f\n', ...
            absoluteMtry, ...
            absoluteLeaf, ...
            cvRMSE(absoluteBestCombo));


        fprintf('  Selected by 1%% tie rule:\n');


        fprintf( ...
            '    mtry=%d | MinLeaf=%d | RMSE=%.6f\n', ...
            selectedMtry, ...
            selectedLeaf, ...
            cvRMSE(selectedCombo));


        %% ----- Save CV details -----

        CVTable = ...
            table( ...
            comboMtry, ...
            comboLeaf, ...
            cvRMSE, ...
            cvMAE, ...
            cvR2, ...
            cvSpearman, ...
            'VariableNames', { ...
            'NumPredictorsToSample', ...
            'MinLeafSize', ...
            'RMSE_Log', ...
            'MAE_Log', ...
            'R2_Log', ...
            'Spearman'});


        CVTable.IsAbsoluteBest = ...
            false(nCombo, 1);


        CVTable.IsSelected = ...
            false(nCombo, 1);


        CVTable.IsAbsoluteBest(absoluteBestCombo) = ...
            true;


        CVTable.IsSelected(selectedCombo) = ...
            true;


        Results.CVDetails{oi, m} = ...
            CVTable;


        Results.SelectedMtry(oi, m) = ...
            selectedMtry;


        Results.SelectedMinLeaf(oi, m) = ...
            selectedLeaf;


        Results.SelectedCVRMSE(oi, m) = ...
            cvRMSE(selectedCombo);


        Results.AbsoluteBestMtry(oi, m) = ...
            absoluteMtry;


        Results.AbsoluteBestMinLeaf(oi, m) = ...
            absoluteLeaf;


        Results.AbsoluteBestCVRMSE(oi, m) = ...
            cvRMSE(absoluteBestCombo);


        %% ----- Save CV table immediately -----

        cvFile = fullfile( ...
            cvFolder, ...
            sprintf( ...
            'CV_M3_%d_%s.csv', ...
            testYear, ...
            safeModel));


        writetable( ...
            CVTable, ...
            cvFile);


