    cluster = ...
        parcluster('local');


    nWorkers = ...
        min( ...
        nWorkers, ...
        cluster.NumWorkers);


    pool = ...
        gcp('nocreate');


    if ~isempty(pool) && ...
            pool.NumWorkers ~= ...
            nWorkers


        fprintf( ...
            ['Restarting parallel pool: ', ...
             '%d -> %d workers.\n'], ...
            pool.NumWorkers, ...
            nWorkers);


        delete(pool);


        pool = ...
            [];

    end


    if isempty(pool)


        fprintf( ...
            'Starting parallel pool with %d workers...\n', ...
            nWorkers);


        parpool( ...
            'local', ...
            nWorkers);

    end


end


