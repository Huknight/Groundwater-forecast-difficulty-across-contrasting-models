%% s7_M1_TreeSHAP_compute.m
%
% ============================================================
% FORMAL M1 EXACT TREE-SHAP COMPUTATION
% ============================================================
%
% M1:
%
%   13 pre-origin dGWS features
%           ->
%   RF forecastability meta-model
%           ->
%   predicted log1p(NRMSE_Q10Q90)
%
%
% ============================================================
% OUTER TEST DESIGN
% ============================================================
%
% train 2019-2021 -> explain 2022
% train 2019-2022 -> explain 2023
% train 2019-2023 -> explain 2024
%
% 9 forecast-model targets:
%
%   AR
%   ARIMA
%   SARIMA
%   SVM
%   RF
%   LSTM
%   SVMX
%   RFX
%   LSTMX
%
% Total:
%
%   3 years x 9 targets = 27 RF meta-models
%
%
% ============================================================
% SHAP METHOD
% ============================================================
%
% Each CompactTreeBagger contains 500 CompactRegressionTree
% learners.
%
% Exact Tree SHAP is calculated separately for every tree:
%
%   phi_RF =
%       mean(phi_tree_1,...,phi_tree_500)
%
% and:
%
%   intercept_RF =
%       mean(intercept_tree_1,...,intercept_tree_500)
%
%
% s7a validation demonstrated:
%
%   RF prediction == mean(tree prediction)
%
% and:
%
%   RF prediction ==
%       intercept_RF + sum(phi_RF)
%
% to machine precision.
%
%
% IMPORTANT:
%
% NO MaxNumSubsets is specified anywhere in this script.
%
% This preserves MATLAB native:
%
%   interventional-tree
%
% rather than Kernel SHAP.
%
%
% ============================================================
% FORMAL PARAMETERS LOCKED BY s7b
% ============================================================
%
% workers:
%
%   initial = 12
%
% background:
%
%   300 outer-training pixel-year observations
%
% foreground:
%
%   ALL 17,284 independent outer-test pixels
%
% initial query batch:
%
%   5000 pixels
%
%
% ============================================================
% BACKGROUND DESIGN
% ============================================================
%
% Each outer year has ONE fixed BG300.
%
% All nine target RFs in the same outer year use exactly the
% same background rows.
%
%
% 2022:
%
%   2019 : 100
%   2020 : 100
%   2021 : 100
%
%
% 2023:
%
%   2019 : 75
%   2020 : 75
%   2021 : 75
%   2022 : 75
%
%
% 2024:
%
%   2019 : 60
%   2020 : 60
%   2021 : 60
%   2022 : 60
%   2023 : 60
%
%
% Backgrounds are:
%
%   random
%   reproducible
%   stratified by training year
%
% No:
%
%   winsorization
%   extreme removal
%   k-means
%   manual typical-pixel selection
%
%
% ============================================================
% SHAP SIGN
% ============================================================
%
% Target:
%
%   log1p(NRMSE)
%
% Therefore:
%
%   SHAP > 0
%       -> pushes future forecast error upward
%       -> worse forecastability
%
%   SHAP < 0
%       -> pushes future forecast error downward
%       -> better forecastability
%
%
% ============================================================
% M1 MECHANISM GROUPS
% ============================================================
%
% 1 Memory / persistence
%
%   ACF1
%   ACF6
%   ACF memory length
%   Sign persistence
%
%
% 2 Seasonal / spectral organization
%
%   ACF12
%   STL seasonality strength
%   Annual spectral power ratio
%   Seasonal-pattern stability
%   Spectral entropy
%
%
% 3 Local complexity
%
%   Permutation entropy
%
%
% 4 Recent state / nonstationarity
%
%   Recent variability
%   Recent median shift
%   Distribution shift
%
%
% ============================================================
% LOCAL GROUP SHAP
% ============================================================
%
% Signed group SHAP:
%
%   GroupSigned(i,g) =
%       sum_j in group phi(i,j)
%
% Positive:
%
%   mechanism pushes predicted future NRMSE upward.
%
%
% Absolute group attribution:
%
%   GroupAbs(i,g) =
%       sum_j in group |phi(i,j)|
%
% This measures local mechanism importance irrespective of
% direction.
%
%
% ============================================================
% GLOBAL IMPORTANCE
% ============================================================
%
% Feature:
%
%   MeanAbsSHAP_j =
%       mean_i |phi(i,j)|
%
%
% Normalized feature share:
%
%   Share_j =
%       MeanAbsSHAP_j /
%       sum_k MeanAbsSHAP_k
%
%
% Group share:
%
%   GroupShare_g =
%       sum_j in g MeanAbsSHAP_j /
%       sum_all MeanAbsSHAP
%
%
% ============================================================
% MEMORY SAFETY
% ============================================================
%
% Initial:
%
%   batch   = 5000
%   workers = 12
%
% If a genuine memory/deserialization error occurs:
%
% batch fallback:
%
%   5000 -> 2500 -> 1000 -> 500
%
% If still unsuccessful:
%
% workers:
%
%   12 -> 8 -> 4 -> 2
%
% Background, SHAP definition and samples NEVER change.
%
%
% ============================================================
% CHECKPOINT
% ============================================================
%
% Each model-year raw MAT stores:
%
%   CompletedThrough
%
% Therefore an interrupted run resumes from the first
