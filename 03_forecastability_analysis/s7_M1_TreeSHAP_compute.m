function SHAPValues = ...
    extractRegressionSHAP( ...
    fittedExplainer, ...
    nFeature, ...
    nQuery)


    if isprop( ...
            fittedExplainer, ...
            'Shapley')


        T = ...
            fittedExplainer.Shapley;


    elseif isprop( ...
            fittedExplainer, ...
            'ShapleyValues')


        T = ...
            fittedExplainer.ShapleyValues;


    else


        error( ...
            'Could not locate SHAP-value property.');

    end


    if isempty(T)

        error( ...
            'SHAP table is empty.');

    end


    variableNames = ...
        T.Properties.VariableNames;


    if ismember( ...
            'Value', ...
            variableNames)


        V = ...
            T.Value;


    elseif ismember( ...
            'ShapleyValue', ...
            variableNames)


        V = ...
            T.ShapleyValue;


    else


        V = ...
            T{:,2:end};

    end


    if iscell(V)

        V = ...
            cell2mat(V);

    end


    V = ...
        double(V);


    if size(V,1) == nFeature && ...
            size(V,2) == nQuery


        SHAPValues = ...
            V';


    elseif size(V,1) == nQuery && ...
            size(V,2) == nFeature


        SHAPValues = ...
            V;


    elseif nQuery == 1 && ...
            numel(V) == nFeature


        SHAPValues = ...
            V(:)';


    else


        error( ...
            ['Unexpected SHAP dimensions.\n', ...
             'Found    : %d x %d\n', ...
             'Features : %d\n', ...
             'Queries  : %d'], ...
            size(V,1), ...
            size(V,2), ...
            nFeature, ...
            nQuery);

    end


    if any(~isfinite(SHAPValues(:)))

        error( ...
            'Non-finite SHAP values detected.');

    end


end


