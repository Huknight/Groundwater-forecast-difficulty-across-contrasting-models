                currentWorkers);


        else


            %% ------------------------------------------------
            % Metadata
            % -------------------------------------------------

            Meta = ...
                struct();


            Meta.signature = ...
                signature;


            Meta.script_version = ...
                scriptVersion;


            Meta.created = ...
                datestr(now);


            Meta.target_model = ...
                targetModel;


            Meta.test_year = ...
                testYear;


            if isfield(ModelInfo,'train_years')

                Meta.training_years = ...
                    ModelInfo.train_years;

            else

                Meta.training_years = ...
                    unique( ...
                    forecastYear( ...
                    forecastYear < ...
                    testYear))';

            end


            Meta.target_transform = ...
                'log1p(NRMSE_Q10Q90)';


            Meta.feature_names = ...
                featureNames;


            Meta.feature_group_id = ...
                featureGroupID;


            Meta.group_names = ...
                groupNames;


            Meta.background_rows = ...
                backgroundRows;


            Meta.background_pixel_id = ...
                pixelID(backgroundRows);


            Meta.background_forecast_year = ...
                forecastYear(backgroundRows);


            Meta.background_size = ...
                backgroundSize;


            Meta.background_seed = ...
                backgroundSeed;


            Meta.background_median_KS = ...
                BackgroundAuditSummary.MedianKS;


            Meta.background_max_KS = ...
                BackgroundAuditSummary.MaxKS;


            Meta.foreground_definition = ...
                'All independent outer-test pixels';


            Meta.n_foreground = ...
                nTest;


            Meta.shap_method = ...
                'exact interventional-tree';


            Meta.n_trees = ...
                expectedNTrees;


            Meta.initial_batch_size = ...
                initialBatchSize;


            Meta.batch_fallback_sequence = ...
                batchFallbackSequence;


            Meta.initial_workers = ...
                initialWorkers;


            Meta.worker_fallback_sequence = ...
                workerFallbackSequence;


            Meta.shap_sign_interpretation = ...
                ['Positive SHAP = larger predicted ', ...
                 'log1p(NRMSE) = worse forecastability; ', ...
                 'negative SHAP = better forecastability.'];


            %% ------------------------------------------------
            % Foreground metadata/data
            % -------------------------------------------------

            TestRows = ...
                testRows;


            PixelID = ...
                pixelID(testRows);


            Lat = ...
                lat(testRows);


            Lon = ...
                lon(testRows);


            TestYear = ...
                forecastYear(testRows);


            FeatureValues = ...
                Xtest;


            ObservedLogTarget = ...
                Ylog(testRows,m);


            ObservedNRMSE = ...
                Yraw(testRows,m);


            PredictedLogTarget = ...
                predictedLog;


            BackgroundFeatureValues = ...
                Xbackground;


            %% ------------------------------------------------
            % Checkpoint variables
            % -------------------------------------------------

            Completed = ...
                false;


            CompletedThrough = ...
                0;


            CurrentBatchSize = ...
                initialBatchSize;


            CurrentWorkers = ...
                initialWorkers;


            SuccessfulBatchCount = ...
                0;


            ExpectedValue = ...
                NaN;


            TreeIntercepts = ...
                NaN(expectedNTrees,1);


            TotalRuntimeMinutes = ...
                NaN;


            %% ------------------------------------------------
            % Batch log arrays
            % -------------------------------------------------

            BatchStart = ...
                NaN(maxBatchRecords,1);


            BatchEnd = ...
                NaN(maxBatchRecords,1);


            BatchSizeUsed = ...
                NaN(maxBatchRecords,1);


            BatchWorkersUsed = ...
                NaN(maxBatchRecords,1);


            BatchRuntimeMinutes = ...
                NaN(maxBatchRecords,1);


            BatchMaxAdditivityResidual = ...
                NaN(maxBatchRecords,1);


            BatchMeanAdditivityResidual = ...
                NaN(maxBatchRecords,1);


            BatchInterceptDifference = ...
                NaN(maxBatchRecords,1);


            save( ...
                rawFile, ...
                'Meta', ...
                'TestRows', ...
                'PixelID', ...
                'Lat', ...
                'Lon', ...
                'TestYear', ...
                'FeatureValues', ...
                'ObservedLogTarget', ...
                'ObservedNRMSE', ...
                'PredictedLogTarget', ...
                'BackgroundFeatureValues', ...
                'Completed', ...
                'CompletedThrough', ...
                'CurrentBatchSize', ...
                'CurrentWorkers', ...
                'SuccessfulBatchCount', ...
                'ExpectedValue', ...
                'TreeIntercepts', ...
                'TotalRuntimeMinutes', ...
                'BatchStart', ...
                'BatchEnd', ...
                'BatchSizeUsed', ...
                'BatchWorkersUsed', ...
                'BatchRuntimeMinutes', ...
                'BatchMaxAdditivityResidual', ...
                'BatchMeanAdditivityResidual', ...
                'BatchInterceptDifference', ...
                '-v7.3');


            %% ------------------------------------------------
            % Preallocate large arrays in MAT file
            % -------------------------------------------------

            rawMat = ...
                matfile( ...
                rawFile, ...
                'Writable', ...
                true);


            rawMat.SHAPValues( ...
                nTest, ...
                nFeature) = ...
                0;


            rawMat.GroupSignedSHAP( ...
                nTest, ...
                nGroup) = ...
                0;


            rawMat.GroupAbsAttribution( ...
                nTest, ...
                nGroup) = ...
                0;


            completedThrough = ...
                0;


            currentBatchSize = ...
                initialBatchSize;


            currentWorkers = ...
                initialWorkers;


            successfulBatchCount = ...
                0;

        end


        %% ====================================================
        % 15.3.5 FORMAL BATCH LOOP
        % ====================================================

        rawMat = ...
            matfile( ...
            rawFile, ...
            'Writable', ...
            true);


        ensureParallelPool( ...
            currentWorkers);


        while completedThrough < nTest


            firstIndex = ...
                completedThrough + ...
                1;


            finalIndex = ...
                min( ...
                completedThrough + ...
                currentBatchSize, ...
                nTest);


            localIndex = ...
                firstIndex:finalIndex;


            Xbatch = ...
                Xtest(localIndex,:);


            predictedBatch = ...
                predictedLog(localIndex);


            fprintf('\n');
            fprintf( ...
                ['Batch attempt | pixels %d-%d/%d | ', ...
                 'N=%d | workers=%d\n'], ...
                firstIndex, ...
                finalIndex, ...
                nTest, ...
                numel(localIndex), ...
                currentWorkers);


            %% ------------------------------------------------
            % Try current computational configuration
            % -------------------------------------------------

            try


                ensureParallelPool( ...
                    currentWorkers);


                [ ...
                    batchSHAP, ...
                    batchIntercept, ...
                    treeInterceptsThisBatch, ...
                    methodAudit, ...
                    batchRuntimeMinutes] = ...
                    computeEnsembleTreeSHAP( ...
                    Trees, ...
                    Xbackground, ...
                    Xbatch, ...
                    supportsNumObservationsToSample);


                %% --------------------------------------------
                % Native Tree-SHAP audit
                % ---------------------------------------------

                if ~methodAudit.AllInterventionalTree

                    error( ...
                        ['At least one tree did not use ', ...
                         'interventional-tree SHAP.']);

                end


                if methodAudit.NumberInterventionalTree ~= ...
                        expectedNTrees

                    error( ...
                        'Tree-SHAP method count mismatch.');

                end


                %% --------------------------------------------
                % Additivity
                % ---------------------------------------------

                reconstructedBatch = ...
                    batchIntercept + ...
                    sum( ...
                    batchSHAP, ...
                    2);


                residual = ...
                    predictedBatch - ...
                    reconstructedBatch;


                meanResidual = ...
                    mean( ...
                    abs(residual));


                maxResidual = ...
                    max( ...
                    abs(residual));


                if maxResidual > ...
                        additivityTolerance

                    error( ...
                        ['Tree-SHAP additivity failed.\n', ...
                         'Max residual = %.12g'], ...
                        maxResidual);

                end


                %% --------------------------------------------
                % Intercept consistency across batches
                % ---------------------------------------------

                if successfulBatchCount == 0


                    expectedValueReference = ...
                        batchIntercept;


                    treeInterceptReference = ...
                        treeInterceptsThisBatch;


                    rawMat.ExpectedValue = ...
                        expectedValueReference;


                    rawMat.TreeIntercepts = ...
                        treeInterceptReference;


                    interceptDifference = ...
                        0;


                else


                    expectedValueReference = ...
                        rawMat.ExpectedValue;


                    treeInterceptReference = ...
                        rawMat.TreeIntercepts;


                    interceptDifference = ...
                        abs( ...
                        batchIntercept - ...
                        expectedValueReference);


                    treeInterceptDifference = ...
                        max( ...
                        abs( ...
                        treeInterceptsThisBatch - ...
                        treeInterceptReference));


                    if interceptDifference > ...
                            interceptTolerance

                        error( ...
                            ['Ensemble SHAP intercept changed ', ...
                             'across batches.\nDifference = %.12g'], ...
                            interceptDifference);

                    end


                    if treeInterceptDifference > ...
                            interceptTolerance

                        error( ...
                            ['Tree intercepts changed across ', ...
                             'batches.\nMax difference = %.12g'], ...
                            treeInterceptDifference);

                    end

                end


                %% --------------------------------------------
                % Local mechanism aggregation
                % ---------------------------------------------

                [ ...
                    groupSignedBatch, ...
                    groupAbsBatch] = ...
                    computeLocalGroups( ...
                    batchSHAP, ...
                    featureGroupID, ...
                    nGroup);


                %% --------------------------------------------
                % WRITE RAW DATA IMMEDIATELY
                % ---------------------------------------------

                rawMat.SHAPValues( ...
                    localIndex, ...
                    :) = ...
                    batchSHAP;


                rawMat.GroupSignedSHAP( ...
                    localIndex, ...
                    :) = ...
                    groupSignedBatch;


                rawMat.GroupAbsAttribution( ...
                    localIndex, ...
                    :) = ...
                    groupAbsBatch;


                %% --------------------------------------------
                % Update successful batch log
                % ---------------------------------------------

                successfulBatchCount = ...
                    successfulBatchCount + ...
                    1;


                if successfulBatchCount > ...
                        maxBatchRecords

                    error( ...
                        ['Successful batch count exceeded ', ...
                         'preallocated batch log.']);

                end


                rawMat.BatchStart( ...
                    successfulBatchCount,1) = ...
                    firstIndex;


                rawMat.BatchEnd( ...
                    successfulBatchCount,1) = ...
                    finalIndex;


                rawMat.BatchSizeUsed( ...
                    successfulBatchCount,1) = ...
                    numel(localIndex);


                rawMat.BatchWorkersUsed( ...
                    successfulBatchCount,1) = ...
                    currentWorkers;


                rawMat.BatchRuntimeMinutes( ...
                    successfulBatchCount,1) = ...
                    batchRuntimeMinutes;


                rawMat.BatchMaxAdditivityResidual( ...
                    successfulBatchCount,1) = ...
                    maxResidual;


                rawMat.BatchMeanAdditivityResidual( ...
                    successfulBatchCount,1) = ...
                    meanResidual;


                rawMat.BatchInterceptDifference( ...
                    successfulBatchCount,1) = ...
                    interceptDifference;


                %% --------------------------------------------
                % Checkpoint
                % ---------------------------------------------

                completedThrough = ...
                    finalIndex;


                rawMat.CompletedThrough = ...
                    completedThrough;


                rawMat.CurrentBatchSize = ...
                    currentBatchSize;


                rawMat.CurrentWorkers = ...
                    currentWorkers;


                rawMat.SuccessfulBatchCount = ...
                    successfulBatchCount;


                fprintf( ...
                    ['SUCCESS | %.3f min | ', ...
                     'max residual %.3e | ', ...
                     'completed %d/%d (%.1f%%)\n'], ...
                    batchRuntimeMinutes, ...
                    maxResidual, ...
                    completedThrough, ...
                    nTest, ...
                    100 * ...
                    completedThrough / ...
                    nTest);


                clear batchSHAP ...
                    groupSignedBatch ...
                    groupAbsBatch ...
                    treeInterceptsThisBatch;


            catch ME


                %% --------------------------------------------
                % Only computational-memory problems trigger
                % automatic fallback.
                %
                % Scientific / mathematical errors are thrown.
                % ---------------------------------------------

                if ~isMemoryRelatedError(ME)

                    rethrow(ME);

                end


                fprintf('\n');
                fprintf('!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!\n');
                fprintf('MEMORY-RELATED TREE-SHAP FAILURE\n');
                fprintf('Pixels  : %d-%d\n', ...
                    firstIndex, ...
                    finalIndex);
                fprintf('Batch   : %d\n', ...
                    currentBatchSize);
                fprintf('Workers : %d\n', ...
                    currentWorkers);
                fprintf('Error:\n%s\n', ...
                    ME.message);
                fprintf('!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!\n');


                %% Clear failed parallel state.

                deleteCurrentPool();


                %% --------------------------------------------
                % First reduce query batch
                % ---------------------------------------------

                nextBatchSize = ...
                    nextSmallerValue( ...
                    currentBatchSize, ...
                    batchFallbackSequence);


                if ~isnan(nextBatchSize)


                    currentBatchSize = ...
                        nextBatchSize;


                    rawMat.CurrentBatchSize = ...
                        currentBatchSize;


                    fprintf( ...
                        ['Retrying same unfinished pixels ', ...
                         'with batch size %d.\n'], ...
                        currentBatchSize);


                    ensureParallelPool( ...
                        currentWorkers);


                    continue

                end


                %% --------------------------------------------
                % Then reduce worker count
                % ---------------------------------------------

                nextWorkers = ...
                    nextSmallerValue( ...
                    currentWorkers, ...
                    workerFallbackSequence);


                if ~isnan(nextWorkers)


                    currentWorkers = ...
                        nextWorkers;


                    rawMat.CurrentWorkers = ...
                        currentWorkers;


                    %% Once worker count is reduced, reset the
                    % batch to a conservative 1000 if possible.

                    currentBatchSize = ...
                        min( ...
                        1000, ...
                        currentBatchSize);


                    currentBatchSize = ...
                        max( ...
                        minimumBatchSize, ...
                        currentBatchSize);


                    rawMat.CurrentBatchSize = ...
                        currentBatchSize;


                    fprintf( ...
                        ['Retrying with %d workers and ', ...
                         'batch size %d.\n'], ...
                        currentWorkers, ...
                        currentBatchSize);


                    ensureParallelPool( ...
                        currentWorkers);


                    continue

                end


                %% No safe fallback remains.

                fprintf('\nNo further memory fallback is available.\n');

                rethrow(ME);

            end

        end


        %% ====================================================
        % 15.3.6 COMPLETE MODEL-YEAR
        % ====================================================

        Completed = ...
            true;


        completedBatchRuntime = ...
            rawMat.BatchRuntimeMinutes( ...
            1:successfulBatchCount, ...
            1);


        TotalRuntimeMinutes = ...
            sum( ...
            completedBatchRuntime, ...
            'omitnan');


        rawMat.Completed = ...
            Completed;


        rawMat.TotalRuntimeMinutes = ...
            TotalRuntimeMinutes;


        fprintf('\n');
        fprintf('------------------------------------------------------------\n');
        fprintf('COMPLETED %s / %d\n', ...
            targetModel, ...
            testYear);
        fprintf('Successful batches : %d\n', ...
            successfulBatchCount);
        fprintf('SHAP runtime        : %.2f min\n', ...
            TotalRuntimeMinutes);
        fprintf('Final batch size    : %d\n', ...
            currentBatchSize);
        fprintf('Final workers       : %d\n', ...
            currentWorkers);
        fprintf('------------------------------------------------------------\n');


        %% ====================================================
        % 15.3.7 GLOBAL FEATURE / GROUP SUMMARY
        % ====================================================

        [featureTable,groupTable] = ...
            summarizeCompletedRawFile( ...
            rawFile, ...
            testYear, ...
            targetModel, ...
            featureNames, ...
            featureGroupID, ...
            groupNames);


        FeatureSummaryCell{modelYearCounter} = ...
            featureTable;


        GroupSummaryCell{modelYearCounter} = ...
            groupTable;


        RuntimeSummaryCell{modelYearCounter} = ...
            loadRuntimeSummary( ...
            rawFile, ...
            testYear, ...
            targetModel);


        writetable( ...
            featureTable, ...
            fullfile( ...
            summaryFolder, ...
            sprintf( ...
            'M1_TreeSHAP_Features_%d_%s.csv', ...
            testYear, ...
            safeModel)));


        writetable( ...
            groupTable, ...
            fullfile( ...
            summaryFolder, ...
            sprintf( ...
            'M1_TreeSHAP_Groups_%d_%s.csv', ...
            testYear, ...
            safeModel)));


        %% ====================================================
        % 15.3.8 PRINT TOP FEATURES / GROUPS
        % ====================================================

        featurePrint = ...
            sortrows( ...
            featureTable, ...
            'NormalizedShare', ...
            'descend');


        fprintf('\nTop five SHAP features:\n');

        disp( ...
            featurePrint( ...
            1:min(5,height(featurePrint)), ...
            { ...
            'FeatureName', ...
            'MeanAbsSHAP', ...
            'NormalizedShare'}));


        groupPrint = ...
            sortrows( ...
            groupTable, ...
            'NormalizedGroupShare', ...
            'descend');


        fprintf('\nMechanism groups:\n');

        disp( ...
            groupPrint(:, ...
            { ...
            'MechanismGroup', ...
            'NormalizedGroupShare', ...
            'MeanAbsoluteAttributionPerFeature'}));


        %% ====================================================
        % 15.3.9 CLEAR MODEL BEFORE NEXT TARGET
        % ====================================================

        clear CompactRF ...
            Trees ...
            predictedLog ...
            savedPrediction;

    end

end


