    backgroundRows, ...
    AuditTable, ...
    AuditSummary] = ...
    getOrCreateFormalBackground( ...
    backgroundFile, ...
    X, ...
    forecastYear, ...
    featureNames, ...
    testYear, ...
    backgroundSize, ...
    backgroundSeed)


    trainRows = ...
        find( ...
        forecastYear < ...
        testYear);


    XtrainFull = ...
        X(trainRows,:);


    if exist(backgroundFile,'file')


        S = ...
            load( ...
            backgroundFile, ...
            'Background');


        if ~isfield(S,'Background')

            error( ...
                ['Existing background file does not ', ...
                 'contain Background:\n%s'], ...
                backgroundFile);

        end


        Background = ...
            S.Background;


        if Background.test_year ~= ...
                testYear

            error( ...
                'Background test-year mismatch.');

        end


        if Background.background_size ~= ...
                backgroundSize

            error( ...
                'Background-size mismatch.');

        end


        if Background.seed ~= ...
                backgroundSeed

            error( ...
                'Background-seed mismatch.');

        end


        backgroundRows = ...
            Background.rows;


        if numel(backgroundRows) ~= ...
                backgroundSize

            error( ...
                'Existing background row count mismatch.');

        end


        if any( ...
                forecastYear(backgroundRows) >= ...
                testYear)

            error( ...
                ['Existing background contains ', ...
                 'non-training observations.']);

        end


        [AuditTable,AuditSummary] = ...
            auditBackgroundRepresentativeness( ...
            XtrainFull, ...
            X(backgroundRows,:), ...
            featureNames);


        fprintf( ...
            'Loaded existing fixed background:\n%s\n', ...
            backgroundFile);


    else


        backgroundRows = ...
            selectStratifiedBackgroundRows( ...
            forecastYear, ...
            testYear, ...
            backgroundSize, ...
            backgroundSeed);


        [AuditTable,AuditSummary] = ...
            auditBackgroundRepresentativeness( ...
            XtrainFull, ...
            X(backgroundRows,:), ...
            featureNames);


        Background = ...
            struct();


        Background.test_year = ...
            testYear;


        Background.background_size = ...
            backgroundSize;


        Background.seed = ...
            backgroundSeed;


        Background.rows = ...
            backgroundRows;


        Background.forecast_year = ...
            forecastYear(backgroundRows);


        Background.feature_values = ...
            X(backgroundRows,:);


        Background.audit_table = ...
            AuditTable;


        Background.audit_summary = ...
            AuditSummary;


        Background.created = ...
            datestr(now);


        save( ...
            backgroundFile, ...
            'Background', ...
            '-v7.3');


        fprintf( ...
            'Created fixed background:\n%s\n', ...
            backgroundFile);

    end


end


function [ ...
    EnsembleSHAP, ...
    EnsembleIntercept, ...
    TreeIntercept, ...
    MethodAudit, ...
    RuntimeMinutes] = ...
    computeEnsembleTreeSHAP( ...
    Trees, ...
    Xbackground, ...
    Xquery, ...
    supportsNumObservationsToSample)


    nTrees = ...
        numel(Trees);


    nQuery = ...
        size(Xquery,1);


    nFeature = ...
        size(Xquery,2);


    %% --------------------------------------------------------
    % Temporary per-tree values.
    %
    % For Nquery = 5000:
    %
    % 5000 x 13 x 500 doubles ~= 260 MB on client.
    %
    % This was selected based on the preceding optimization.
    % ---------------------------------------------------------

    TreeSHAP = ...
        NaN( ...
        nQuery, ...
        nFeature, ...
        nTrees);


    TreeIntercept = ...
        NaN(nTrees,1);


    TreeMethod = ...
        strings(nTrees,1);


    timerAll = ...
        tic;


    parfor t = 1:nTrees


        thisTree = ...
            Trees{t};


        %% ----------------------------------------------------
        % IMPORTANT:
        %
        % NO MaxNumSubsets.
        %
        % This preserves native exact Tree SHAP.
        % -----------------------------------------------------

        if supportsNumObservationsToSample


            explainer = ...
                shapley( ...
                thisTree, ...
                Xbackground, ...
                'Method', ...
                'interventional', ...
                'NumObservationsToSample', ...
                'all');


        else


            %% R2024a path used by the current machine.

            explainer = ...
                shapley( ...
                thisTree, ...
                Xbackground, ...
                'Method', ...
                'interventional');

        end


        %% Parallelism already occurs across trees.
        %
        % Never create nested SHAP parallelism here.

        fitted = ...
            fit( ...
            explainer, ...
            Xquery, ...
            'Method', ...
            'interventional', ...
            'UseParallel', ...
            false);


        TreeSHAP(:,:,t) = ...
            extractRegressionSHAP( ...
            fitted, ...
