%% Step 4: Diagnose NRMSE targets before RF meta-model training
% File name:
%   s4_target_diagnostics.m
%
% Purpose:
%   Diagnose the distribution of the 9 model-specific forecastability
%   targets before RF meta-model training.
%
% Target:
%   Master.nrmse_q10q90
%
% Compare:
%   1. Raw target:
%          y = NRMSE_Q10Q90
%
%   2. Log-transformed target:
%          y_log = log1p(NRMSE_Q10Q90)
%
% Main diagnostics:
%   - finite sample count
%   - mean / std
%   - median
%   - P1 / P5 / P25 / P75 / P95 / P99 / P99.5 / P99.9 / max
%   - skewness
%   - kurtosis
%   - P99 / median ratio
%   - extreme-target frequencies
%   - year-specific distributions
%   - raw vs log1p histograms
%
% IMPORTANT:
%   This script is diagnostic only.
%   It does NOT modify the master database and does NOT decide the
%   final RF target automatically.
%
% Input:
%   E:\P1_SKLGB\M_manuscript2\s3_analysis\
%   s1_master_database_pixel_year.mat
%
% Output:
%   E:\P1_SKLGB\M_manuscript2\s3_analysis\
%   s4_target_diagnostics.mat

clc;
clearvars;
close all;

%% ===================== Paths =====================

analysisFolder = ...
    'E:\P1_SKLGB\M_manuscript2\s3_analysis\';

masterFile = fullfile( ...
    analysisFolder, ...
    's1_master_database_pixel_year.mat');

outFile = fullfile( ...
    analysisFolder, ...
    's4_target_diagnostics.mat');

%% ===================== Check input =====================

if ~exist(masterFile, 'file')

    error( ...
        'Master database not found:\n%s', ...
        masterFile);

end

%% ===================== Load Master =====================

fprintf('Loading master forecast-performance database...\n');

S = load( ...
    masterFile, ...
    'Master');

if ~isfield(S, 'Master')

    error( ...
        'Master variable not found in:\n%s', ...
        masterFile);

end

Master = S.Master;

clear S;

requiredFields = { ...
    'pixel_id', ...
    'forecast_year', ...
    'model_names', ...
    'nrmse_q10q90'};

for k = 1:numel(requiredFields)

    if ~isfield(Master, requiredFields{k})

        error( ...
            'Master is missing required field: %s', ...
            requiredFields{k});

    end

end

%% ===================== Extract data =====================

Y = ...
    double(Master.nrmse_q10q90);

forecastYear = ...
    double(Master.forecast_year(:));

pixelID = ...
    double(Master.pixel_id(:));

modelNames = ...
    Master.model_names;

[nSample, nModel] = ...
    size(Y);

forecastYears = ...
    unique(forecastYear)';

nYear = ...
    numel(forecastYears);

if nModel ~= 9

    error( ...
        'Expected 9 models, but found %d.', ...
        nModel);

end

if numel(forecastYear) ~= nSample

    error( ...
        'forecast_year length is inconsistent with target matrix.');

end

fprintf('Samples : %d\n', nSample);
fprintf('Models  : %d\n', nModel);
fprintf('Years   : %s\n', mat2str(forecastYears));

%% ===================== Basic target validation =====================

fprintf('\nChecking target validity...\n');

for m = 1:nModel

    y = ...
        Y(:, m);

    nNegative = ...
        sum(y < 0 & isfinite(y));

    if nNegative > 0

        error( ...
            '%s contains %d negative NRMSE values.', ...
            modelNames{m}, ...
            nNegative);

    end

end

fprintf('No negative NRMSE values detected.\n');

%% ============================================================
%  PART 1
%  Overall RAW target diagnostics
% ============================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf('RAW NRMSE TARGET DIAGNOSTICS: 2019-2024\n');
fprintf('============================================================\n');

pctLevels = [ ...
    0, ...
    0.1, ...
    0.5, ...
    1, ...
    5, ...
    25, ...
    50, ...
    75, ...
    95, ...
    99, ...
    99.5, ...
    99.9, ...
    100];

nPct = ...
    numel(pctLevels);

RawPct = ...
    NaN(nModel, nPct);

RawMean = ...
    NaN(nModel, 1);

RawStd = ...
    NaN(nModel, 1);

RawSkewness = ...
    NaN(nModel, 1);

RawKurtosis = ...
    NaN(nModel, 1);

RawFiniteN = ...
    zeros(nModel, 1);

RawP99MedianRatio = ...
    NaN(nModel, 1);

for m = 1:nModel

    y = ...
        Y(:, m);

    y = ...
        y(isfinite(y));

    RawFiniteN(m) = ...
        numel(y);

    RawPct(m, :) = ...
        prctile( ...
        y, ...
        pctLevels);

    RawMean(m) = ...
        mean(y);

    RawStd(m) = ...
        std(y);

    RawSkewness(m) = ...
        skewness(y);

    RawKurtosis(m) = ...
        kurtosis(y);

    medY = ...
        median(y);

    p99Y = ...
        prctile(y, 99);

    if medY > 0

        RawP99MedianRatio(m) = ...
            p99Y / medY;

    end

end

%% ----- Compact RAW summary -----

fprintf('\n');

fprintf( ...
    ['%-8s %8s %9s %9s %9s %9s %9s ', ...
     '%9s %9s %9s %9s\n'], ...
    'Model', ...
    'N', ...
    'Mean', ...
    'Median', ...
    'P95', ...
    'P99', ...
    'P99.5', ...
    'P99.9', ...
    'Max', ...
    'Skew', ...
    'Kurt');

fprintf('%s\n', repmat('-', 1, 110));

for m = 1:nModel

    fprintf( ...
        ['%-8s %8d %9.4f %9.4f %9.4f %9.4f ', ...
         '%9.4f %9.4f %9.4f %9.3f %9.3f\n'], ...
        modelNames{m}, ...
        RawFiniteN(m), ...
        RawMean(m), ...
        RawPct(m, pctLevels == 50), ...
        RawPct(m, pctLevels == 95), ...
        RawPct(m, pctLevels == 99), ...
        RawPct(m, pctLevels == 99.5), ...
        RawPct(m, pctLevels == 99.9), ...
        RawPct(m, pctLevels == 100), ...
        RawSkewness(m), ...
        RawKurtosis(m));

end

%% ============================================================
%  PART 2
%  Detailed raw percentiles
% ============================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf('DETAILED RAW NRMSE PERCENTILES\n');
fprintf('============================================================\n');

for m = 1:nModel

    fprintf('\n%s\n', modelNames{m});

    for p = 1:nPct

        fprintf( ...
            '  P%-6g = %12.6f\n', ...
            pctLevels(p), ...
            RawPct(m, p));

    end

    fprintf( ...
        '  Mean            = %12.6f\n', ...
        RawMean(m));

    fprintf( ...
        '  Std             = %12.6f\n', ...
        RawStd(m));

    fprintf( ...
        '  Skewness        = %12.6f\n', ...
        RawSkewness(m));

    fprintf( ...
        '  Kurtosis        = %12.6f\n', ...
        RawKurtosis(m));

    fprintf( ...
        '  P99 / Median    = %12.6f\n', ...
        RawP99MedianRatio(m));

end

%% ============================================================
%  PART 3
%  Extreme-target frequencies
% ============================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf('RAW NRMSE EXTREME-VALUE FREQUENCIES\n');
fprintf('============================================================\n');

thresholds = [ ...
    0.5, ...
    0.75, ...
    1.0, ...
    1.5, ...
    2.0, ...
    3.0, ...
    5.0];

ExtremePct = ...
    NaN(nModel, numel(thresholds));

for m = 1:nModel

    y = ...
        Y(:, m);

    valid = ...
        isfinite(y);

    y = ...
        y(valid);

    fprintf('\n%s\n', modelNames{m});

    for t = 1:numel(thresholds)

        threshold = ...
            thresholds(t);

        nExtreme = ...
            sum(y > threshold);

        pctExtreme = ...
            100 * nExtreme / numel(y);

        ExtremePct(m, t) = ...
            pctExtreme;

        fprintf( ...
            '  NRMSE > %-5.2f : %6d / %6d = %7.3f%%\n', ...
            threshold, ...
            nExtreme, ...
            numel(y), ...
            pctExtreme);

    end

end

%% ============================================================
%  PART 4
%  log1p target diagnostics
% ============================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf('LOG1P(NRMSE) TARGET DIAGNOSTICS: 2019-2024\n');
fprintf('============================================================\n');

Ylog = ...
    log1p(Y);

LogPct = ...
    NaN(nModel, nPct);

LogMean = ...
    NaN(nModel, 1);

LogStd = ...
    NaN(nModel, 1);

LogSkewness = ...
    NaN(nModel, 1);

LogKurtosis = ...
    NaN(nModel, 1);

for m = 1:nModel

    y = ...
        Ylog(:, m);

    y = ...
        y(isfinite(y));

    LogPct(m, :) = ...
        prctile( ...
        y, ...
        pctLevels);

    LogMean(m) = ...
        mean(y);

    LogStd(m) = ...
        std(y);

    LogSkewness(m) = ...
        skewness(y);

    LogKurtosis(m) = ...
        kurtosis(y);

end

fprintf('\n');

fprintf( ...
    ['%-8s %10s %10s %10s %10s %10s ', ...
     '%10s %10s\n'], ...
    'Model', ...
    'Mean', ...
    'Median', ...
    'P95', ...
    'P99', ...
    'Max', ...
    'Skew', ...
    'Kurt');

fprintf('%s\n', repmat('-', 1, 92));

for m = 1:nModel

    fprintf( ...
        ['%-8s %10.4f %10.4f %10.4f %10.4f ', ...
         '%10.4f %10.3f %10.3f\n'], ...
        modelNames{m}, ...
        LogMean(m), ...
        LogPct(m, pctLevels == 50), ...
        LogPct(m, pctLevels == 95), ...
        LogPct(m, pctLevels == 99), ...
        LogPct(m, pctLevels == 100), ...
        LogSkewness(m), ...
        LogKurtosis(m));

end

%% ============================================================
%  PART 5
%  Direct raw vs log comparison
% ============================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf('RAW VS LOG1P DISTRIBUTION COMPARISON\n');
fprintf('============================================================\n');

fprintf('\n');

fprintf( ...
    ['%-8s %10s %10s %12s %12s %12s\n'], ...
    'Model', ...
    'RawSkew', ...
    'LogSkew', ...
    'RawKurt', ...
    'LogKurt', ...
    'SkewReduce');

fprintf('%s\n', repmat('-', 1, 72));

SkewReduction = ...
    NaN(nModel, 1);

for m = 1:nModel

    if RawSkewness(m) ~= 0

        SkewReduction(m) = ...
            100 * ...
            ( ...
            abs(RawSkewness(m)) - ...
            abs(LogSkewness(m)) ...
            ) / ...
            abs(RawSkewness(m));

    end

    fprintf( ...
        '%-8s %10.3f %10.3f %12.3f %12.3f %11.1f%%\n', ...
        modelNames{m}, ...
        RawSkewness(m), ...
        LogSkewness(m), ...
        RawKurtosis(m), ...
        LogKurtosis(m), ...
        SkewReduction(m));

end

%% ============================================================
%  PART 6
%  Year-specific raw target diagnostics
% ============================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf('YEAR-SPECIFIC RAW NRMSE DISTRIBUTIONS\n');
fprintf('============================================================\n');

YearMean = ...
    NaN(nYear, nModel);

YearMedian = ...
    NaN(nYear, nModel);

YearP95 = ...
    NaN(nYear, nModel);

YearP99 = ...
    NaN(nYear, nModel);

YearSkewness = ...
    NaN(nYear, nModel);

for yi = 1:nYear

    thisYear = ...
        forecastYears(yi);

    yearMask = ...
        forecastYear == thisYear;

    fprintf('\nForecast year %d\n', thisYear);

    fprintf( ...
        '%-8s %10s %10s %10s %10s %10s\n', ...
        'Model', ...
        'Mean', ...
        'Median', ...
        'P95', ...
        'P99', ...
        'Skew');

    for m = 1:nModel

        y = ...
            Y(yearMask, m);

        y = ...
            y(isfinite(y));

        YearMean(yi, m) = ...
            mean(y);

        YearMedian(yi, m) = ...
            median(y);

        YearP95(yi, m) = ...
            prctile(y, 95);

        YearP99(yi, m) = ...
            prctile(y, 99);

        YearSkewness(yi, m) = ...
            skewness(y);

        fprintf( ...
            '%-8s %10.4f %10.4f %10.4f %10.4f %10.3f\n', ...
            modelNames{m}, ...
            YearMean(yi, m), ...
            YearMedian(yi, m), ...
            YearP95(yi, m), ...
            YearP99(yi, m), ...
            YearSkewness(yi, m));

    end

end

%% ============================================================
%  PART 7
%  Year-specific log1p target diagnostics
% ============================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf('YEAR-SPECIFIC LOG1P(NRMSE) SKEWNESS\n');
fprintf('============================================================\n');

YearLogSkewness = ...
    NaN(nYear, nModel);

fprintf('\n%-8s', 'Year');

for m = 1:nModel

    fprintf( ...
        '%10s', ...
        modelNames{m});

end

fprintf('\n');

for yi = 1:nYear

    thisYear = ...
        forecastYears(yi);

    yearMask = ...
        forecastYear == thisYear;

    fprintf( ...
        '%-8d', ...
        thisYear);

    for m = 1:nModel

        y = ...
            Ylog(yearMask, m);

        y = ...
            y(isfinite(y));

        YearLogSkewness(yi, m) = ...
            skewness(y);

        fprintf( ...
            '%10.3f', ...
            YearLogSkewness(yi, m));

    end

    fprintf('\n');

end

%% ============================================================
%  PART 8
%  Identify largest target values
% ============================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf('TOP 10 RAW NRMSE CASES FOR EACH MODEL\n');
fprintf('============================================================\n');

TopCases = ...
    cell(nModel, 1);

for m = 1:nModel

    y = ...
        Y(:, m);

    [sortedY, idx] = ...
        sort( ...
        y, ...
        'descend', ...
        'MissingPlacement', ...
        'last');

    nShow = ...
        min(10, sum(isfinite(y)));

    idx = ...
        idx(1:nShow);

    sortedY = ...
        sortedY(1:nShow);

    TopCases{m} = ...
        table( ...
        pixelID(idx), ...
        forecastYear(idx), ...
        sortedY, ...
        'VariableNames', ...
        {'PixelID', 'ForecastYear', 'NRMSE'});

    fprintf('\n%s\n', modelNames{m});

    fprintf( ...
        '%5s %8s %8s %12s\n', ...
        'Rank', ...
        'Pixel', ...
        'Year', ...
        'NRMSE');

    for k = 1:nShow

        fprintf( ...
            '%5d %8d %8d %12.4f\n', ...
            k, ...
            pixelID(idx(k)), ...
            forecastYear(idx(k)), ...
            sortedY(k));

    end

end

%% ============================================================
%  PART 9
%  RAW target distribution figure
% ============================================================

fprintf('\nCreating target-distribution figures...\n');

figure( ...
    'Name', ...
    'Raw NRMSE target distributions', ...
    'Color', ...
    'w', ...
    'Position', ...
    [100 50 1500 900]);

tiledlayout( ...
    3, ...
    3, ...
    'TileSpacing', ...
    'compact', ...
    'Padding', ...
    'compact');

for m = 1:nModel

    nexttile;

    y = ...
        Y(:, m);

    y = ...
        y(isfinite(y));

    % Display central 99.8% so extreme tails do not destroy visibility.
    displayLimit = ...
        prctile(y, 99.8);

    yDisplay = ...
        y(y <= displayLimit);

    histogram( ...
        yDisplay, ...
        70);

    hold on;

    xline( ...
        median(y), ...
        '--', ...
        'Median');

    xline( ...
        mean(y), ...
        ':', ...
        'Mean');

    hold off;

    xlabel('NRMSE_{Q10-Q90}');
    ylabel('Samples');

    title( ...
        sprintf( ...
        '%s | skew = %.2f', ...
        modelNames{m}, ...
        RawSkewness(m)), ...
        'Interpreter', ...
        'none');

    box on;

end

sgtitle( ...
    'Raw NRMSE target distributions (display truncated at P99.8)');

